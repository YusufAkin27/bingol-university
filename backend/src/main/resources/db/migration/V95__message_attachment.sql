-- T8: sohbet gorselleri. Mesaj tablosuna DOKUNULMAZ; ekler ayri tabloda tutulur.
-- Gorsel baytlari veritabaninda degil, ozel depoda (sifreli) durur; burada yalnizca anahtar ve meta veri vardir.
-- message_id NULL = yuklendi ama henuz bir mesaja baglanmadi (24 saat sonra temizlenir).

CREATE TABLE message_attachment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT       NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    uploader_id     BIGINT       NOT NULL REFERENCES app_user (id),
    message_id      BIGINT       REFERENCES message (id) ON DELETE CASCADE,
    kind            VARCHAR(16)  NOT NULL DEFAULT 'IMAGE',
    storage_key     VARCHAR(80)  NOT NULL,
    thumb_key       VARCHAR(80)  NOT NULL,
    width           INTEGER      NOT NULL,
    height          INTEGER      NOT NULL,
    bytes           BIGINT       NOT NULL,
    content_type    VARCHAR(40)  NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Moderasyon "gizle": yumusak; erisim kapanir, gizleme geri alinabilir (itiraz)
    hidden_at       TIMESTAMPTZ,
    hidden_by       VARCHAR(16),
    CONSTRAINT chi95_att_kind_ck CHECK (kind IN ('IMAGE'))
);
CREATE UNIQUE INDEX chi95_att_storage_key ON message_attachment (storage_key);
CREATE INDEX chi95_att_message ON message_attachment (message_id);
CREATE INDEX chi95_att_conv ON message_attachment (conversation_id, id);
CREATE INDEX chi95_att_uploader ON message_attachment (uploader_id, created_at);
-- Baglanmamis yuklemeleri tarayan temizleyici icin kismi indeks
CREATE INDEX chi95_att_unclaimed ON message_attachment (created_at) WHERE message_id IS NULL;
