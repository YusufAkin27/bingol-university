CREATE TABLE forum_topic (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES app_user (id),
    category_id      BIGINT       NOT NULL REFERENCES forum_category (id),
    title            VARCHAR(150) NOT NULL,
    body             TEXT         NOT NULL,
    anonymous        BOOLEAN      NOT NULL DEFAULT FALSE,
    comment_count    INT          NOT NULL DEFAULT 0,
    like_count       INT          NOT NULL DEFAULT 0,
    bookmark_count   INT          NOT NULL DEFAULT 0,
    image_count      SMALLINT     NOT NULL DEFAULT 0,
    pinned_at        TIMESTAMPTZ,
    locked_at        TIMESTAMPTZ,
    status           VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    removed_reason   VARCHAR(300),
    idem_key         VARCHAR(100),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    edited_at        TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    last_activity_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fa14_topic_status_chk CHECK (status IN ('ACTIVE', 'REMOVED'))
);
CREATE INDEX fa14_topic_cat_idx ON forum_topic (category_id, id DESC) WHERE deleted_at IS NULL AND status = 'ACTIVE';
CREATE INDEX fa14_topic_user_idx ON forum_topic (user_id, id DESC) WHERE deleted_at IS NULL;
CREATE INDEX fa14_topic_activity_idx ON forum_topic (last_activity_at DESC, id DESC) WHERE deleted_at IS NULL AND status = 'ACTIVE';
CREATE INDEX fa14_topic_ncomments_idx ON forum_topic (comment_count DESC, id DESC) WHERE deleted_at IS NULL AND status = 'ACTIVE';
CREATE INDEX fa14_topic_pinned_idx ON forum_topic (pinned_at DESC) WHERE pinned_at IS NOT NULL AND deleted_at IS NULL;
-- Cift gonderim korumasi: ayni kullanici + ayni Idempotency-Key tek konu (NULL anahtarlar serbest)
CREATE UNIQUE INDEX fa14_topic_idem_uq ON forum_topic (user_id, idem_key);

CREATE TABLE forum_media (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT       NOT NULL REFERENCES app_user (id),
    storage_key  VARCHAR(300) NOT NULL,
    thumb_key    VARCHAR(300),
    content_type VARCHAR(80)  NOT NULL,
    width        INT,
    height       INT,
    bytes        BIGINT       NOT NULL DEFAULT 0,
    sha256       VARCHAR(64),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    hidden_at    TIMESTAMPTZ
);
CREATE INDEX fa14_media_owner_idx ON forum_media (owner_id, id DESC);
CREATE INDEX fa14_media_skey_idx ON forum_media (storage_key);

CREATE TABLE forum_topic_image (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT   NOT NULL REFERENCES forum_topic (id) ON DELETE CASCADE,
    media_id BIGINT   NOT NULL REFERENCES forum_media (id),
    position SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT fa14_timg_media_uq UNIQUE (media_id)
);
CREATE INDEX fa14_timg_topic_idx ON forum_topic_image (topic_id, position);

CREATE TABLE forum_topic_like (
    topic_id   BIGINT      NOT NULL REFERENCES forum_topic (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (topic_id, user_id)
);
CREATE INDEX fa14_tlike_user_idx ON forum_topic_like (user_id, created_at DESC);

CREATE TABLE forum_bookmark (
    user_id     BIGINT      NOT NULL REFERENCES app_user (id),
    target_type VARCHAR(10) NOT NULL,
    target_id   BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, target_type, target_id),
    CONSTRAINT fa14_bm_type_chk CHECK (target_type IN ('TOPIC', 'COMMENT'))
);
CREATE INDEX fa14_bm_user_idx ON forum_bookmark (user_id, created_at DESC);
CREATE INDEX fa14_bm_target_idx ON forum_bookmark (target_type, target_id);

-- follow=TRUE: konuyu takip ediyor. follow=FALSE + notify=FALSE: takip etmeyen (ornegin konu sahibi) kisinin
-- "bu konunun bildirimlerini kapat" tercihi. notify=FALSE iken takipci bildirim almaz.
CREATE TABLE forum_topic_follow (
    topic_id   BIGINT      NOT NULL REFERENCES forum_topic (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    notify     BOOLEAN     NOT NULL DEFAULT TRUE,
    follow     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (topic_id, user_id)
);
CREATE INDEX fa14_tfollow_user_idx ON forum_topic_follow (user_id, created_at DESC) WHERE follow = TRUE;

CREATE TABLE forum_anon_alias (
    topic_id BIGINT NOT NULL REFERENCES forum_topic (id) ON DELETE CASCADE,
    user_id  BIGINT NOT NULL REFERENCES app_user (id),
    n        INT    NOT NULL,
    PRIMARY KEY (topic_id, user_id),
    CONSTRAINT fa14_alias_n_uq UNIQUE (topic_id, n)
);
