-- Mesaj sifreleme altyapisi (T21 Asama 1): konusma veri anahtari (DEK) + yonetici cozme denetim kaydi

-- DEK ana anahtarla (KEK) AES-GCM ile sarili saklanir: wrapped_key = nonce(12) + sifreli anahtar + etiket.
CREATE TABLE conversation_key (
    conversation_id BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    key_version     INT         NOT NULL,
    wrapped_key     BYTEA       NOT NULL,
    master_key_id   VARCHAR(32) NOT NULL,
    active          BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_conversation_key PRIMARY KEY (conversation_id, key_version)
);
-- Konusma basina en fazla bir aktif surum
CREATE UNIQUE INDEX uq_conversation_key_active ON conversation_key (conversation_id) WHERE active;
-- Rotasyonda "hala eski anahtarla sarili olanlar" taramasi
CREATE INDEX idx_conversation_key_master ON conversation_key (master_key_id);

-- Yonetici mesaj cozme denetimi: yalnizca-ekleme. Konusma/mesaj silinse bile kayit KALIR (FK yok).
CREATE TABLE message_access_audit (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id        BIGINT       NOT NULL REFERENCES app_user (id),
    conversation_id BIGINT       NOT NULL,
    message_count   INT          NOT NULL,
    from_message_id BIGINT,
    to_message_id   BIGINT,
    reason          VARCHAR(500) NOT NULL,
    ip              VARCHAR(64),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT message_access_audit_reason_len CHECK (char_length(btrim(reason)) >= 10)
);
CREATE INDEX idx_message_access_audit_conv ON message_access_audit (conversation_id, created_at DESC);
CREATE INDEX idx_message_access_audit_admin ON message_access_audit (admin_id, created_at DESC);

CREATE FUNCTION message_access_audit_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'message_access_audit is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_message_access_audit_no_change
    BEFORE UPDATE OR DELETE ON message_access_audit
    FOR EACH ROW EXECUTE FUNCTION message_access_audit_immutable();

CREATE TRIGGER trg_message_access_audit_no_truncate
    BEFORE TRUNCATE ON message_access_audit
    FOR EACH STATEMENT EXECUTE FUNCTION message_access_audit_immutable();
