-- Kampus Forum (C alani): konu anketi. Mevcut `poll` modulunden AYRI tablolar (konuya bagli, hedef kitle/menu mantigi yok).
-- Bir konunun en fazla bir anketi vardir (topic_id UNIQUE). Oy: PK(poll_id, user_id) = kisi basina tek oy (cift oy imkansiz);
-- secenek sayaclari (vote_count) yalniz atomik UPDATE ile degisir. Oy veren kimligi hicbir uctan gosterilmez.
CREATE TABLE forum_poll (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id          BIGINT      NOT NULL REFERENCES forum_topic (id) ON DELETE CASCADE,
    question          VARCHAR(200),
    ends_at           TIMESTAMPTZ,
    allow_change_vote BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fc14_poll_topic_uq UNIQUE (topic_id)
);

CREATE TABLE forum_poll_option (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id    BIGINT       NOT NULL REFERENCES forum_poll (id) ON DELETE CASCADE,
    text       VARCHAR(80)  NOT NULL,
    position   SMALLINT     NOT NULL,
    vote_count INT          NOT NULL DEFAULT 0,
    CONSTRAINT fc14_option_count_chk CHECK (vote_count >= 0)
);
CREATE INDEX fc14_option_poll_idx ON forum_poll_option (poll_id, position);

CREATE TABLE forum_poll_vote (
    poll_id    BIGINT      NOT NULL REFERENCES forum_poll (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    option_id  BIGINT      NOT NULL REFERENCES forum_poll_option (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (poll_id, user_id)
);
-- Hesap silme ve secenek bazli sayim/FK islemleri
CREATE INDEX fc14_vote_user_idx ON forum_poll_vote (user_id);
CREATE INDEX fc14_vote_option_idx ON forum_poll_vote (option_id);
