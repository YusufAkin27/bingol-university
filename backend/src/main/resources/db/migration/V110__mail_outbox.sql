-- Mail modulu: e-posta kuyrugu (outbox). Gonderim zamanlanmis isleyiciyle yapilir.
CREATE TABLE mail_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    to_address      VARCHAR(254)  NOT NULL,
    template        VARCHAR(40)   NOT NULL,
    lang            VARCHAR(2)    NOT NULL DEFAULT 'tr',
    vars_json       VARCHAR(4000) NOT NULL DEFAULT '{}',
    status          VARCHAR(12)   NOT NULL DEFAULT 'PENDING',
    attempts        INT           NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    last_error      VARCHAR(500),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    sent_at         TIMESTAMPTZ
);

-- Isleyici yalnizca bekleyen/yeniden denenecek kayitlari tarar
CREATE INDEX mail110_due ON mail_outbox (next_attempt_at, id) WHERE status IN ('PENDING', 'FAILED');
-- Durum sayilari ve temizlik
CREATE INDEX mail110_status_created ON mail_outbox (status, created_at);
