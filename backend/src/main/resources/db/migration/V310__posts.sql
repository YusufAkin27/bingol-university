CREATE TABLE post (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id     BIGINT           NOT NULL REFERENCES app_user (id),
    body          TEXT,
    like_count    INT              NOT NULL DEFAULT 0,
    comment_count INT              NOT NULL DEFAULT 0,
    media_count   SMALLINT         NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ      NOT NULL DEFAULT now(),
    edited_at     TIMESTAMPTZ,
    deleted_at    TIMESTAMPTZ,
    deleted_by    BIGINT,
    hidden_at     TIMESTAMPTZ,
    hidden_reason VARCHAR(300),
    score         DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE INDEX post310_feed_idx ON post (created_at DESC, id DESC) WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX post310_author_idx ON post (author_id, created_at DESC);
CREATE INDEX post310_score_idx ON post (score DESC, id DESC);

CREATE TABLE post_media (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id      BIGINT REFERENCES post (id) ON DELETE CASCADE,
    owner_id     BIGINT      NOT NULL REFERENCES app_user (id),
    kind         VARCHAR(8)  NOT NULL,
    position     SMALLINT    NOT NULL DEFAULT 0,
    storage_key  VARCHAR(300) NOT NULL,
    thumb_key    VARCHAR(300),
    content_type VARCHAR(80) NOT NULL,
    width        INT,
    height       INT,
    duration_ms  INT,
    bytes        BIGINT      NOT NULL DEFAULT 0,
    sha256       VARCHAR(64),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    hidden_at    TIMESTAMPTZ,
    CONSTRAINT post310_media_kind_chk CHECK (kind IN ('IMAGE', 'VIDEO'))
);
CREATE INDEX post310_media_post_idx ON post_media (post_id, position);
CREATE INDEX post310_media_orphan_idx ON post_media (owner_id) WHERE post_id IS NULL;

CREATE TABLE post_like (
    post_id    BIGINT      NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, user_id)
);
CREATE INDEX post310_like_user_idx ON post_like (user_id, created_at DESC);

CREATE TABLE post_comment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id          BIGINT      NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    parent_id        BIGINT REFERENCES post_comment (id) ON DELETE CASCADE,
    root_id          BIGINT,
    depth            SMALLINT    NOT NULL DEFAULT 0,
    author_id        BIGINT      NOT NULL REFERENCES app_user (id),
    reply_to_user_id BIGINT,
    body             TEXT,
    reply_count      INT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    edited_at        TIMESTAMPTZ,
    deleted_at       TIMESTAMPTZ,
    deleted_by       BIGINT,
    hidden_at        TIMESTAMPTZ
);
CREATE INDEX post310_comment_post_idx ON post_comment (post_id, parent_id, created_at, id);
CREATE INDEX post310_comment_root_idx ON post_comment (root_id, created_at, id);
