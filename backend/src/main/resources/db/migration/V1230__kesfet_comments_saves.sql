-- V1230 (KS-BE2): Kesfet gonderi/reel yorumlari + yanitlar + yorum begenisi + gonderi kaydetme + kullanici arama indeksi.
-- V470 yorum/kaydet ozelligini kaldirip eski tablolari dusurmustu; kullanici karariyla geri geliyor (yeni tablolar).
-- Indeks onekleri: pcm1230_ (yorum), pcl1230_ (yorum begenisi), psv1230_ (kaydet), usr1230_ (kullanici).

ALTER TABLE post ADD COLUMN comment_count INT NOT NULL DEFAULT 0;

-- Yorum: parent_id yalniz ust duzey yorumu gosterir (en cok iki seviye: yorum + yanitlar). Yanita yanit, ust duzey
-- yoruma yassilanir; reply_to_id yanitlanan asil yorumu tutar (yorum silinse de satir kalir, "@ad" gosterimi icin).
CREATE TABLE post_comment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id       BIGINT       NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    parent_id     BIGINT REFERENCES post_comment (id) ON DELETE CASCADE,
    reply_to_id   BIGINT,
    author_id     BIGINT       NOT NULL REFERENCES app_user (id),
    body          TEXT         NOT NULL,
    like_count    INT          NOT NULL DEFAULT 0,
    reply_count   INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at    TIMESTAMPTZ,
    deleted_by    BIGINT,
    hidden_at     TIMESTAMPTZ,
    hidden_reason VARCHAR(300)
);
-- Ust duzey yorum listeleri (yeni / populer) ve yanit listesi
CREATE INDEX pcm1230_post_new_idx ON post_comment (post_id, id DESC) WHERE parent_id IS NULL AND deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX pcm1230_post_top_idx ON post_comment (post_id, like_count DESC, id DESC) WHERE parent_id IS NULL AND deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX pcm1230_parent_idx   ON post_comment (parent_id, id) WHERE parent_id IS NOT NULL;
CREATE INDEX pcm1230_author_idx   ON post_comment (author_id);

CREATE TABLE post_comment_like (
    comment_id BIGINT      NOT NULL REFERENCES post_comment (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (comment_id, user_id)
);
CREATE INDEX pcl1230_user_idx ON post_comment_like (user_id);

-- Kaydedilenler (yalniz sahibi gorur)
CREATE TABLE post_save (
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    post_id    BIGINT      NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, post_id)
);
CREATE INDEX psv1230_user_time_idx ON post_save (user_id, created_at DESC, post_id DESC);
CREATE INDEX psv1230_post_idx ON post_save (post_id);

