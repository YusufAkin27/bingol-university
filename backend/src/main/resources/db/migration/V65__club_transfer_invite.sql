CREATE TABLE club_ownership_transfer (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id   BIGINT      NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    from_user_id   BIGINT      NOT NULL,
    to_user_id     BIGINT      NOT NULL,
    keep_as_admin  BOOLEAN     NOT NULL DEFAULT TRUE,
    status         VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at     TIMESTAMPTZ NOT NULL,
    decided_at     TIMESTAMPTZ,
    CONSTRAINT ck_club_transfer_status CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'CANCELLED', 'EXPIRED'))
);
-- Kulup basina en fazla bir bekleyen teklif.
CREATE UNIQUE INDEX uq_club_transfer_pending ON club_ownership_transfer (community_id) WHERE status = 'PENDING';
CREATE INDEX idx_club_transfer_from ON club_ownership_transfer (from_user_id);
CREATE INDEX idx_club_transfer_to ON club_ownership_transfer (to_user_id);

CREATE TABLE club_invite (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT      NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    code_hash    VARCHAR(64) NOT NULL,
    code_hint    VARCHAR(8)  NOT NULL,
    created_by   BIGINT      NOT NULL,
    max_uses     INT,
    used_count   INT         NOT NULL DEFAULT 0,
    expires_at   TIMESTAMPTZ NOT NULL,
    revoked      BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_club_invite_code UNIQUE (code_hash)
);
CREATE INDEX idx_club_invite_community ON club_invite (community_id, id DESC);
CREATE INDEX idx_club_invite_creator ON club_invite (created_by);
