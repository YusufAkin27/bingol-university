-- Topluluklar, topluluk akisi, kullanici etkinlikleri, RSVP ve yoklama

CREATE TABLE community (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80)  NOT NULL,
    slug         VARCHAR(100) NOT NULL,
    description  VARCHAR(1000),
    category     VARCHAR(40),
    cover_url    VARCHAR(300),
    join_policy  VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    visibility   VARCHAR(16)  NOT NULL DEFAULT 'PUBLIC',
    status       VARCHAR(16)  NOT NULL DEFAULT 'PENDING_REVIEW',
    owner_id     BIGINT       NOT NULL REFERENCES app_user (id),
    review_note  VARCHAR(300),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_community_slug UNIQUE (slug),
    CONSTRAINT ck_community_join CHECK (join_policy IN ('OPEN', 'APPROVAL')),
    CONSTRAINT ck_community_visibility CHECK (visibility IN ('PUBLIC', 'PRIVATE')),
    CONSTRAINT ck_community_status CHECK (status IN ('PENDING_REVIEW', 'ACTIVE', 'REJECTED', 'HIDDEN'))
);
CREATE INDEX idx_community_status ON community (status, id DESC);
CREATE INDEX idx_community_owner ON community (owner_id, status);

CREATE TABLE community_member (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT      NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    user_id      BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    role         VARCHAR(16) NOT NULL DEFAULT 'MEMBER',
    status       VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_community_member UNIQUE (community_id, user_id),
    CONSTRAINT ck_member_role CHECK (role IN ('OWNER', 'MODERATOR', 'MEMBER')),
    CONSTRAINT ck_member_status CHECK (status IN ('ACTIVE', 'PENDING', 'BANNED'))
);
CREATE INDEX idx_member_user ON community_member (user_id, status);
CREATE INDEX idx_member_community ON community_member (community_id, status, id);

CREATE TABLE community_post (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT       NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    author_id    BIGINT       NOT NULL REFERENCES app_user (id),
    content      VARCHAR(2000) NOT NULL,
    image_url    VARCHAR(300),
    pinned       BOOLEAN      NOT NULL DEFAULT FALSE,
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_post_feed ON community_post (community_id, id DESC);

CREATE TABLE user_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(150) NOT NULL,
    description  VARCHAR(2000),
    starts_at    TIMESTAMPTZ  NOT NULL,
    ends_at      TIMESTAMPTZ  NOT NULL,
    location     VARCHAR(200),
    cover_url    VARCHAR(300),
    capacity     INTEGER,
    -- GOING sayisi; kapasite kontrolu kosullu UPDATE ile atomik yapilir, CHECK son savunma hattidir
    going_count  INTEGER      NOT NULL DEFAULT 0,
    community_id BIGINT       REFERENCES community (id),
    created_by   BIGINT       NOT NULL REFERENCES app_user (id),
    status       VARCHAR(16)  NOT NULL DEFAULT 'PENDING_REVIEW',
    review_note  VARCHAR(300),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_event_status CHECK (status IN ('PENDING_REVIEW', 'ACTIVE', 'REJECTED', 'CANCELLED', 'HIDDEN')),
    CONSTRAINT ck_event_dates CHECK (ends_at > starts_at),
    CONSTRAINT ck_event_capacity CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_event_going CHECK (going_count >= 0 AND (capacity IS NULL OR going_count <= capacity))
);
CREATE INDEX idx_event_status_start ON user_event (status, starts_at, id);
CREATE INDEX idx_event_community ON user_event (community_id, starts_at);
CREATE INDEX idx_event_creator ON user_event (created_by, id DESC);

CREATE TABLE event_rsvp (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      BIGINT      NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    user_id       BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    status        VARCHAR(16) NOT NULL,
    -- Hatirlatma isaretleri: ayni hatirlatma tekrar gitmesin
    reminded_day  BOOLEAN     NOT NULL DEFAULT FALSE,
    reminded_hour BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_event_rsvp UNIQUE (event_id, user_id),
    CONSTRAINT ck_rsvp_status CHECK (status IN ('GOING', 'INTERESTED'))
);
CREATE INDEX idx_rsvp_event ON event_rsvp (event_id, status, id);
CREATE INDEX idx_rsvp_user ON event_rsvp (user_id, status);

CREATE TABLE event_attendance (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id  BIGINT      NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    user_id   BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    present   BOOLEAN     NOT NULL,
    method    VARCHAR(8)  NOT NULL,
    -- QR'da kullanicinin kendisi, elle yoklamada organizator
    marked_by BIGINT      NOT NULL REFERENCES app_user (id),
    marked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_event_attendance UNIQUE (event_id, user_id),
    CONSTRAINT ck_attendance_method CHECK (method IN ('QR', 'MANUAL'))
);
CREATE INDEX idx_attendance_event ON event_attendance (event_id);
