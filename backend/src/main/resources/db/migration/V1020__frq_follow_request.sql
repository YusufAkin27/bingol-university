-- Hesap turu: varsayilan herkese acik (mevcut tum hesaplar degismez). Satiri olmayan kullanici da herkese acik sayilir.
ALTER TABLE profile_privacy ADD COLUMN private_account BOOLEAN NOT NULL DEFAULT FALSE;

-- Bekleyen takip istekleri: yalniz GIZLI hesaplar icin olusur. Kabulde gercek takip (user_follow) yazilir ve satir silinir;
-- redde/geri cekmede satir silinir. Tekil (requester, target). Gecmis tutulmaz (90 gunden eski bekleyen istek gece silinir).
CREATE TABLE follow_request (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    target_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT frq_pair_uq UNIQUE (requester_id, target_id)
);
-- Gelen istek listesi (yeniden eskiye, imlec = id) ve sayac
CREATE INDEX frq_target_idx ON follow_request (target_id, id DESC);
-- Gece temizligi (90 gun) icin
CREATE INDEX frq_created_idx ON follow_request (created_at);
