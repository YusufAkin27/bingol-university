-- Etkinlik ekstralari (T14): ortak organizator, duyuru kaydi, haftalik seri, anket, katilim sertifikasi

CREATE TABLE event_co_organizer (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT      NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    added_by   BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_evx71_co UNIQUE (event_id, user_id)
);
CREATE INDEX evx71_co_user ON event_co_organizer (user_id);

-- Gunluk duyuru sinirini saymak icin kayit (metin tutulmaz)
CREATE TABLE event_announcement (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT      NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    sender_id  BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    recipients INT         NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX evx71_ann_event ON event_announcement (event_id, created_at);

-- Haftalik seri: series_id = serinin ilk etkinliginin id'si
CREATE TABLE event_series_member (
    event_id  BIGINT PRIMARY KEY REFERENCES user_event (id) ON DELETE CASCADE,
    series_id BIGINT NOT NULL,
    seq       INT    NOT NULL
);
CREATE INDEX evx71_series ON event_series_member (series_id, seq);

CREATE TABLE event_feedback (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT       NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    rating     SMALLINT     NOT NULL,
    comment    VARCHAR(500),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_evx71_feedback UNIQUE (event_id, user_id),
    CONSTRAINT ck_evx71_rating CHECK (rating BETWEEN 1 AND 5)
);
CREATE INDEX evx71_fb_event ON event_feedback (event_id, id);

CREATE TABLE event_certificate (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    code        VARCHAR(32)  NOT NULL,
    holder_name VARCHAR(100) NOT NULL,
    issued_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_evx71_cert UNIQUE (event_id, user_id),
    CONSTRAINT uq_evx71_cert_code UNIQUE (code)
);
CREATE INDEX evx71_cert_user ON event_certificate (user_id);
