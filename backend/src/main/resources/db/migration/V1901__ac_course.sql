-- Akademisyen dersleri ve haftalik program satirlari (onek ak1900_).
CREATE TABLE ac_course (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id            BIGINT       NOT NULL REFERENCES app_user (id),
    code                VARCHAR(30),
    name                VARCHAR(200) NOT NULL,
    term                VARCHAR(40)  NOT NULL,
    faculty             VARCHAR(160),
    department          VARCHAR(160) NOT NULL,
    grade               VARCHAR(8),
    absence_limit_type  VARCHAR(8),
    absence_limit_value SMALLINT,
    status              VARCHAR(16)  NOT NULL,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ak1900_course_owner_idx ON ac_course (owner_id, status);

CREATE TABLE ac_course_slot (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT   NOT NULL REFERENCES ac_course (id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  TIME     NOT NULL,
    end_time    TIME     NOT NULL,
    room        VARCHAR(100),
    CONSTRAINT ak1900_slot_time_ck CHECK (end_time > start_time)
);
CREATE INDEX ak1900_slot_course_idx ON ac_course_slot (course_id);
