CREATE TABLE unit_source (
    code                 VARCHAR(20)  PRIMARY KEY,
    name                 VARCHAR(120) NOT NULL,
    kind                 VARCHAR(12)  NOT NULL,
    base_url             VARCHAR(120) NOT NULL,
    graduate             BOOLEAN      NOT NULL DEFAULT FALSE,
    -- virgullu AudienceKey degerleri: katalogdaki hangi fakulte adlarina hizmet eder (yonetici duzenler)
    faculty_keys         VARCHAR(600) NOT NULL DEFAULT '',
    enabled              BOOLEAN      NOT NULL DEFAULT TRUE,
    departments_checked_at TIMESTAMPTZ,
    last_success_at      TIMESTAMPTZ,
    last_attempt_at      TIMESTAMPTZ,
    last_message         VARCHAR(300),
    maintenance          BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT un_ck_kind CHECK (kind IN ('FACULTY', 'INSTITUTE', 'VOCATIONAL', 'LANGUAGE'))
);

CREATE TABLE unit_department (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code VARCHAR(20)  NOT NULL REFERENCES unit_source (code) ON DELETE CASCADE,
    slug        VARCHAR(160) NOT NULL,
    name        VARCHAR(200) NOT NULL,
    -- AudienceKey(ad) ve sondaki "bolumu/programi" atilmis hali: profildeki bolumle eslesme anahtari
    name_key    VARCHAR(200) NOT NULL,
    -- bolumun kendi duyuru akisi (/bolumler_/<x>/duyurular/); yoksa NULL
    feed_path   VARCHAR(200)
);
CREATE UNIQUE INDEX un_department_uq ON unit_department (source_code, slug);
CREATE INDEX un_department_key_idx ON unit_department (name_key);

CREATE TABLE unit_announcement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code    VARCHAR(20)  NOT NULL REFERENCES unit_source (code) ON DELETE CASCADE,
    -- bolum akisindan geldiyse bolum slug'i, genel (fakulte/okul) akistan geldiyse NULL
    dept_slug      VARCHAR(160),
    title          VARCHAR(300) NOT NULL,
    url            VARCHAR(500) NOT NULL,
    published_date DATE         NOT NULL,
    summary        VARCHAR(300) NOT NULL DEFAULT '',
    body           TEXT,
    -- JSON dizisi: [{"name","url","type"}]
    attachments    TEXT,
    hidden         BOOLEAN      NOT NULL DEFAULT FALSE,
    fetched_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX un_announcement_url_uq ON unit_announcement (url);
CREATE INDEX un_announcement_feed_idx ON unit_announcement (source_code, dept_slug, published_date DESC, id DESC);
CREATE INDEX un_announcement_date_idx ON unit_announcement (published_date);

