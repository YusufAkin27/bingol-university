-- Anket ve oylama: anket, secenek, secmen kaydi (tekillik/katilim) ve oy. Tasarim: docs/API_CONTRACTS_V2.md "Anket ve oylama".
CREATE TABLE poll (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(150) NOT NULL,
    description         VARCHAR(1000),
    type                VARCHAR(8)   NOT NULL,
    scope               VARCHAR(10)  NOT NULL,
    community_id        BIGINT,
    menu_date           DATE,
    created_by          BIGINT REFERENCES app_user (id),
    anonymous           BOOLEAN      NOT NULL DEFAULT FALSE,
    allow_change_vote   BOOLEAN      NOT NULL DEFAULT TRUE,
    show_results        VARCHAR(12)  NOT NULL DEFAULT 'ALWAYS',
    max_choices         SMALLINT     NOT NULL DEFAULT 1,
    notify              BOOLEAN      NOT NULL DEFAULT FALSE,
    opens_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closes_at           TIMESTAMPTZ,
    audience_faculty    VARCHAR(120),
    audience_department VARCHAR(120),
    audience_grade      VARCHAR(8),
    status              VARCHAR(10)  NOT NULL DEFAULT 'OPEN',
    voter_count         INT          NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closed_at           TIMESTAMPTZ,
    opened_notified_at  TIMESTAMPTZ,
    closing_notified_at TIMESTAMPTZ,
    CONSTRAINT pol330_type_chk CHECK (type IN ('SINGLE', 'MULTI', 'RATING', 'RANKED')),
    CONSTRAINT pol330_scope_chk CHECK (scope IN ('GLOBAL', 'COMMUNITY', 'MENU')),
    CONSTRAINT pol330_status_chk CHECK (status IN ('DRAFT', 'OPEN', 'CLOSED', 'CANCELLED')),
    CONSTRAINT pol330_show_chk CHECK (show_results IN ('ALWAYS', 'AFTER_VOTE', 'AFTER_CLOSE'))
);
CREATE INDEX pol330_status_idx ON poll (status, id DESC);
CREATE INDEX pol330_community_idx ON poll (community_id, id DESC) WHERE community_id IS NOT NULL;
CREATE INDEX pol330_creator_idx ON poll (created_by, id DESC) WHERE created_by IS NOT NULL;
-- Isleyici (kapanis/bildirim) yalniz acik anketleri tarar
CREATE INDEX pol330_open_idx ON poll (closes_at) WHERE status = 'OPEN';
-- Bir gun icin tek menu anketi
CREATE UNIQUE INDEX pol330_menu_day_uq ON poll (menu_date) WHERE menu_date IS NOT NULL;

CREATE TABLE poll_option (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id    BIGINT       NOT NULL REFERENCES poll (id) ON DELETE CASCADE,
    position   SMALLINT     NOT NULL,
    text       VARCHAR(100) NOT NULL,
    vote_count INT          NOT NULL DEFAULT 0,
    rank_score INT          NOT NULL DEFAULT 0
);
CREATE INDEX pol330_option_poll_idx ON poll_option (poll_id, position);

-- Secmen kaydi: kullanici basina tek satir (cift oyu engeller, katilimi sayar). Hesap silinince satir silinir.
CREATE TABLE poll_ballot (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id    BIGINT      NOT NULL REFERENCES poll (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pol330_ballot_uq UNIQUE (poll_id, user_id)
);
CREATE INDEX pol330_ballot_user_idx ON poll_ballot (user_id);

-- Oy: hesap silinince user_id NULL olur (anonimlestirme); sayaclar poll_option'da korunur.
CREATE TABLE poll_vote (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poll_id    BIGINT      NOT NULL REFERENCES poll (id) ON DELETE CASCADE,
    option_id  BIGINT      NOT NULL REFERENCES poll_option (id) ON DELETE CASCADE,
    user_id    BIGINT REFERENCES app_user (id),
    choice_rank SMALLINT    NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pol330_vote_uq UNIQUE (poll_id, user_id, option_id)
);
CREATE INDEX pol330_vote_user_idx ON poll_vote (user_id, poll_id);
CREATE INDEX pol330_vote_option_idx ON poll_vote (option_id);
