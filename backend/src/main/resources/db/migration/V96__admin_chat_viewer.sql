-- Silinen mesajda sifreli govde ARTIK silinmez (deleted_at/deleted_by V92'den); duzenleme gecmisi burada tutulur.

-- Mesajin onceki (duzenlemeyle degistirilen) sifreli surumleri. Sifreleme baglami (gonderen + clientId) asil mesajla aynidir.
CREATE TABLE message_revision (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id      BIGINT      NOT NULL REFERENCES message (id) ON DELETE CASCADE,
    body_ciphertext BYTEA       NOT NULL,
    body_nonce      BYTEA       NOT NULL,
    key_version     INTEGER     NOT NULL,
    -- bu surumun yazildigi an (duzenleme zamani ya da ilk gonderim)
    revised_at      TIMESTAMPTZ NOT NULL
);
CREATE INDEX adm96_revision_message ON message_revision (message_id, id);

-- Silinme saklama suresi taramasi
CREATE INDEX adm96_message_deleted ON message (deleted_at) WHERE deleted_at IS NOT NULL;

