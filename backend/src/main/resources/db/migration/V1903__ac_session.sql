-- Yoklama oturumu ve yoklama kayitlari (onek ak1900_). Oturum suresi expires_at ile tembel dolar (zamanlayici yok).
CREATE TABLE ac_session (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT      NOT NULL REFERENCES ac_course (id) ON DELETE CASCADE,
    slot_id     BIGINT      REFERENCES ac_course_slot (id) ON DELETE SET NULL,
    lesson_date DATE        NOT NULL,
    opened_at   TIMESTAMPTZ NOT NULL,
    expires_at  TIMESTAMPTZ NOT NULL,
    closed_at   TIMESTAMPTZ,
    status      VARCHAR(8)  NOT NULL
);
CREATE INDEX ak1900_session_course_idx ON ac_session (course_id, lesson_date);

CREATE TABLE ac_attendance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  BIGINT      NOT NULL REFERENCES ac_session (id) ON DELETE CASCADE,
    student_id  BIGINT      NOT NULL REFERENCES app_user (id),
    method      VARCHAR(8)  NOT NULL,
    marked_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    marked_by   BIGINT      REFERENCES app_user (id),
    device_hash VARCHAR(64),
    -- Hoca kaydi "silerse" satir kalir, revoked_at dolar (devamsiz sayilir); ayni oturumda tekrar taramayla geri donulemez.
    revoked_at  TIMESTAMPTZ,
    revoked_by  BIGINT      REFERENCES app_user (id),
    CONSTRAINT ak1900_att_uq UNIQUE (session_id, student_id)
);
CREATE INDEX ak1900_att_student_idx ON ac_attendance (student_id);

-- Kayitli olmayan ogrencinin gecerli kodu okutmasi: hocaya sunulan bekleyen istek (ekle+var say ya da yok say).
CREATE TABLE ac_scan_request (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT      NOT NULL REFERENCES ac_session (id) ON DELETE CASCADE,
    student_id BIGINT      NOT NULL REFERENCES app_user (id),
    scanned_at TIMESTAMPTZ NOT NULL,
    status     VARCHAR(12) NOT NULL,
    decided_at TIMESTAMPTZ,
    decided_by BIGINT      REFERENCES app_user (id),
    CONSTRAINT ak1900_scanreq_uq UNIQUE (session_id, student_id)
);
CREATE INDEX ak1900_scanreq_status_idx ON ac_scan_request (session_id, status);
