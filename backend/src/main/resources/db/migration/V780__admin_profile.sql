-- P16 yonetici rol/izin matrisi (RBAC): Role USER/ADMIN KALIR; yalniz role=ADMIN icin anlamli yonetici profili.
-- Mevcut yoneticiler FULL olarak tasinir (geriye uyum: bugune dek herkes her seyi yapabiliyordu).
ALTER TABLE app_user ADD COLUMN admin_profile VARCHAR(16);
UPDATE app_user SET admin_profile = 'FULL' WHERE role = 'ADMIN';
ALTER TABLE app_user ADD CONSTRAINT p16_ck_user_admin_profile
    CHECK (admin_profile IS NULL OR admin_profile IN ('FULL', 'MODERATOR', 'SUPPORT', 'EDITOR', 'VIEWER'));
CREATE INDEX p16_user_admin_profile ON app_user (admin_profile) WHERE admin_profile IS NOT NULL;

-- Iki kisi onayi: FULL yoneticiyi dusurme / birini FULL yapma onerisi; 24 saat gecerli.
CREATE TABLE admin_profile_change (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id  BIGINT       NOT NULL,
    from_profile    VARCHAR(16),
    to_profile      VARCHAR(16)  NOT NULL,
    reason          VARCHAR(300) NOT NULL,
    proposed_by     BIGINT       NOT NULL,
    proposed_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at      TIMESTAMPTZ  NOT NULL,
    status          VARCHAR(12)  NOT NULL DEFAULT 'PENDING',
    decided_by      BIGINT,
    decided_at      TIMESTAMPTZ,
    decision_note   VARCHAR(300),
    CONSTRAINT p16_ck_change_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'EXPIRED')),
    CONSTRAINT p16_ck_change_to CHECK (to_profile IN ('FULL', 'MODERATOR', 'SUPPORT', 'EDITOR', 'VIEWER'))
);
CREATE INDEX p16_change_status_proposed ON admin_profile_change (status, proposed_at DESC, id DESC);
CREATE INDEX p16_change_target ON admin_profile_change (target_user_id, status);
