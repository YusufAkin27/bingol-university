-- T15: kulup ekstralari. Genel sohbet odasi baglantisi, kulup logosu, duyuru gonderileri, katilim sorulari.
-- Indeks/kisit adlari clx72_ onekli (tum semada benzersiz).

-- Oda = mevcut bir grup konusmasi + (tur, kaynak id) baglantisi. COMMUNITY simdi, EVENT etkinlik sohbeti icin.
CREATE TABLE chat_room_link (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            VARCHAR(16)  NOT NULL,
    ref_id          BIGINT       NOT NULL,
    conversation_id BIGINT       NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    closed          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT clx72_room_ref_uq UNIQUE (kind, ref_id),
    CONSTRAINT clx72_room_conv_uq UNIQUE (conversation_id),
    CONSTRAINT clx72_room_kind_ck CHECK (kind IN ('COMMUNITY', 'EVENT'))
);

-- Kulup logosu: kapakla ayni hat (MediaService); yetim temizleyiciye ClubLogoMediaReferenceSource bildirir.
ALTER TABLE community ADD COLUMN logo_url VARCHAR(300);

-- Duyuru = isaretli kulup gonderisi (akista gorunur; gunluk 3 sinir, tum uyelere bildirim).
ALTER TABLE community_post ADD COLUMN announcement BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX clx72_post_announce_idx ON community_post (community_id, created_at) WHERE announcement;

-- Katilim sorulari (en fazla 3, uygulamada denetlenir) ve basvuru yanitlari (yalniz yetkililere gorunur).
CREATE TABLE club_join_question (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT       NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    sort_order   SMALLINT     NOT NULL,
    question     VARCHAR(200) NOT NULL,
    CONSTRAINT clx72_question_pos_uq UNIQUE (community_id, sort_order)
);

CREATE TABLE club_join_answer (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT       NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    question_id  BIGINT       NOT NULL REFERENCES club_join_question (id) ON DELETE CASCADE,
    user_id      BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    answer       VARCHAR(500) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT clx72_answer_uq UNIQUE (question_id, user_id)
);
CREATE INDEX clx72_answer_member_idx ON club_join_answer (community_id, user_id);
CREATE INDEX clx72_answer_user_idx ON club_join_answer (user_id);

-- Istatistik sorgulari icin: uyelik tarihine gore yeni uye sayimi.
CREATE INDEX clx72_member_joined_idx ON community_member (community_id, joined_at);
