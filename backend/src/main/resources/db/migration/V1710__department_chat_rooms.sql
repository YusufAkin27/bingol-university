-- Bolum sohbet gruplari: her bolum icin bir oda (chat_room_link DEPARTMENT). Onek dchat1710_.
-- dept_key = UnitKeys.deptKey(profil bolum adi); ayni bolumun yazim varyantlari tek odaya duser.
CREATE TABLE department_chat_room (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_key   VARCHAR(200) NOT NULL,
    name       VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT dchat1710_key_uq UNIQUE (dept_key)
);

-- chat_room_link.kind kisitina DEPARTMENT eklenir (V72'deki kisit adi clx72_room_kind_ck).
ALTER TABLE chat_room_link DROP CONSTRAINT clx72_room_kind_ck;
ALTER TABLE chat_room_link ADD CONSTRAINT dchat1710_room_kind_ck
    CHECK (kind IN ('COMMUNITY', 'EVENT', 'DEPARTMENT'));
