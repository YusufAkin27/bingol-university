-- Favoriler (genel bookmark tablosu, simdilik yalnizca NEWS) ve haber arama indeksleri

CREATE TABLE bookmark (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    target_type VARCHAR(16) NOT NULL,
    target_id   BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_bookmark UNIQUE (user_id, target_type, target_id)
);
-- Liste imecleri: kullanici + tur, yeni -> eski (id sirasi kaydedilme sirasidir)
CREATE INDEX idx_bookmark_user_type ON bookmark (user_id, target_type, id DESC);

-- Tam metin arama: ifade, NewsRepository'deki sorgu ifadesiyle birebir ayni olmali ki indeks kullanilsin.
CREATE INDEX idx_news_fts ON news_item
    USING GIN (to_tsvector('turkish', title || ' ' || coalesce(summary, '')));

-- Baslikta ILIKE '%...%' yedegi icin trigram indeksi
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE INDEX idx_news_title_trgm ON news_item USING GIN (title gin_trgm_ops);
