-- DS1 Veri saklama: yonetici paneli disa aktarma makbuzlari ve silme meta kayitlari. Indeks oneki: ds_.
-- Her iki tablo kanit niteligindedir: satir SILINEMEZ (tetikleyici), yalniz durum/sayac guncellenir.

CREATE TABLE data_export_receipt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name  VARCHAR(48)  NOT NULL,
    range_from  DATE         NOT NULL,                  -- dahil; "bastan" = 1970-01-01
    range_to    DATE         NOT NULL,                  -- haric
    format      VARCHAR(16)  NOT NULL DEFAULT 'CSV_GZIP',
    status      VARCHAR(12)  NOT NULL DEFAULT 'RUNNING',
    row_count   BIGINT       NOT NULL DEFAULT 0,
    byte_count  BIGINT       NOT NULL DEFAULT 0,
    sha256      VARCHAR(64),                            -- indirilen (gzip) dosyanin ozeti
    admin_id    BIGINT,
    admin_email VARCHAR(254),
    reason      VARCHAR(300),
    request_id  VARCHAR(64),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    CONSTRAINT ds_ck_receipt_status CHECK (status IN ('RUNNING', 'COMPLETED', 'PARTIAL', 'FAILED')),
    CONSTRAINT ds_ck_receipt_range CHECK (range_to > range_from)
);
CREATE INDEX ds_receipt_table_range ON data_export_receipt (table_name, status, range_to DESC, id DESC);
CREATE INDEX ds_receipt_created ON data_export_receipt (created_at DESC, id DESC);

CREATE TABLE data_purge_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name   VARCHAR(48)  NOT NULL,
    range_from   DATE         NOT NULL,
    range_to     DATE         NOT NULL,
    receipt_id   BIGINT,                                 -- kapsayan disa aktarma makbuzu (zorla silmede NULL)
    forced       BOOLEAN      NOT NULL DEFAULT FALSE,
    status       VARCHAR(12)  NOT NULL DEFAULT 'RUNNING',
    est_rows     BIGINT       NOT NULL DEFAULT 0,        -- onizleme tahmini (ust sinirli sayim)
    deleted_rows BIGINT       NOT NULL DEFAULT 0,
    oldest_at    TIMESTAMPTZ,                            -- silinen aralikta en eski / en yeni kayit zamani
    newest_at    TIMESTAMPTZ,
    reason       VARCHAR(300) NOT NULL,
    admin_id     BIGINT,
    admin_email  VARCHAR(254),
    request_id   VARCHAR(64),
    error        VARCHAR(300),
    started_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    finished_at  TIMESTAMPTZ,
    CONSTRAINT ds_ck_purge_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED', 'INTERRUPTED')),
    CONSTRAINT ds_ck_purge_range CHECK (range_to > range_from)
);
CREATE INDEX ds_purge_started ON data_purge_log (started_at DESC, id DESC);
CREATE INDEX ds_purge_running ON data_purge_log (updated_at) WHERE status = 'RUNNING';

CREATE FUNCTION ds_retention_no_delete() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only (no delete)', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER ds_trg_receipt_no_delete BEFORE DELETE ON data_export_receipt
    FOR EACH ROW EXECUTE FUNCTION ds_retention_no_delete();
CREATE TRIGGER ds_trg_purge_no_delete BEFORE DELETE ON data_purge_log
    FOR EACH ROW EXECUTE FUNCTION ds_retention_no_delete();
