-- 2FA-BACKEND: e-posta kodlu iki faktorlu dogrulama (istege bagli, kullanici kendisi acar).
-- Indeks/kisit onekleri: tf_ (sema genelinde benzersiz). Sozlesme: docs/TWO_FACTOR_API.md.

-- Kullanici bayragi: varsayilan KAPALI (mevcut hesaplar degismez).
ALTER TABLE app_user ADD COLUMN two_factor_enabled BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE app_user ADD COLUMN two_factor_enabled_at TIMESTAMPTZ;

-- Yonetici ozeti/listesi icin: yalniz 2FA acik olan az sayida satir indekslenir.
CREATE INDEX tf_user_enabled_idx ON app_user (two_factor_enabled_at DESC) WHERE two_factor_enabled;

-- Guvenilen cihazlar: kullanici basina en cok 10 (uygulama sinirlar, en eski duser). Ham cihaz kimligi SAKLANMAZ;
-- device_hash = ClientContexts HMAC-SHA256 ozeti. label yalniz platform/surum (ornek "ANDROID 2.0.5").
CREATE TABLE two_factor_device (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    device_hash  VARCHAR(64) NOT NULL,
    label        VARCHAR(80),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT tf_device_user_hash_uq UNIQUE (user_id, device_hash)
);
-- Cihaz listesi (son kullanima gore) ve en eski kaydi dusurme
CREATE INDEX tf_device_user_used_idx ON two_factor_device (user_id, last_used_at DESC);
