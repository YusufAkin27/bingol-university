-- Profil, roller, bildirimler, engelleme, raporlar

ALTER TABLE app_user
    ADD COLUMN role           VARCHAR(16)  NOT NULL DEFAULT 'USER',
    ADD COLUMN status         VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN department     VARCHAR(120),
    ADD COLUMN class_year     SMALLINT,
    ADD COLUMN bio            VARCHAR(300),
    ADD COLUMN avatar_url     VARCHAR(300),
    ADD COLUMN show_email     BOOLEAN      NOT NULL DEFAULT FALSE,
    ADD COLUMN suspended_reason VARCHAR(300),
    ADD COLUMN deleted_at     TIMESTAMPTZ;

CREATE INDEX idx_user_display_name ON app_user (lower(display_name));

CREATE TABLE device (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    fcm_token  VARCHAR(500) NOT NULL UNIQUE,
    platform   VARCHAR(16)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_device_user ON device (user_id);

CREATE TABLE notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    type       VARCHAR(24)   NOT NULL,
    title      VARCHAR(200)  NOT NULL,
    body       VARCHAR(500),
    data       VARCHAR(1000),
    read_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_user ON notification (user_id, id DESC);

CREATE TABLE notification_pref (
    user_id       BIGINT  PRIMARY KEY REFERENCES app_user (id) ON DELETE CASCADE,
    news          BOOLEAN NOT NULL DEFAULT TRUE,
    announcements BOOLEAN NOT NULL DEFAULT TRUE,
    events        BOOLEAN NOT NULL DEFAULT TRUE,
    messages      BOOLEAN NOT NULL DEFAULT TRUE,
    communities   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE user_block (
    blocker_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    blocked_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (blocker_id, blocked_id)
);
CREATE INDEX idx_user_block_blocked ON user_block (blocked_id);

CREATE TABLE report (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    target_type VARCHAR(16)  NOT NULL,
    target_id   BIGINT       NOT NULL,
    reason      VARCHAR(32)  NOT NULL,
    note        VARCHAR(500),
    status      VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    resolution  VARCHAR(24),
    resolved_by BIGINT       REFERENCES app_user (id),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolved_at TIMESTAMPTZ
);
CREATE INDEX idx_report_status ON report (status, id);
-- Ayni kullanici ayni hedefi acik raporla birden fazla kez raporlayamaz
CREATE UNIQUE INDEX uq_report_open ON report (reporter_id, target_type, target_id) WHERE status = 'OPEN';
