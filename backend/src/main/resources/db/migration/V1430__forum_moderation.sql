-- Kampus Forum D alani: moderator islem kaydi + kullanici sessize alma (tek yonlu).
-- Sessize alma: bakan (user_id) kendi listelerinde muted_user_id'nin icerigini gormez; engelden farki tek yonlu olmasi.
-- Islem kaydi: kaldirma/geri alma/sabitleme/kilitleme izi; hesap silinse de KORUNUR (moderasyon izi).

CREATE TABLE forum_moderation_action (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT       REFERENCES app_user (id),
    target_type VARCHAR(16)  NOT NULL,
    target_id   BIGINT       NOT NULL,
    topic_id    BIGINT,
    action      VARCHAR(16)  NOT NULL,
    reason      VARCHAR(500),
    source      VARCHAR(16)  NOT NULL DEFAULT 'MODERATOR',
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX fd14_action_created ON forum_moderation_action (created_at DESC, id DESC);
CREATE INDEX fd14_action_target ON forum_moderation_action (target_type, target_id, id DESC);

CREATE TABLE forum_user_mute (
    user_id       BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    muted_user_id BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, muted_user_id),
    CONSTRAINT fd14_mute_not_self CHECK (user_id <> muted_user_id)
);
CREATE INDEX fd14_mute_muted ON forum_user_mute (muted_user_id);
