-- B4: yazma uclari icin kalici Idempotency-Key defteri (events, communities, club posts, polls, support tickets).
-- (user_id, scope, idem_key) benzersiz: ayni anahtar ayni kaydi dondurur. Satir, kaynagi olusturan islemle
-- AYNI islemde yazilir; es zamanli ikinci istek benzersiz ihlaliyle geri alinir ve kazananin kaydini dondurur.
-- Saklama 7 gun (IdempotencyRecords gece temizligi). Kisisel veri yok: yalniz kimlikler.
CREATE TABLE idempotency_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    scope       VARCHAR(40) NOT NULL,
    idem_key    VARCHAR(64) NOT NULL,
    resource_id BIGINT      NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT idr1610_user_scope_key_uq UNIQUE (user_id, scope, idem_key)
);
CREATE INDEX idr1610_created_idx ON idempotency_record (created_at);
