-- Kampus haritasi (CAMPUS-BE): yer kayitlari + tek satirlik harita ayari. Indeks oneki: cm_.
-- Kisisel veri YOK (favoriler istemcide yerel tutulur). Tohum: V1201 (universite haritasi + OSM siniri). Sozlesme: docs/CAMPUS_MAP.md.

CREATE TABLE campus_place (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120)  NOT NULL,
    -- Turkce duyarsiz arama anahtari (kucuk harf, i/ı, s/ş, g/ğ, u/ü, o/ö, c/ç sadelesir); servis uretir
    name_key       VARCHAR(160)  NOT NULL,
    category       VARCHAR(20)   NOT NULL,
    lat            DOUBLE PRECISION NOT NULL,
    lng            DOUBLE PRECISION NOT NULL,
    summary        VARCHAR(300),
    -- Medya hattindaki herkese acik goreli URL (/files/covers/<ozet>.jpg); yuklemeyi yonetici ucu yapar
    photo_key      VARCHAR(200),
    units_json     TEXT          NOT NULL DEFAULT '[]',
    -- Birimlerin sadelestirilmis birlesimi (arama); servis uretir
    units_key      VARCHAR(2000) NOT NULL DEFAULT '',
    footprint_json TEXT,
    sort_key       INTEGER       NOT NULL DEFAULT 0,
    active         BOOLEAN       NOT NULL DEFAULT TRUE,
    -- Birimin resmi web sayfasi (yalniz https + bingol.edu.tr alt alani; servis dogrular)
    web_url        VARCHAR(300),
    -- Ana yerleske disindaki birim (Ilicalar, Solhan vb.): ana harita sinirlarinda gosterilmez, "diger yerleskeler" grubu
    remote         BOOLEAN       NOT NULL DEFAULT FALSE,
    -- Tohum kaynagi ("harita:19" = universite haritasi birim no); tohumun idempotent olmasi icin benzersiz; elle eklenen null
    source_ref     VARCHAR(40),
    -- yumusak silme (gerekce denetim kaydinda)
    deleted_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT cm_ck_category CHECK (category IN
        ('faculty', 'institute', 'school', 'vocational', 'dining', 'library', 'sports', 'health', 'admin', 'service',
         'dorm', 'gate', 'social')),
    CONSTRAINT cm_ck_lat CHECK (lat BETWEEN -90 AND 90),
    CONSTRAINT cm_ck_lng CHECK (lng BETWEEN -180 AND 180)
);
CREATE UNIQUE INDEX cm_place_source_uq ON campus_place (source_ref);
CREATE INDEX cm_place_list_idx ON campus_place (category, sort_key, name_key) WHERE active = TRUE AND deleted_at IS NULL;
CREATE INDEX cm_place_name_idx ON campus_place (name_key);

-- Tek satir (id = 1): harita merkezi, sinir poligonu, zoom, karo adresi. data_version her yazmada artar (istemci surumu).
CREATE TABLE campus_config (
    id                  SMALLINT PRIMARY KEY,
    center_lat          DOUBLE PRECISION NOT NULL,
    center_lng          DOUBLE PRECISION NOT NULL,
    zoom_initial        SMALLINT     NOT NULL,
    zoom_min            SMALLINT     NOT NULL,
    zoom_max            SMALLINT     NOT NULL,
    bound_south         DOUBLE PRECISION NOT NULL,
    bound_west          DOUBLE PRECISION NOT NULL,
    bound_north         DOUBLE PRECISION NOT NULL,
    bound_east          DOUBLE PRECISION NOT NULL,
    boundary_json       TEXT         NOT NULL DEFAULT '[]',
    tile_url            VARCHAR(300) NOT NULL,
    tile_attribution    VARCHAR(200) NOT NULL,
    tile_max_native_zoom SMALLINT    NOT NULL,
    user_agent_hint     VARCHAR(80)  NOT NULL,
    data_version        BIGINT       NOT NULL DEFAULT 1,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT cm_ck_config_single CHECK (id = 1)
);

-- Varsayilan: Bingol il merkezi civari; sinir poligonu V1201'de OSM'den gelir. Karo: OpenStreetMap standart sunucusu
-- (yogun/ticari kullanim politikaya aykiridir; adres yonetici panelinden degistirilebilir, docs/CAMPUS_MAP.md).
INSERT INTO campus_config (id, center_lat, center_lng, zoom_initial, zoom_min, zoom_max,
                           bound_south, bound_west, bound_north, bound_east, boundary_json,
                           tile_url, tile_attribution, tile_max_native_zoom, user_agent_hint)
VALUES (1, 38.8855, 40.4985, 16, 14, 19, 38.84, 40.44, 38.93, 40.56, '[]',
        'https://tile.openstreetmap.org/{z}/{x}/{y}.png',
        '© OpenStreetMap katkıda bulunanları', 19, 'BUKampus/{version}')
ON CONFLICT (id) DO NOTHING;
