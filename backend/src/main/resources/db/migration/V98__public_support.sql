-- Durum sorgu baglantisi: yalnizca SHA-256 hash'i saklanir; bir talep icin birden fazla gecerli olabilir
CREATE TABLE support_track_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT      NOT NULL REFERENCES support_ticket (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX pub98_track_hash ON support_track_token (token_hash);
CREATE INDEX pub98_track_ticket ON support_track_token (ticket_id);
