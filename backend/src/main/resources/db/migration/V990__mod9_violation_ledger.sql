-- burada kalir; ayni adresle yeniden kayitta strike devralinir, askiya alinmis hesabin adresi kayit olamaz.
-- KVKK: yalniz ozet + sayi; mesru menfaat (platform guvenligi); saklama 365 gun (expires_at), gecelik temizlik.
CREATE TABLE violation_ledger (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_digest VARCHAR(64) NOT NULL,
    strike_count INT         NOT NULL DEFAULT 0,
    banned       BOOLEAN     NOT NULL DEFAULT FALSE,
    recorded_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX mod9_vledger_email ON violation_ledger (email_digest);
CREATE INDEX mod9_vledger_expires ON violation_ledger (expires_at);

-- Acik sikayeti olan hesabin silinmesi bekletilir (7 gun): ilk talep burada kayitlanir, bekleme dolunca silinebilir.
CREATE TABLE account_delete_hold (
    user_id      BIGINT      PRIMARY KEY,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    release_at   TIMESTAMPTZ NOT NULL
);
CREATE INDEX mod9_delhold_release ON account_delete_hold (release_at);
