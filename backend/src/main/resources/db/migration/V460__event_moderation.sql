-- Durum gecmisi (denetim): kim, ne zaman, hangi gecis, hangi gerekce. admin_id NULL = Basic auth / sistem (rapor otomasyonu).
CREATE TABLE event_moderation_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT       NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    admin_id    BIGINT,
    action      VARCHAR(16)  NOT NULL,
    from_status VARCHAR(16)  NOT NULL,
    to_status   VARCHAR(16)  NOT NULL,
    reason      VARCHAR(300),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT evm460_action_check CHECK (action IN ('HIDE', 'UNHIDE', 'CANCEL', 'DELETE', 'EDIT', 'REPORT_HIDE', 'REPORT_UNHIDE'))
);
CREATE INDEX evm460_log_event ON event_moderation_log (event_id, id DESC);

-- Yonetici listesi: durum + id'ye gore azalan sayfalama
CREATE INDEX evm460_event_status_id ON user_event (status, id DESC);
