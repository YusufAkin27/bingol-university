-- Kullanici dili ve yoneticinin mobilden gonderdigi push kampanyalari

ALTER TABLE app_user
    ADD COLUMN language VARCHAR(2) NOT NULL DEFAULT 'tr',
    ADD CONSTRAINT app_user_language_check CHECK (language IN ('tr', 'en', 'ar'));

CREATE TABLE push_campaign (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by      BIGINT        NOT NULL REFERENCES app_user (id),
    type            VARCHAR(24)   NOT NULL DEFAULT 'ANNOUNCEMENT',
    audience_type   VARCHAR(16)   NOT NULL,
    audience_value  VARCHAR(2000),
    title_tr        VARCHAR(100)  NOT NULL,
    body_tr         VARCHAR(300)  NOT NULL,
    title_en        VARCHAR(100),
    body_en         VARCHAR(300),
    title_ar        VARCHAR(100),
    body_ar         VARCHAR(300),
    -- Bildirime tiklaninca acilacak yer: NONE | NEWS | EVENT | COMMUNITY | TICKET | URL
    target_type     VARCHAR(16)   NOT NULL DEFAULT 'NONE',
    target_value    VARCHAR(500),
    status          VARCHAR(16)   NOT NULL DEFAULT 'SCHEDULED',
    scheduled_at    TIMESTAMPTZ   NOT NULL,
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ,
    recipient_count INTEGER,
    error           VARCHAR(500),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT campaign_audience_check CHECK (audience_type IN ('ALL', 'DEPARTMENT', 'CLASS_YEAR', 'USERS', 'ADMINS', 'SELF')),
    CONSTRAINT campaign_status_check CHECK (status IN ('SCHEDULED', 'SENDING', 'SENT', 'CANCELLED', 'FAILED'))
);
CREATE INDEX idx_campaign_due ON push_campaign (status, scheduled_at);
CREATE INDEX idx_campaign_created ON push_campaign (id DESC);
