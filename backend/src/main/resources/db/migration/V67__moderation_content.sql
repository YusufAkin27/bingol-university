-- T12: yeni icerik turleri icin moderasyon altyapisi (oncelik, otomatik gizleme, ihlal takibi, itiraz, yasakli ozet listesi)

ALTER TABLE report ADD COLUMN priority INT NOT NULL DEFAULT 0;
ALTER TABLE report ADD COLUMN reason_code VARCHAR(32);
CREATE INDEX idx_modrep_status_prio ON report (status, priority DESC, id);
CREATE INDEX idx_modrep_reporter_res ON report (reporter_id, resolution, resolved_at);
CREATE INDEX idx_modrep_target ON report (target_type, target_id, status);

-- Gizlenmis (otomatik veya yonetici karariyla) hedefler; itiraz ve geri acma buradan yurur
CREATE TABLE moderation_target_state (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(16) NOT NULL,
    target_id   BIGINT      NOT NULL,
    hidden_by   VARCHAR(8),
    hidden_at   TIMESTAMPTZ,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_modstate_target UNIQUE (target_type, target_id)
);

-- Cozulmus ihlaller (kullanici basina); itiraz kabul edilirse revoked_at dolar
CREATE TABLE moderation_strike (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    report_id   BIGINT,
    target_type VARCHAR(16) NOT NULL,
    target_id   BIGINT      NOT NULL,
    resolution  VARCHAR(24) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at  TIMESTAMPTZ
);
CREATE INDEX idx_modstrike_user ON moderation_strike (user_id, created_at);
CREATE INDEX idx_modstrike_target ON moderation_strike (target_type, target_id);

-- Tekrarlayan ihlal: yoneticiye askiya alma onerisi
CREATE TABLE suspend_recommendation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    strike_count INT         NOT NULL,
    status       VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_by   BIGINT,
    decided_at   TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_susprec_open ON suspend_recommendation (user_id) WHERE status = 'OPEN';
CREATE INDEX idx_susprec_status ON suspend_recommendation (status, id);

-- Itiraz
CREATE TABLE moderation_appeal (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    target_type VARCHAR(16)   NOT NULL,
    target_id   BIGINT        NOT NULL,
    message     VARCHAR(1000) NOT NULL,
    status      VARCHAR(16)   NOT NULL DEFAULT 'OPEN',
    admin_note  VARCHAR(500),
    decided_by  BIGINT,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    decided_at  TIMESTAMPTZ
);
CREATE INDEX idx_modappeal_status ON moderation_appeal (status, id);
CREATE INDEX idx_modappeal_user ON moderation_appeal (user_id, id);
CREATE INDEX idx_modappeal_target ON moderation_appeal (target_type, target_id);

-- Yasakli gorsel ozetleri (SHA-256, kucuk harf hex); medya hatti yuklemede sorgular
CREATE TABLE blocked_content_hash (
    sha256     VARCHAR(64)  PRIMARY KEY,
    note       VARCHAR(300),
    created_by BIGINT,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
