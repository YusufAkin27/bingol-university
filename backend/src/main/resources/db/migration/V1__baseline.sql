-- Baslangic semasi: kullanici, haber/duyuru/etkinlik, yemek listesi, kaynak durumu

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(80)  NOT NULL,
    email_verified BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE news_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type           VARCHAR(16)   NOT NULL,
    url            VARCHAR(1000) NOT NULL UNIQUE,
    title          VARCHAR(1000) NOT NULL,
    summary        VARCHAR(600),
    content        TEXT,
    image_url      VARCHAR(1000),
    published_date DATE,
    fetched_at     TIMESTAMPTZ   NOT NULL,
    CONSTRAINT news_item_type_check CHECK (type IN ('DUYURU', 'HABER', 'ETKINLIK'))
);
CREATE INDEX idx_news_type_date ON news_item (type, published_date DESC);
CREATE INDEX idx_news_date ON news_item (published_date DESC);

CREATE TABLE menu_day (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_date DATE          NOT NULL UNIQUE,
    items     VARCHAR(1000) NOT NULL
);

CREATE TABLE sync_status (
    source          VARCHAR(32) PRIMARY KEY,
    state           VARCHAR(16) NOT NULL DEFAULT 'OK',
    last_attempt_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    message         VARCHAR(500)
);
