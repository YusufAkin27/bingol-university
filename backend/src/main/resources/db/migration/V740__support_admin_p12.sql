ALTER TABLE support_ticket ADD COLUMN priority    VARCHAR(8) NOT NULL DEFAULT 'NORMAL';
ALTER TABLE support_ticket ADD COLUMN assignee_id BIGINT;
ALTER TABLE support_ticket ADD CONSTRAINT p12_ticket_priority_check CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT'));
CREATE INDEX p12_ticket_assignee_idx ON support_ticket (assignee_id) WHERE assignee_id IS NOT NULL;

CREATE TABLE support_ticket_note (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT        NOT NULL REFERENCES support_ticket (id) ON DELETE CASCADE,
    author_id  BIGINT,
    text       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX p12_ticket_note_idx ON support_ticket_note (ticket_id, id);
