-- Sozlesmeler (kullanim kosullari, gizlilik, KVKK aydinlatma, topluluk kurallari): surumlu belgeler + kullanici onaylari
-- NOT: Asagidaki metinler TASLAKTIR; yayina almadan once hukuk birimi onayi gerekir.
-- Yonetici panelinden (POST /api/admin/legal/{type}) yeni surum yayinlanabilir.

CREATE TABLE legal_document (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(24)  NOT NULL,
    lang             VARCHAR(2)   NOT NULL DEFAULT 'tr',
    version          INTEGER      NOT NULL,
    title            VARCHAR(200) NOT NULL,
    content          TEXT         NOT NULL,
    require_reaccept BOOLEAN      NOT NULL DEFAULT TRUE,
    active           BOOLEAN      NOT NULL DEFAULT FALSE,
    published_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT legal_type_check CHECK (type IN ('TERMS', 'PRIVACY', 'KVKK', 'COMMUNITY_RULES')),
    CONSTRAINT legal_lang_check CHECK (lang IN ('tr', 'en', 'ar')),
    CONSTRAINT uq_legal_version UNIQUE (type, lang, version)
);
-- Her tur ve dil icin tek aktif surum. Surum numarasi dillerde ortaktir; onaylar (type, version) bazindadir (tr belge esastir).
CREATE UNIQUE INDEX uq_legal_active ON legal_document (type, lang) WHERE active;

CREATE TABLE legal_acceptance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    doc_type    VARCHAR(24) NOT NULL,
    version     INTEGER     NOT NULL,
    accepted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_legal_acceptance UNIQUE (user_id, doc_type, version)
);

