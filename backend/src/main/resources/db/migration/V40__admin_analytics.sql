-- Yonetim paneli: fakulte, son gorulme, kullanim takibi, denetim kaydi, haber gizleme ve raporlama indeksleri
-- NOT: PostgreSQL'de indeks adlari TUM semada benzersizdir; yeni adlar idx_<tablo>_<alan> bicimindedir ve
-- V1-V30'daki adlarla cakismadigi kontrol edilmistir.

ALTER TABLE app_user
    ADD COLUMN faculty      VARCHAR(120),
    ADD COLUMN last_seen_at TIMESTAMPTZ;

ALTER TABLE news_item
    ADD COLUMN hidden BOOLEAN NOT NULL DEFAULT FALSE;

-- Fakulte listesi (yonetici doldurur; ';' ile ayrilmis). Bos ise profilde serbest metin kabul edilir.
INSERT INTO app_setting (setting_key, setting_value) VALUES ('faculties', '')
ON CONFLICT (setting_key) DO NOTHING;

-- Kullanici basina gunluk acilis: yalnizca "o gun aktifti" bilgisi + acilis sayaci (kisisel icerik yok)
CREATE TABLE activity_daily (
    user_id BIGINT  NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    day     DATE    NOT NULL,
    opens   INTEGER NOT NULL DEFAULT 1,
    PRIMARY KEY (user_id, day)
);
-- DAU/WAU/MAU: gun araligi taramasi (COUNT DISTINCT user_id) icin
CREATE INDEX idx_activity_daily_day ON activity_daily (day, user_id);

-- Mobil kullanim olaylari (180 gun sonra zamanlayici siler)
CREATE TABLE analytics_event (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    name       VARCHAR(40)  NOT NULL,
    screen     VARCHAR(60),
    props      JSONB,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_analytics_event_created ON analytics_event (created_at);
CREATE INDEX idx_analytics_event_name ON analytics_event (name, created_at);
CREATE INDEX idx_analytics_event_user ON analytics_event (user_id, created_at);

-- Yonetici islemleri denetim kaydi (govde saklanmaz)
CREATE TABLE admin_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT,
    admin_email VARCHAR(254),
    method      VARCHAR(8)   NOT NULL,
    path        VARCHAR(300) NOT NULL,
    status      INTEGER      NOT NULL,
    ip          VARCHAR(64),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_admin_audit_admin ON admin_audit (admin_id, id DESC);
CREATE INDEX idx_admin_audit_created ON admin_audit (created_at);

-- Raporlama sorgulari icin tarih / iliski indeksleri
CREATE INDEX idx_app_user_created ON app_user (created_at);
CREATE INDEX idx_app_user_last_seen ON app_user (last_seen_at DESC NULLS LAST);
CREATE INDEX idx_app_user_faculty ON app_user (faculty) WHERE faculty IS NOT NULL;
CREATE INDEX idx_message_created ON message (created_at);
CREATE INDEX idx_message_sender ON message (sender_id);
CREATE INDEX idx_post_created ON community_post (created_at);
CREATE INDEX idx_rsvp_created ON event_rsvp (created_at);
CREATE INDEX idx_ticket_created ON support_ticket (created_at);
CREATE INDEX idx_support_message_staff ON support_message (ticket_id, created_at) WHERE from_staff;
CREATE INDEX idx_report_target ON report (target_type, target_id);
CREATE INDEX idx_report_reporter ON report (reporter_id);
CREATE INDEX idx_legal_acceptance_doc ON legal_acceptance (doc_type, version);
CREATE INDEX idx_news_hidden ON news_item (id) WHERE hidden;
