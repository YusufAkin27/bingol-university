-- Derse kayitli ogrenciler (onek ak1900_). Yoklamada "yok" = kayitli ama yoklama satiri olmayan.
CREATE TABLE ac_enrollment (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT      NOT NULL REFERENCES ac_course (id) ON DELETE CASCADE,
    student_id BIGINT      NOT NULL REFERENCES app_user (id),
    added_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Devamsizlik uyarisi tekrarlanmasin: 0 uyari yok, 1 risk bildirildi, 2 sinira ulasildi bildirildi.
    warned_level SMALLINT   NOT NULL DEFAULT 0,
    CONSTRAINT ak1900_enroll_uq UNIQUE (course_id, student_id)
);
CREATE INDEX ak1900_enroll_student_idx ON ac_enrollment (student_id);
