-- CR1 Cokme/hata raporlari (kendi sunucumuzda, ucuncu tarafa veri yok). Indeks oneki: cr_.
-- Anonimdir: kullanici kimligi, e-posta, token SAKLANMAZ (sunucuda ayrica maskelenir); cihaz yalniz model/OS duzeyindedir.
-- Saklama: olay 30 gun + grup basina son 50 olay (dbmaint gece temizligi); grup, son gorulmesi 30 gunu asinca silinir.

CREATE TABLE crash_group (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signature        VARCHAR(64)  NOT NULL,                 -- hata turu + normalize ust kareler SHA-256 (hex)
    error_type       VARCHAR(160) NOT NULL,
    message_sample   VARCHAR(300),
    top_frame        VARCHAR(300),
    status           VARCHAR(12)  NOT NULL DEFAULT 'NEW',
    status_reason    VARCHAR(300),
    status_by        VARCHAR(80),
    status_at        TIMESTAMPTZ,
    event_count      BIGINT       NOT NULL DEFAULT 0,       -- kumulatif (silinen olaylar dahil)
    first_seen_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_seen_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    first_version    VARCHAR(32),
    last_version     VARCHAR(32),
    fixed_in_version VARCHAR(32),                           -- yoneticinin bildirdigi duzeltme surumu (>= ise yeniden acilir)
    resolved_at_version VARCHAR(32),                        -- cozuldugu andaki son surum (> ise yeniden acilir)
    reopen_count     INT          NOT NULL DEFAULT 0,
    CONSTRAINT cr_ck_group_status CHECK (status IN ('NEW', 'ACK', 'RESOLVED'))
);
CREATE UNIQUE INDEX cr_group_signature ON crash_group (signature);
CREATE INDEX cr_group_status_seen ON crash_group (status, last_seen_at DESC, id DESC);
CREATE INDEX cr_group_last_seen ON crash_group (last_seen_at);

CREATE TABLE crash_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT       NOT NULL REFERENCES crash_group (id) ON DELETE CASCADE,
    app_version   VARCHAR(32)  NOT NULL,
    platform      VARCHAR(12)  NOT NULL,
    os_version    VARCHAR(64),
    device_model  VARCHAR(64),
    screen        VARCHAR(80),
    fatal         BOOLEAN      NOT NULL DEFAULT FALSE,
    message       VARCHAR(300),
    stack         TEXT         NOT NULL,                     -- maskelenmis, en cok ~8000 karakter
    occurred_at   TIMESTAMPTZ  NOT NULL,                     -- istemci saati (sinirlandirilmis)
    received_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX cr_event_group ON crash_event (group_id, id DESC);
CREATE INDEX cr_event_received ON crash_event (received_at);

-- Surum x platform dagilimi kumulatif tutulur (olaylar 50 ile sinirli oldugundan dagilim buradan okunur)
CREATE TABLE crash_group_version (
    group_id     BIGINT       NOT NULL REFERENCES crash_group (id) ON DELETE CASCADE,
    app_version  VARCHAR(32)  NOT NULL,
    platform     VARCHAR(12)  NOT NULL,
    cnt          BIGINT       NOT NULL DEFAULT 0,
    last_seen_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, app_version, platform)
);
CREATE INDEX cr_gv_version ON crash_group_version (app_version, platform);
