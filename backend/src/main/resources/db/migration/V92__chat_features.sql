-- Mesaj govdesine dokunulmaz; yalnizca meta sutunlari eklenir. Silinen mesajda sifreli govde NULL'lanir (tombstone).

ALTER TABLE message ADD COLUMN reply_to_message_id BIGINT REFERENCES message (id) ON DELETE SET NULL;
ALTER TABLE message ADD COLUMN edited_at           TIMESTAMPTZ;
ALTER TABLE message ADD COLUMN deleted_at          TIMESTAMPTZ;
ALTER TABLE message ADD COLUMN deleted_by          BIGINT REFERENCES app_user (id);

-- V69 kisiti tombstone'a izin vermeli: silinmis satirda govde de sifreli icerik de bulunmaz.
ALTER TABLE message DROP CONSTRAINT IF EXISTS message_body_present;
ALTER TABLE message ADD CONSTRAINT message_body_present CHECK (
    deleted_at IS NOT NULL OR body IS NOT NULL
    OR (body_ciphertext IS NOT NULL AND body_nonce IS NOT NULL AND key_version IS NOT NULL)) NOT VALID;

CREATE INDEX chf92_message_reply ON message (reply_to_message_id) WHERE reply_to_message_id IS NOT NULL;

-- Mesaj basina kullanici basina tek tepki
CREATE TABLE message_reaction (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT      NOT NULL REFERENCES message (id) ON DELETE CASCADE,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    emoji      VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chf92_uq_reaction UNIQUE (message_id, user_id)
);
CREATE INDEX chf92_reaction_user ON message_reaction (user_id);

-- Uye bazli tercihler: sessize alma, arsiv
ALTER TABLE conversation_member ADD COLUMN muted_until     TIMESTAMPTZ;
ALTER TABLE conversation_member ADD COLUMN archived_at     TIMESTAMPTZ;
-- true: yeni mesaj gelse de arsivde kalir; false: yeni mesaj arsivden cikarir
ALTER TABLE conversation_member ADD COLUMN archive_sticky  BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX chf92_member_archived ON conversation_member (user_id, archived_at) WHERE left_at IS NULL;
