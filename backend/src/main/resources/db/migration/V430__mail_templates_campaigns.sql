-- Yonetici e-posta sablonlari (surumlu) ve toplu/secili e-posta kampanyalari (mail/campaign).
-- Alici listesi kisisel veridir: kampanya kayitlarinda e-posta metni tutulmaz, yalniz user_id (KVKK).
-- Indeks adlari: mcp430_ oneki.

CREATE TABLE mail_template_custom (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL,
    description     VARCHAR(500),
    category        VARCHAR(16)  NOT NULL DEFAULT 'ANNOUNCEMENT',
    status          VARCHAR(12)  NOT NULL DEFAULT 'DRAFT',
    current_version INT          NOT NULL DEFAULT 1,
    created_by      BIGINT,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_mcp430_tpl_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);
CREATE INDEX mcp430_tpl_status ON mail_template_custom (status, id DESC);

-- Degismez icerik anlik goruntusu: kampanya, olusturuldugu andaki surume sabitlenir.
CREATE TABLE mail_template_custom_version (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT      NOT NULL REFERENCES mail_template_custom (id) ON DELETE CASCADE,
    version     INT         NOT NULL,
    subject_tr  VARCHAR(200),
    html_tr     TEXT,
    text_tr     TEXT,
    subject_en  VARCHAR(200),
    html_en     TEXT,
    text_en     TEXT,
    subject_ar  VARCHAR(200),
    html_ar     TEXT,
    text_ar     TEXT,
    created_by  BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_mcp430_tplver UNIQUE (template_id, version)
);

CREATE TABLE mail_campaign (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120) NOT NULL,
    template_id      BIGINT       NOT NULL REFERENCES mail_template_custom (id),
    template_version INT          NOT NULL,
    status           VARCHAR(12)  NOT NULL DEFAULT 'DRAFT',
    audience_type    VARCHAR(12)  NOT NULL,
    -- FILTER: filtre JSON'u; USERS/EMAILS: virgullu kullanici kimlikleri (e-posta metni SAKLANMAZ)
    audience_value   TEXT,
    unmatched_count  INT          NOT NULL DEFAULT 0,
    target_count     INT          NOT NULL DEFAULT 0,
    scheduled_at     TIMESTAMPTZ,
    resolved_at      TIMESTAMPTZ,
    started_at       TIMESTAMPTZ,
    finished_at      TIMESTAMPTZ,
    created_by       BIGINT,
    request_key      VARCHAR(64),
    error            VARCHAR(300),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_mcp430_cmp_status CHECK (status IN ('DRAFT', 'SCHEDULED', 'SENDING', 'PAUSED', 'DONE', 'CANCELLED', 'FAILED')),
    CONSTRAINT ck_mcp430_cmp_aud CHECK (audience_type IN ('ALL', 'FILTER', 'USERS', 'EMAILS'))
);
-- Zamanlayici yalniz isi olan kampanyalari tarar
CREATE INDEX mcp430_cmp_due ON mail_campaign (status, scheduled_at, id);
CREATE INDEX mcp430_cmp_tpl ON mail_campaign (template_id);
-- Cift tiklama / tekrar istek korumasi: ayni yonetici ayni istek anahtariyla tek kampanya olusturur
CREATE UNIQUE INDEX mcp430_cmp_reqkey ON mail_campaign (created_by, request_key);

CREATE TABLE mail_campaign_recipient (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   BIGINT      NOT NULL REFERENCES mail_campaign (id) ON DELETE CASCADE,
    user_id       BIGINT      NOT NULL,
    status        VARCHAR(12) NOT NULL DEFAULT 'PENDING',
    skip_reason   VARCHAR(24),
    lang          VARCHAR(2),
    lang_fallback BOOLEAN     NOT NULL DEFAULT FALSE,
    error_code    VARCHAR(40),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Ayni kullaniciya ayni kampanyadan en fazla bir e-posta
    CONSTRAINT uq_mcp430_recipient UNIQUE (campaign_id, user_id),
    CONSTRAINT ck_mcp430_rcp_status CHECK (status IN ('PENDING', 'QUEUED', 'SKIPPED', 'FAILED', 'CANCELLED'))
);
CREATE INDEX mcp430_rcp_pending ON mail_campaign_recipient (campaign_id, status, id);
CREATE INDEX mcp430_rcp_user ON mail_campaign_recipient (user_id);
CREATE INDEX mcp430_rcp_updated ON mail_campaign_recipient (updated_at);
