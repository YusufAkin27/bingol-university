-- Kalici push kuyrugu (outbox): surec yeniden baslasa da bekleyen push kaybolmaz. Isleyici: PushOutboxWorker.
-- Token tabloda tutulmaz: cihaz kimligi (device_id) gonderim aninda cozulur; fcm_token_hash yalniz izleme icindir.
CREATE TABLE push_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT,
    device_id       BIGINT,
    fcm_token_hash  VARCHAR(64),
    payload_json    TEXT         NOT NULL,
    priority        SMALLINT     NOT NULL DEFAULT 0,
    status          VARCHAR(12)  NOT NULL DEFAULT 'PENDING',
    attempts        INT          NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    lease_until     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    sent_at         TIMESTAMPTZ,
    last_error      VARCHAR(300),
    dedupe_key      VARCHAR(120)
);

-- Isleyici yalniz bekleyen/yeniden denenecek kayitlari tarar
CREATE INDEX pso350_due ON push_outbox (priority DESC, next_attempt_at, id) WHERE status IN ('PENDING', 'FAILED');
-- Kirasi dolan SENDING kayitlarini kurtarma
CREATE INDEX pso350_lease ON push_outbox (lease_until) WHERE status = 'SENDING';
-- Durum sayilari ve temizlik
CREATE INDEX pso350_status_created ON push_outbox (status, created_at);
-- Hesap silme
CREATE INDEX pso350_user ON push_outbox (user_id);
-- Ayni cihaza ayni dedupe anahtariyla ikinci bekleyen kayit yazilmaz
CREATE UNIQUE INDEX pso350_dedupe ON push_outbox (dedupe_key, device_id)
    WHERE dedupe_key IS NOT NULL AND status IN ('PENDING', 'SENDING', 'FAILED');
