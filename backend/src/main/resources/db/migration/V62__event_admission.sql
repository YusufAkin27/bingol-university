-- Etkinlik basina alim ayari; satir yoksa mod OPEN'dir (mevcut etkinlikler degismez).
CREATE TABLE event_admission (
    event_id   BIGINT       PRIMARY KEY REFERENCES user_event (id) ON DELETE CASCADE,
    mode       VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    question1  VARCHAR(200),
    question2  VARCHAR(200),
    question3  VARCHAR(200),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_evadm_mode CHECK (mode IN ('OPEN', 'APPROVAL'))
);

CREATE TABLE event_application (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id   BIGINT       NOT NULL REFERENCES user_event (id) ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    status     VARCHAR(16)  NOT NULL,
    note       VARCHAR(500),
    answer1    VARCHAR(500),
    answer2    VARCHAR(500),
    answer3    VARCHAR(500),
    -- Bekleme listesine giris ani: terfi sirasi (queued_at, id) ile adil FIFO
    queued_at  TIMESTAMPTZ,
    decided_by BIGINT       REFERENCES app_user (id) ON DELETE SET NULL,
    decided_at TIMESTAMPTZ,
    decision_note VARCHAR(300),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_event_application UNIQUE (event_id, user_id),
    CONSTRAINT ck_evapp_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'WAITLISTED', 'CANCELLED'))
);
CREATE INDEX idx_evapp_event ON event_application (event_id, status, id);
CREATE INDEX idx_evapp_user ON event_application (user_id, id DESC);

