-- Yemek ogesi basina kalori (kcal). Yonetici girer; kaynak site (scraper) kaloriye ASLA dokunmaz.
-- Anahtar (menu_date, item_key): item_key = yemek adinin normalize hali (kucuk harf, Turkce harf farki yok: I/i/ı->i, ç->c..., bosluklar tek). menu_day satiri
-- aylik senkronda yeniden yazilsa ya da silinse bile kalori ayri tabloda kalir ve ayni isimli yemege yeniden uygulanir.
-- Indeks oneki: mc_. Kalori silmek = satiri silmek (NULL tutulmaz).
CREATE TABLE menu_item_calorie (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_date  DATE         NOT NULL,
    item_key   VARCHAR(300) NOT NULL,
    item_name  VARCHAR(300) NOT NULL,
    kcal       INT          NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_by VARCHAR(80),
    CONSTRAINT mc_ck_kcal CHECK (kcal >= 0 AND kcal <= 5000)
);
CREATE UNIQUE INDEX mc_item_calorie_uq ON menu_item_calorie (menu_date, item_key);
