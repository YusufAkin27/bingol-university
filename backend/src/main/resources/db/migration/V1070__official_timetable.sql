-- V1070: resmi ders programi (yonetici Excel yukler). Onek: ott_
-- Sinav takvimi (exam_schedule) gibi bolum/sinif bazli; kullanicinin kisisel ders programindan (tt_*) ayridir.
CREATE TABLE official_timetable_batch (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term        VARCHAR(40)  NOT NULL,
    file_name   VARCHAR(200),
    sha256      VARCHAR(64),
    row_count   INT          NOT NULL,
    program_count INT        NOT NULL,
    created_by  BIGINT REFERENCES app_user (id),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE official_timetable_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id    BIGINT       NOT NULL REFERENCES official_timetable_batch (id) ON DELETE CASCADE,
    term        VARCHAR(40)  NOT NULL,
    unit        VARCHAR(160) NOT NULL,
    faculty     VARCHAR(160),
    department  VARCHAR(160) NOT NULL,
    program     VARCHAR(160) NOT NULL,
    grade       VARCHAR(8)   NOT NULL,
    grp         VARCHAR(40),
    day_of_week SMALLINT     NOT NULL,
    start_time  TIME         NOT NULL,
    end_time    TIME         NOT NULL,
    course_code VARCHAR(30),
    course_name VARCHAR(200) NOT NULL,
    instructor  VARCHAR(200),
    room        VARCHAR(100),
    note        VARCHAR(300),
    source_url  VARCHAR(500),
    published   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- sorgu yolu: bolum + sinif (kullanici), birim + program (yonetici ozet/silme)
CREATE INDEX ott_entry_dept_idx ON official_timetable_entry (term, department, grade, day_of_week, start_time);
CREATE INDEX ott_entry_prog_idx ON official_timetable_entry (term, unit, program);
CREATE INDEX ott_entry_batch_idx ON official_timetable_entry (batch_id);
