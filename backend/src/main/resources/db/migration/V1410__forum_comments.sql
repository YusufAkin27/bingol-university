-- V1410 (Kampus Forum, B alani): yorum agaci + yorum begenisi. Indeks oneki: fb14_.
-- Silme YUMUSAKTIR: deleted_at (sahibi sildi) ya da status=REMOVED (moderator). Yaniti olan tombstone satirlar API'de
-- `deleted:true` yer tutucu olarak doner (govde/yazar null); yanitsiz olanlar listelerden kalkar.
-- Sayaclar atomik UPDATE ile tutulur (okuma-degistir-yaz yok):
--   forum_topic.comment_count = konudaki CANLI (silinmemis, ACTIVE) yorum sayisi (yanitlar dahil)
--   forum_comment.reply_count = dogrudan "listelenen" cocuk sayisi (canli ya da kendi altinda listelenen cocugu olan tombstone)
--   forum_comment.like_count  = begeni sayisi

CREATE TABLE forum_comment (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id           BIGINT        NOT NULL REFERENCES forum_topic (id),
    user_id            BIGINT        NOT NULL REFERENCES app_user (id),
    parent_comment_id  BIGINT REFERENCES forum_comment (id),
    -- Ust duzey yorumda NULL; yanitlarda zincirin kokundeki ust duzey yorum
    root_comment_id    BIGINT REFERENCES forum_comment (id),
    depth              INT           NOT NULL DEFAULT 0,
    body               VARCHAR(4000) NOT NULL,
    anonymous          BOOLEAN       NOT NULL DEFAULT FALSE,
    like_count         INT           NOT NULL DEFAULT 0,
    reply_count        INT           NOT NULL DEFAULT 0,
    status             VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    removed_reason     VARCHAR(500),
    removed_at         TIMESTAMPTZ,
    idempotency_key    VARCHAR(100),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    edited_at          TIMESTAMPTZ,
    deleted_at         TIMESTAMPTZ,
    CONSTRAINT fb14_comment_status_chk CHECK (status IN ('ACTIVE', 'REMOVED'))
);

-- Ust duzey yorum listeleri (en yeni / en eski / en iyi): konu + id
CREATE INDEX fb14_comment_topic_top_idx ON forum_comment (topic_id, id) WHERE parent_comment_id IS NULL;
-- Dogrudan yanitlar
CREATE INDEX fb14_comment_parent_idx ON forum_comment (parent_comment_id, id) WHERE parent_comment_id IS NOT NULL;
-- Zincir (yol) ve kullanici gecmisi
CREATE INDEX fb14_comment_root_idx ON forum_comment (root_comment_id) WHERE root_comment_id IS NOT NULL;
CREATE INDEX fb14_comment_user_idx ON forum_comment (user_id, id DESC);
-- Cift gonderim korumasi: ayni kullanici + Idempotency-Key tek yorum
CREATE UNIQUE INDEX fb14_comment_idem_uq ON forum_comment (user_id, idempotency_key) WHERE idempotency_key IS NOT NULL;

CREATE TABLE forum_comment_like (
    comment_id BIGINT      NOT NULL REFERENCES forum_comment (id),
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (comment_id, user_id)
);
CREATE INDEX fb14_comment_like_user_idx ON forum_comment_like (user_id, created_at DESC);
