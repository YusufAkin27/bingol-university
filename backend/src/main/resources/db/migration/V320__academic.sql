-- V320: akademik modul (ders programi, sinav takvimi, akademik takvim, bolum duyurulari). Onek: acd320_
CREATE TABLE tt_semester (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    name       VARCHAR(60) NOT NULL,
    start_date DATE        NOT NULL,
    end_date   DATE        NOT NULL,
    is_current BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX acd320_sem_user_idx ON tt_semester (user_id);

CREATE TABLE tt_course (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id),
    semester_id BIGINT REFERENCES tt_semester (id) ON DELETE SET NULL,
    name        VARCHAR(120) NOT NULL,
    code        VARCHAR(20),
    instructor  VARCHAR(120),
    color       VARCHAR(12)  NOT NULL,
    note        VARCHAR(500),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX acd320_course_user_idx ON tt_course (user_id);
CREATE INDEX acd320_course_sem_idx ON tt_course (semester_id);

CREATE TABLE tt_session (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT      NOT NULL REFERENCES tt_course (id) ON DELETE CASCADE,
    day_of_week SMALLINT    NOT NULL,
    start_time  TIME        NOT NULL,
    end_time    TIME        NOT NULL,
    room        VARCHAR(60)
);
CREATE INDEX acd320_session_course_idx ON tt_session (course_id);

CREATE TABLE tt_exam (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT       NOT NULL REFERENCES app_user (id),
    course_id BIGINT REFERENCES tt_course (id) ON DELETE SET NULL,
    title     VARCHAR(120) NOT NULL,
    type      VARCHAR(10)  NOT NULL,
    starts_at TIMESTAMPTZ  NOT NULL,
    ends_at   TIMESTAMPTZ,
    room      VARCHAR(60),
    note      VARCHAR(500)
);
CREATE INDEX acd320_exam_user_idx ON tt_exam (user_id, starts_at);

-- Resmi sinav programi (yonetici girer); bos faculty/department/grade = herkes
CREATE TABLE exam_schedule (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150) NOT NULL,
    type        VARCHAR(10)  NOT NULL DEFAULT 'FINAL',
    term        VARCHAR(60)  NOT NULL,
    course_code VARCHAR(20),
    faculty     VARCHAR(120),
    department  VARCHAR(120),
    grade       VARCHAR(8),
    starts_at   TIMESTAMPTZ  NOT NULL,
    ends_at     TIMESTAMPTZ,
    room        VARCHAR(60),
    note        VARCHAR(500),
    published   BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX acd320_xs_start_idx ON exam_schedule (starts_at);

CREATE TABLE academic_event (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind             VARCHAR(20)  NOT NULL,
    title            VARCHAR(150) NOT NULL,
    starts_at        TIMESTAMPTZ  NOT NULL,
    ends_at          TIMESTAMPTZ,
    all_day          BOOLEAN      NOT NULL DEFAULT TRUE,
    scope_department VARCHAR(120),
    note             VARCHAR(500),
    published        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX acd320_ev_start_idx ON academic_event (starts_at);

CREATE TABLE department_announcement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(150)  NOT NULL,
    body           VARCHAR(4000) NOT NULL,
    department     VARCHAR(120),
    faculty        VARCHAR(120),
    grade          VARCHAR(8),
    pinned         BOOLEAN       NOT NULL DEFAULT FALSE,
    created_by     BIGINT REFERENCES app_user (id),
    publish_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    expires_at     TIMESTAMPTZ,
    attachment_url VARCHAR(500),
    published      BOOLEAN       NOT NULL DEFAULT TRUE,
    notify         BOOLEAN       NOT NULL DEFAULT FALSE,
    notified_at    TIMESTAMPTZ,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX acd320_ann_feed_idx ON department_announcement (publish_at DESC, id DESC);

CREATE TABLE announcement_read (
    announcement_id BIGINT      NOT NULL REFERENCES department_announcement (id) ON DELETE CASCADE,
    user_id         BIGINT      NOT NULL REFERENCES app_user (id),
    read_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (announcement_id, user_id)
);
CREATE INDEX acd320_read_user_idx ON announcement_read (user_id);
