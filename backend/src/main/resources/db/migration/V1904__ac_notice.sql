-- Ders duyurulari (sabit turler: LESSON_STARTED, ATTENDANCE_STARTED, EXAM, ASSIGNMENT). Onek ak1900_.
CREATE TABLE ac_notice (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id  BIGINT       NOT NULL REFERENCES ac_course (id) ON DELETE CASCADE,
    type       VARCHAR(24)  NOT NULL,
    title      VARCHAR(120),
    note       VARCHAR(1000),
    event_at   TIMESTAMPTZ,
    created_by BIGINT       REFERENCES app_user (id),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Yumusak silme: silinen duyuru listelerden kalkar ama sinir sayaclari (10 dk / gunluk) onu saymaya devam eder.
    deleted_at TIMESTAMPTZ
);
CREATE INDEX ak1900_notice_course_idx ON ac_notice (course_id, id);

-- Duyuru dosyalari (ASSIGNMENT/EXAM/MATERIAL): baytlar veritabaninda DEGIL, mevcut ozel medya deposunda (PrivateMediaStore,
-- diskte BlobCipher ile sifreli; kova "acnotice"). storage_key = depodaki anahtar. notice_id yuklemeden sonra, duyuru
-- olusurken doldurulur (once yukle, sonra kimlikle bagla: sohbet eki deseni); bagsiz satirlar 24 saat sonra silinir.
CREATE TABLE ac_notice_file (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id     BIGINT       REFERENCES ac_notice (id) ON DELETE CASCADE,
    course_id     BIGINT       NOT NULL REFERENCES ac_course (id) ON DELETE CASCADE,
    storage_key   VARCHAR(80)  NOT NULL,
    original_name VARCHAR(200) NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    size_bytes    BIGINT       NOT NULL,
    uploaded_by   BIGINT       REFERENCES app_user (id),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ak1900_nfile_notice_idx ON ac_notice_file (notice_id);
CREATE INDEX ak1900_nfile_course_idx ON ac_notice_file (course_id, created_at);
