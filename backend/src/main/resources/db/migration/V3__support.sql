CREATE TABLE feedback (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT        NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    category       VARCHAR(16)   NOT NULL,
    subject        VARCHAR(120)  NOT NULL,
    message        VARCHAR(2000) NOT NULL,
    status         VARCHAR(16)   NOT NULL DEFAULT 'NEW',
    app_version    VARCHAR(32),
    platform       VARCHAR(16),
    admin_response VARCHAR(1000),
    responded_at   TIMESTAMPTZ,
    is_public      BOOLEAN       NOT NULL DEFAULT FALSE,
    vote_count     INTEGER       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT feedback_category_check CHECK (category IN ('BUG', 'SUGGESTION', 'COMPLAINT', 'PRAISE', 'OTHER')),
    CONSTRAINT feedback_status_check CHECK (status IN ('NEW', 'IN_REVIEW', 'PLANNED', 'DONE', 'REJECTED')),
    CONSTRAINT feedback_public_suggestion CHECK (NOT is_public OR category = 'SUGGESTION')
);
CREATE INDEX idx_feedback_user ON feedback (user_id, id DESC);
CREATE INDEX idx_feedback_admin ON feedback (status, id DESC);
CREATE INDEX idx_feedback_board ON feedback (vote_count DESC, id DESC) WHERE is_public;

CREATE TABLE feedback_vote (
    feedback_id BIGINT      NOT NULL REFERENCES feedback (id) ON DELETE CASCADE,
    user_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (feedback_id, user_id)
);

CREATE TABLE support_ticket (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    category   VARCHAR(16)  NOT NULL,
    subject    VARCHAR(120) NOT NULL,
    status     VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closed_at  TIMESTAMPTZ,
    CONSTRAINT ticket_category_check CHECK (category IN ('ACCOUNT', 'TECHNICAL', 'CONTENT', 'OTHER')),
    CONSTRAINT ticket_status_check CHECK (status IN ('OPEN', 'ANSWERED', 'CLOSED'))
);
CREATE INDEX idx_ticket_user ON support_ticket (user_id, id DESC);
CREATE INDEX idx_ticket_admin ON support_ticket (status, updated_at);

CREATE TABLE support_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id  BIGINT        NOT NULL REFERENCES support_ticket (id) ON DELETE CASCADE,
    author_id  BIGINT        NOT NULL REFERENCES app_user (id),
    from_staff BOOLEAN       NOT NULL DEFAULT FALSE,
    text       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX idx_support_message_ticket ON support_message (ticket_id, id);

CREATE TABLE faq_item (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lang       VARCHAR(2)    NOT NULL DEFAULT 'tr',
    category   VARCHAR(40)   NOT NULL,
    question   VARCHAR(300)  NOT NULL,
    answer     VARCHAR(2000) NOT NULL,
    sort_order INTEGER       NOT NULL DEFAULT 0,
    published  BOOLEAN       NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT faq_lang_check CHECK (lang IN ('tr', 'en', 'ar'))
);
CREATE INDEX idx_faq_order ON faq_item (lang, category, sort_order, id);

