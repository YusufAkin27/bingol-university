-- Mesajlasma: konusma, uyelik (okundu imleci dahil) ve mesaj

CREATE TABLE conversation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(10)  NOT NULL,
    -- Yalnizca DIRECT: "kucukId:buyukId". Ayni iki kisi arasinda yinelenen konusmayi (yaris kosulunda da) engeller.
    direct_key      VARCHAR(41)  UNIQUE,
    title           VARCHAR(100),
    created_by      BIGINT       NOT NULL REFERENCES app_user (id),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Denormalize: konusma listesi siralamasi ve onizleme icin
    last_message_id BIGINT,
    last_message_at TIMESTAMPTZ,
    CONSTRAINT conversation_type_check CHECK (type IN ('DIRECT', 'GROUP'))
);
-- Konusma listesi imleci (last_message_id azalan)
CREATE INDEX idx_conversation_last_message ON conversation (last_message_id DESC);

CREATE TABLE conversation_member (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id      BIGINT      NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    user_id              BIGINT      NOT NULL REFERENCES app_user (id),
    role                 VARCHAR(10) NOT NULL DEFAULT 'MEMBER',
    joined_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    left_at              TIMESTAMPTZ,
    -- Okundu imleci: id <= bu deger olan mesajlar okunmus sayilir; yalnizca ileri gider
    last_read_message_id BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_member UNIQUE (conversation_id, user_id),
    CONSTRAINT member_role_check CHECK (role IN ('MEMBER', 'ADMIN'))
);
CREATE INDEX idx_member_user ON conversation_member (user_id, left_at);

CREATE TABLE message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT        NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    sender_id       BIGINT        NOT NULL REFERENCES app_user (id),
    -- Istemcinin urettigi kimlik: tekrar gonderimde cift kayit olmasin
    client_id       VARCHAR(64)   NOT NULL,
    body            VARCHAR(2000) NOT NULL,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Moderasyon "gizle" karari: yumusak silme, icerik API'de donmez
    hidden_at       TIMESTAMPTZ,
    CONSTRAINT uq_message_client UNIQUE (conversation_id, sender_id, client_id)
);
-- Gecmis sayfalama (en kritik indeks)
CREATE INDEX idx_message_conversation ON message (conversation_id, id DESC);
