-- T10: kulup ince yetkileri. Mevcut OWNER/MODERATOR/MEMBER satirlari DEGISMEZ; grant kaydi olmayan uye rolun
-- varsayilan yetkisini kullanir (MODERATOR sablonu eski moderator davranisinin aynisi), yani davranis korunur.
ALTER TABLE community_member DROP CONSTRAINT ck_member_role;
ALTER TABLE community_member ADD CONSTRAINT ck_member_role CHECK (role IN ('OWNER', 'ADMIN', 'MODERATOR', 'MEMBER'));

CREATE TABLE club_member_grant (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id BIGINT       NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    user_id      BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    template     VARCHAR(32),
    permissions  VARCHAR(200) NOT NULL DEFAULT '',
    updated_by   BIGINT,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_club_grant_member UNIQUE (community_id, user_id)
);
CREATE INDEX idx_club_grant_user ON club_member_grant (user_id);

-- Kullanici id'leri bilerek FK degil: denetim kaydi kullanici silinse/anonimlestirilse de korunur.
CREATE TABLE club_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community_id   BIGINT      NOT NULL REFERENCES community (id) ON DELETE CASCADE,
    actor_id       BIGINT,
    target_user_id BIGINT,
    action         VARCHAR(40) NOT NULL,
    detail         VARCHAR(500),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_club_audit_community ON club_audit (community_id, id DESC);
CREATE INDEX idx_club_audit_actor ON club_audit (actor_id);
CREATE INDEX idx_club_audit_target ON club_audit (target_user_id);
