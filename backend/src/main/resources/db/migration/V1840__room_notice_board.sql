-- Sohbet odasi duyuru panosu (bolum/kulup/etkinlik odalari). Onek rn1840_.
CREATE TABLE room_notice (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT       NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    author_id       BIGINT       NOT NULL,
    title           VARCHAR(80)  NOT NULL,
    body            VARCHAR(600) NOT NULL,
    pinned          BOOLEAN      NOT NULL DEFAULT FALSE,
    seen_count      INT          NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ,
    hidden_at       TIMESTAMPTZ
);
CREATE INDEX rn1840_conv_idx ON room_notice (conversation_id, id);

-- Gorulme kaydi: (duyuru, kullanici) tekil; kimlik listesi hicbir uctan verilmez, yalniz sayac.
CREATE TABLE room_notice_seen (
    notice_id BIGINT      NOT NULL REFERENCES room_notice (id) ON DELETE CASCADE,
    user_id   BIGINT      NOT NULL,
    seen_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (notice_id, user_id)
);
CREATE INDEX rn1840_seen_user_idx ON room_notice_seen (user_id);
