-- Mail teslim edilebilirligi: bastirma listesi (abonelikten cikan / kalici hata veren / sikayet eden adresler).
-- Adres duz saklanmaz; yalniz kucuk harfli adresin SHA-256 ozeti tutulur (KVKK veri azaltma).
CREATE TABLE mail_suppression (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash VARCHAR(64) NOT NULL,
    reason     VARCHAR(16) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX mls420_hash ON mail_suppression (email_hash);
