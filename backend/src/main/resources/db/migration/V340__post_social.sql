CREATE TABLE post_save (
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    post_id    BIGINT      NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, post_id)
);
CREATE INDEX soc340_save_user_idx ON post_save (user_id, created_at DESC, post_id DESC);

CREATE TABLE post_mention (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT      NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    comment_id BIGINT,
    user_id    BIGINT      NOT NULL REFERENCES app_user (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX soc340_mention_post_idx ON post_mention (post_id, comment_id);
CREATE INDEX soc340_mention_user_idx ON post_mention (user_id);

CREATE TABLE hashtag (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag        VARCHAR(40) NOT NULL,
    display    VARCHAR(40) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX soc340_hashtag_tag_uq ON hashtag (tag);

CREATE TABLE post_hashtag (
    post_id    BIGINT      NOT NULL REFERENCES post (id) ON DELETE CASCADE,
    hashtag_id BIGINT      NOT NULL REFERENCES hashtag (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, hashtag_id)
);
CREATE INDEX soc340_phash_tag_idx ON post_hashtag (hashtag_id, post_id DESC);
CREATE INDEX soc340_phash_time_idx ON post_hashtag (created_at DESC);

CREATE TABLE user_follow (
    follower_id BIGINT      NOT NULL REFERENCES app_user (id),
    followee_id BIGINT      NOT NULL REFERENCES app_user (id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id)
);
CREATE INDEX soc340_follow_followee_idx ON user_follow (followee_id, created_at DESC, follower_id DESC);
CREATE INDEX soc340_follow_follower_idx ON user_follow (follower_id, created_at DESC, followee_id DESC);

CREATE TABLE user_follow_stats (
    user_id         BIGINT PRIMARY KEY REFERENCES app_user (id),
    follower_count  INT NOT NULL DEFAULT 0,
    following_count INT NOT NULL DEFAULT 0
);

CREATE TABLE story (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id     BIGINT       NOT NULL REFERENCES app_user (id),
    kind          VARCHAR(8)   NOT NULL,
    media_id      BIGINT,
    caption       VARCHAR(200),
    body_text     VARCHAR(200),
    background    VARCHAR(9),
    view_count    INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at    TIMESTAMPTZ  NOT NULL,
    deleted_at    TIMESTAMPTZ,
    hidden_at     TIMESTAMPTZ,
    hidden_reason VARCHAR(300),
    CONSTRAINT soc340_story_kind_chk CHECK (kind IN ('IMAGE', 'VIDEO', 'TEXT'))
);
CREATE INDEX soc340_story_author_idx ON story (author_id, expires_at DESC);
CREATE INDEX soc340_story_expires_idx ON story (expires_at);

CREATE TABLE story_view (
    story_id  BIGINT      NOT NULL REFERENCES story (id) ON DELETE CASCADE,
    viewer_id BIGINT      NOT NULL REFERENCES app_user (id),
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (story_id, viewer_id)
);
CREATE INDEX soc340_sview_viewer_idx ON story_view (viewer_id, story_id);

