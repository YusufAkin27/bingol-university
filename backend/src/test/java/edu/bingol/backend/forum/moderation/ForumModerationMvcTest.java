    @Test
    void moderatorWalksThroughAllTopicTransitionsAndEachIsRecorded() throws Exception {
        User owner = data.user("owner");
        User mod = data.admin("mod", AdminProfile.MODERATOR);
        long t = data.topic(owner.getId(), cat, "Baslik", "Govde metni", false);

        MockHttpServletResponse pin = asAdmin(mod, AdminProfile.MODERATOR, moderate("topics", t, "PIN", null));
        assertThat(pin.getStatus()).as(pin.getContentAsString()).isEqualTo(200);
        assertThat(json(pin).get("pinned").asBoolean()).isTrue();
        assertThat(json(pin).get("status").asText()).isEqualTo("ACTIVE");

        assertThat(asAdmin(mod, AdminProfile.MODERATOR, moderate("topics", t, "LOCK", null)).getStatus()).isEqualTo(200);
        MockHttpServletResponse unlock = asAdmin(mod, AdminProfile.MODERATOR, moderate("topics", t, "UNLOCK", null));
        assertThat(json(unlock).get("locked").asBoolean()).isFalse();
        assertThat(json(unlock).get("pinned").asBoolean()).isTrue();
        assertThat(asAdmin(mod, AdminProfile.MODERATOR, moderate("topics", t, "UNPIN", null)).getStatus()).isEqualTo(200);

        MockHttpServletResponse rm = asAdmin(mod, AdminProfile.MODERATOR, moderate("topics", t, "REMOVE", "Kural ihlali"));
        assertThat(rm.getStatus()).as(rm.getContentAsString()).isEqualTo(200);
        assertThat(json(rm).get("status").asText()).isEqualTo("REMOVED");
        assertThat(jdbc.queryForObject("SELECT removed_reason FROM forum_topic WHERE id = ?", String.class, t))
                .isEqualTo("Kural ihlali");

        MockHttpServletResponse back = asAdmin(mod, AdminProfile.MODERATOR, moderate("topics", t, "RESTORE", "Yanlis karar"));
        assertThat(json(back).get("status").asText()).isEqualTo("ACTIVE");

        // 6 farkli islem + RESTORE = 7 satir: PIN, LOCK, UNLOCK, UNPIN, REMOVE, RESTORE
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM forum_moderation_action WHERE target_id = ? AND source = 'MODERATOR'",
                Long.class, t)).isEqualTo(6L);
        assertThat(jdbc.queryForObject("SELECT actor_id FROM forum_moderation_action WHERE action = 'REMOVE' AND target_id = ?",
                Long.class, t)).isEqualTo(mod.getId());
        // sahibine bildirim olayi (E): her eylem icin
        assertThat(state.events).extracting(FakeForumState.Event::action)
                .containsExactly("PIN", "LOCK", "UNLOCK", "UNPIN", "REMOVE", "RESTORE");
        // denetim kaydi (admin_audit, kullanici API'sinden yonetici mudahalesi)
        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM admin_audit WHERE target_type = 'FORUM_TOPIC' AND target_id = ?",
                Long.class, String.valueOf(t))).isEqualTo(6L);
    }

