package edu.bingol.backend.forum.moderation;

import edu.bingol.backend.admin.rbac.AdminProfile;
import edu.bingol.backend.user.Role;
import edu.bingol.backend.user.User;
import edu.bingol.backend.user.UserRepository;
import edu.bingol.backend.user.UserStatus;
import java.sql.Timestamp;
import java.time.Instant;
import java.util.UUID;
import org.springframework.jdbc.core.JdbcTemplate;

/**
 * D alani testleri icin ortak fixture: kullanici/yonetici + duz SQL ile konu/yorum/kategori (A/B tablolari H2'de
 * entity create-drop ile olusur; D onlarin depolarina bagimli degildir). Tum NOT NULL sutunlar acikca verilir.
 */
final class ForumTestData {

    private final JdbcTemplate jdbc;
    private final UserRepository users;

    ForumTestData(JdbcTemplate jdbc, UserRepository users) {
        this.jdbc = jdbc;
        this.users = users;
    }

    /** B'nin forum_comment tablosu entity ile olusmadiysa (B henuz birlesmediyse) sozlesme sutunlariyla olusturur. */
    void ensureCommentTable() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS forum_comment (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "topic_id BIGINT NOT NULL, user_id BIGINT NOT NULL, parent_comment_id BIGINT, root_comment_id BIGINT, "
                + "depth INT NOT NULL DEFAULT 0, body VARCHAR(4000) NOT NULL, anonymous BOOLEAN NOT NULL DEFAULT FALSE, "
                + "like_count INT NOT NULL DEFAULT 0, reply_count INT NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL, "
                + "updated_at TIMESTAMP NOT NULL, edited_at TIMESTAMP, deleted_at TIMESTAMP, "
                + "status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE')");
    }

    /** Test siniflari ayni Spring baglamini/H2'yi paylasir: forum + sikayet satirlarini sifirlar. */
    void reset() {
        jdbc.update("DELETE FROM forum_moderation_action");
        jdbc.update("DELETE FROM moderation_target_state");
        jdbc.update("DELETE FROM report");
        jdbc.update("DELETE FROM forum_comment");
        jdbc.update("DELETE FROM forum_topic");
    }

    User user(String name) {
        return save(name, Role.USER, null);
    }

    User admin(String name, AdminProfile profile) {
        return save(name, Role.ADMIN, profile);
    }

    private User save(String name, Role role, AdminProfile profile) {
        User u = new User();
        u.setEmail(name + "." + UUID.randomUUID().toString().substring(0, 8) + "@bingol.edu.tr");
        u.setPasswordHash("x");
        u.setDisplayName(name);
        u.setEmailVerified(true);
        u.setRole(role);
        u.setStatus(UserStatus.ACTIVE);
        u.setAdminProfile(profile);
        return users.save(u);
    }

    long category(String name) {
        String slug = name.toLowerCase() + "-" + UUID.randomUUID().toString().substring(0, 6);
        jdbc.update("INSERT INTO forum_category (slug, name_tr, name_en, name_ar, sort_order, active, created_at) "
                + "VALUES (?, ?, ?, ?, 0, TRUE, ?)", slug, name, name, name, Timestamp.from(Instant.now()));
        return jdbc.queryForObject("SELECT id FROM forum_category WHERE slug = ?", Long.class, slug);
    }

    long topic(long userId, long categoryId, String title, String body, boolean anonymous) {
        Timestamp now = Timestamp.from(Instant.now());
        jdbc.update("INSERT INTO forum_topic (user_id, category_id, title, body, anonymous, comment_count, like_count, "
                + "bookmark_count, image_count, status, created_at, updated_at, last_activity_at) "
                + "VALUES (?, ?, ?, ?, ?, 0, 0, 0, 0, 'ACTIVE', ?, ?, ?)", userId, categoryId, title, body, anonymous, now, now, now);
        return jdbc.queryForObject("SELECT MAX(id) FROM forum_topic WHERE user_id = ?", Long.class, userId);
    }

    long comment(long topicId, long userId, String body, boolean anonymous) {
        Timestamp now = Timestamp.from(Instant.now());
        jdbc.update("INSERT INTO forum_comment (topic_id, user_id, root_comment_id, depth, body, anonymous, like_count, "
                + "reply_count, status, created_at, updated_at) VALUES (?, ?, NULL, 0, ?, ?, 0, 0, 'ACTIVE', ?, ?)",
                topicId, userId, body, anonymous, now, now);
        return jdbc.queryForObject("SELECT MAX(id) FROM forum_comment WHERE user_id = ?", Long.class, userId);
    }

    void setTopicStatus(long topicId, String status) {
        jdbc.update("UPDATE forum_topic SET status = ? WHERE id = ?", status, topicId);
    }

    void softDeleteTopic(long topicId) {
        jdbc.update("UPDATE forum_topic SET deleted_at = CURRENT_TIMESTAMP WHERE id = ?", topicId);
    }

    void softDeleteComment(long commentId) {
        jdbc.update("UPDATE forum_comment SET deleted_at = CURRENT_TIMESTAMP WHERE id = ?", commentId);
    }
}
