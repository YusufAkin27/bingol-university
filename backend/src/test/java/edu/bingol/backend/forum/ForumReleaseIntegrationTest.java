    @Test
    void duplicateTopicAndCommentAreRejectedWith429ButOtherUsersAndTopicsAreNot() throws Exception {
        User a = user("yazar");
        User b = user("okur");
        long t = topic(a, "Ayni baslik", "Ayni govde metni burada", false);
        MockHttpServletResponse dup = as(a, post("/api/forum/topics").contentType(MediaType.APPLICATION_JSON).content(
                "{\"title\":\"Ayni baslik\",\"body\":\"Ayni govde metni burada\",\"categoryId\":" + cat + ",\"anonymous\":false,\"imageIds\":[]}"));
        assertThat(dup.getStatus()).isEqualTo(429);
        assertThat(json(dup).get("code").asText()).isEqualTo("FORUM_DUPLICATE_CONTENT");
        assertThat(dup.getHeader("Retry-After")).isNotNull();
        // baska kullanici ayni metni acabilir
        topic(b, "Ayni baslik", "Ayni govde metni burada", false);

        assertThat(comment(b, t, "Bu yorum yeterince uzun bir metindir", false).getStatus()).isEqualTo(201);
        MockHttpServletResponse dupC = comment(b, t, "Bu yorum yeterince uzun bir metindir", false);
        assertThat(dupC.getStatus()).isEqualTo(429);
        assertThat(json(dupC).get("code").asText()).isEqualTo("FORUM_DUPLICATE_CONTENT");
        // kisa metin baska konuda serbest ("Katiliyorum")
        long t2 = topic(a, "Baska konu", "Baska konunun govdesi", false);
        assertThat(comment(b, t, "Katiliyorum", false).getStatus()).isEqualTo(201);
        assertThat(comment(b, t2, "Katiliyorum", false).getStatus()).isEqualTo(201);
        // bir hata sonrasi (olmayan ust yorum) isaret geri alinir: ayni metin yeniden gonderilebilir
        MockHttpServletResponse bad = as(b, post("/api/forum/topics/" + t + "/comments").contentType(MediaType.APPLICATION_JSON)
                .content("{\"body\":\"Gecersiz ust yorumlu uzun metin\",\"parentCommentId\":99999999}"));
        assertThat(bad.getStatus()).isEqualTo(404);
        assertThat(comment(b, t, "Gecersiz ust yorumlu uzun metin", false).getStatus()).isEqualTo(201);
    }

    // ------------------------------------------------------------------ baglanti: moderasyon -> B/A durum servisleri

    @Test
    void moderatorRemovesAndRestoresCommentAndTopicThroughRealStateServices() throws Exception {
        User owner = user("sahip");
        User reader = user("okur");
        User mod = user("mod", Role.ADMIN, AdminProfile.MODERATOR);
        long t = topic(owner, "Moderasyon konusu", "Moderasyon govdesi", false);
        long c = comment(reader, t, "Kaldirilacak yorum metni", false).getStatus() == 201
                ? jdbc.queryForObject("SELECT MAX(id) FROM forum_comment WHERE topic_id = ?", Long.class, t) : -1L;
        assertThat(c).isPositive();
        assertThat(jdbc.queryForObject("SELECT comment_count FROM forum_topic WHERE id = ?", Integer.class, t)).isEqualTo(1);

        MockHttpServletResponse rm = asAdmin(mod, AdminProfile.MODERATOR, post("/api/forum/comments/" + c + "/moderate")
                .contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"REMOVE\",\"reason\":\"ihlal\"}"));
        assertThat(rm.getStatus()).as(rm.getContentAsString()).isEqualTo(200);
        assertThat(jdbc.queryForObject("SELECT status FROM forum_comment WHERE id = ?", String.class, c)).isEqualTo("REMOVED");
        assertThat(jdbc.queryForObject("SELECT comment_count FROM forum_topic WHERE id = ?", Integer.class, t)).isZero();
        MockHttpServletResponse list = as(reader, get("/api/forum/topics/" + t + "/comments"));
        assertThat(json(list).get("items")).isEmpty();

        MockHttpServletResponse back = asAdmin(mod, AdminProfile.MODERATOR, post("/api/forum/comments/" + c + "/moderate")
                .contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"RESTORE\",\"reason\":\"yanlis\"}"));
        assertThat(back.getStatus()).as(back.getContentAsString()).isEqualTo(200);
        assertThat(jdbc.queryForObject("SELECT status FROM forum_comment WHERE id = ?", String.class, c)).isEqualTo("ACTIVE");
        assertThat(jdbc.queryForObject("SELECT comment_count FROM forum_topic WHERE id = ?", Integer.class, t)).isEqualTo(1);

        MockHttpServletResponse rt = asAdmin(mod, AdminProfile.MODERATOR, post("/api/forum/topics/" + t + "/moderate")
                .contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"REMOVE\",\"reason\":\"ihlal\"}"));
        assertThat(rt.getStatus()).as(rt.getContentAsString()).isEqualTo(200);
        assertThat(as(reader, get("/api/forum/topics/" + t)).getStatus()).isEqualTo(404);
        assertThat(asAdmin(mod, AdminProfile.MODERATOR, post("/api/forum/topics/" + t + "/moderate")
                .contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"RESTORE\",\"reason\":\"geri\"}")).getStatus())
                .isEqualTo(200);
        assertThat(as(reader, get("/api/forum/topics/" + t)).getStatus()).isEqualTo(200);
    }

    @Test
    void moderatorProfileMapsToCanModerateAndPermissionHelper() throws Exception {
        User owner = user("sahip");
        User mod = user("mod", Role.ADMIN, AdminProfile.MODERATOR);
        User editor = user("editor", Role.ADMIN, AdminProfile.EDITOR);
        User viewer = user("viewer", Role.ADMIN, AdminProfile.VIEWER);
        long t = topic(owner, "Yetki konusu", "Yetki govdesi", false);
        assertThat(json(asAdmin(mod, AdminProfile.MODERATOR, get("/api/forum/topics/" + t))).get("canModerate").asBoolean()).isTrue();
        assertThat(json(asAdmin(editor, AdminProfile.EDITOR, get("/api/forum/topics/" + t))).get("canModerate").asBoolean()).isFalse();
        assertThat(json(asAdmin(viewer, AdminProfile.VIEWER, get("/api/forum/topics/" + t))).get("canModerate").asBoolean()).isFalse();
        assertThat(json(as(owner, get("/api/forum/topics/" + t))).get("canModerate").asBoolean()).isFalse();

        // ForumPermissions (A) -> PermissionMatrix (D)
        var req = new org.springframework.mock.web.MockHttpServletRequest();
        req.setAttribute(JwtAuthFilter.ADMIN_PROFILE_ATTR, AdminProfile.MODERATOR.name());
        org.springframework.web.context.request.RequestContextHolder.setRequestAttributes(
                new org.springframework.web.context.request.ServletRequestAttributes(req));
        org.springframework.security.core.context.SecurityContextHolder.getContext().setAuthentication(
                new UsernamePasswordAuthenticationToken(mod.getId(), null, List.of(new SimpleGrantedAuthority("ROLE_ADMIN"))));
        try {
            assertThat(ForumPermissions.canModerate()).isTrue();
            req.setAttribute(JwtAuthFilter.ADMIN_PROFILE_ATTR, AdminProfile.VIEWER.name());
            assertThat(ForumPermissions.canModerate()).isFalse();
        } finally {
            org.springframework.web.context.request.RequestContextHolder.resetRequestAttributes();
            org.springframework.security.core.context.SecurityContextHolder.clearContext();
        }
    }

