    private User user(String name, Role role, AdminProfile profile) {
        User u = new User();
        u.setEmail(name + "." + UUID.randomUUID().toString().substring(0, 8) + "@gmail.com"); // e-posta alan adi kisiti yok
        u.setPasswordHash("x");
        u.setDisplayName(name);
        u.setEmailVerified(true);
        u.setRole(role);
        u.setStatus(UserStatus.ACTIVE);
        u.setAdminProfile(profile);
        return users.save(u);
    }

    private User user(String name) {
        return user(name, Role.USER, null);
    }

    private MockHttpServletResponse as(User u, MockHttpServletRequestBuilder b) throws Exception {
        var token = new UsernamePasswordAuthenticationToken(u.getId(), null, List.of(new SimpleGrantedAuthority("ROLE_USER")));
        return mvc.perform(b.with(authentication(token))).andReturn().getResponse();
    }

    private MockHttpServletResponse asAdmin(User u, AdminProfile p, MockHttpServletRequestBuilder b) throws Exception {
        var token = new UsernamePasswordAuthenticationToken(u.getId(), null, List.of(new SimpleGrantedAuthority("ROLE_ADMIN")));
        return mvc.perform(b.with(authentication(token)).requestAttr(JwtAuthFilter.ADMIN_PROFILE_ATTR, p.name()))
                .andReturn().getResponse();
    }

    private static JsonNode json(MockHttpServletResponse r) throws Exception {
        return OM.readTree(r.getContentAsString(StandardCharsets.UTF_8));
    }

    private long topic(User u, String title, String body, boolean anonymous) throws Exception {
        MockHttpServletResponse r = as(u, post("/api/forum/topics").contentType(MediaType.APPLICATION_JSON).content(
                "{\"title\":\"" + title + "\",\"body\":\"" + body + "\",\"categoryId\":" + cat + ",\"anonymous\":" + anonymous
                        + ",\"imageIds\":[]}"));
        assertThat(r.getStatus()).as(r.getContentAsString()).isEqualTo(201);
        return json(r).get("id").asLong();
    }

    private MockHttpServletResponse comment(User u, long topic, String body, boolean anonymous) throws Exception {
        return as(u, post("/api/forum/topics/" + topic + "/comments").contentType(MediaType.APPLICATION_JSON)
                .content("{\"body\":\"" + body + "\",\"anonymous\":" + anonymous + "}"));
    }

    private boolean feedHas(User viewer, long topicId) throws Exception {
        MockHttpServletResponse r = as(viewer, get("/api/forum/topics?sort=NEWEST&size=30"));
        assertThat(r.getStatus()).as(r.getContentAsString()).isEqualTo(200);
        for (JsonNode n : json(r).get("items")) {
            if (n.get("id").asLong() == topicId) {
                return true;
            }
        }
        return false;
    }

