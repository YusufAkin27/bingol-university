    @Test
    void profileCommentsAndSavedItemsUseTheCommentAdapter() throws Exception {
        User owner = user("sahip");
        User reader = user("okur");
        long t = topic(owner, "Profil konusu", "Profil govdesi", false);
        assertThat(comment(reader, t, "Profil listesindeki yorum", false).getStatus()).isEqualTo(201);
        long c = jdbc.queryForObject("SELECT MAX(id) FROM forum_comment WHERE topic_id = ?", Long.class, t);
        assertThat(as(reader, put("/api/forum/comments/" + c + "/bookmark")).getStatus()).isEqualTo(200);
        assertThat(as(reader, put("/api/forum/topics/" + t + "/bookmark")).getStatus()).isEqualTo(200);

        JsonNode mine = json(as(reader, get("/api/forum/me/comments")));
        assertThat(mine.get("items")).hasSize(1);
        assertThat(mine.get("items").get(0).get("id").asLong()).isEqualTo(c);
        assertThat(mine.get("items").get(0).get("topicTitle").asText()).isEqualTo("Profil konusu");
        assertThat(mine.get("items").get(0).get("body").asText()).isEqualTo("Profil listesindeki yorum");

        JsonNode saved = json(as(reader, get("/api/forum/me/saved")));
        List<String> types = new java.util.ArrayList<>();
        saved.get("items").forEach(n -> types.add(n.get("type").asText()));
        assertThat(types).containsExactlyInAnyOrder("TOPIC", "COMMENT");
        for (JsonNode n : saved.get("items")) {
            assertThat(n.get("topic").get("id").asLong()).isEqualTo(t);
            if ("COMMENT".equals(n.get("type").asText())) {
                assertThat(n.get("comment").get("id").asLong()).isEqualTo(c);
                assertThat(n.get("comment").get("topicTitle").asText()).isEqualTo("Profil konusu");
            }
        }
        // baskasinin profilinde de gorunur (anonim olmayan)
        JsonNode other = json(as(owner, get("/api/forum/users/" + reader.getId() + "/comments")));
        assertThat(other.get("items")).hasSize(1);
        // kaldirilinca profil listesinden duser
        jdbc.update("UPDATE forum_comment SET status = 'REMOVED' WHERE id = ?", c);
        assertThat(json(as(reader, get("/api/forum/me/comments"))).get("items")).isEmpty();
    }

    // ------------------------------------------------------------------ karar (f): mute anonimde uygulanmaz, engel uygulanir

    @Test
    void muteHidesOnlyNamedContentWhileBlockHidesAnonymousToo() throws Exception {
        User viewer = user("bakan");
        User target = user("hedef");
        long anon = topic(target, "Anonim itiraf", "Anonim konu govdesi", true);
        long named = topic(target, "Acik gonderi", "Acik konu govdesi", false);
        long host = topic(viewer, "Ev sahibi konu", "Ev sahibi govdesi", false);
        assertThat(comment(target, host, "Anonim yorum metni burada", true).getStatus()).isEqualTo(201);
        assertThat(comment(target, host, "Acik yorum metni burada", false).getStatus()).isEqualTo(201);

        assertThat(as(viewer, put("/api/forum/mutes/" + target.getId())).getStatus()).isEqualTo(200);
        assertThat(feedHas(viewer, anon)).as("anonim konu mute ile gizlenmez").isTrue();
        assertThat(feedHas(viewer, named)).as("acik konu mute ile gizlenir").isFalse();
        assertThat(as(viewer, get("/api/forum/topics/" + anon)).getStatus()).isEqualTo(200);
        assertThat(as(viewer, get("/api/forum/topics/" + named)).getStatus()).isEqualTo(404);
        String comments = as(viewer, get("/api/forum/topics/" + host + "/comments")).getContentAsString(StandardCharsets.UTF_8);
        assertThat(comments).contains("Anonim yorum metni burada").doesNotContain("Acik yorum metni burada");
        // yazar kimligi anonim konuda yok
        assertThat(as(viewer, get("/api/forum/topics/" + anon)).getContentAsString()).doesNotContain("\"userId\":" + target.getId());

        assertThat(as(viewer, delete("/api/forum/mutes/" + target.getId())).getStatus()).isEqualTo(200);
        assertThat(feedHas(viewer, named)).isTrue();

        blocks.block(viewer.getId(), target.getId());
        assertThat(feedHas(viewer, anon)).as("engel anonimde de uygulanir").isFalse();
        assertThat(feedHas(viewer, named)).isFalse();
    }

