/**
 * Veri saklama HTTP sozlesmesi (H2): izinler (VIEWER okur, FULL aktarir/siler), makbuzsuz silme reddi, onay ve
 * Idempotency-Key zorunlulugu, asgari saklama suresi, disa aktar -> makbuz -> silme akisi.
 */
@SpringBootTest
class RetentionMvcTest {

    private static final ObjectMapper OM = new ObjectMapper();

    @Autowired WebApplicationContext ctx;
    @Autowired UserRepository users;
    @Autowired JdbcTemplate jdbc;
    @MockitoBean RateLimiter limiter;
    @MockitoBean StringRedisTemplate redis;
    @MockitoBean SchedulerLock lock;
    MockMvc mvc;

    @BeforeEach
    void setUp() {
        mvc = MockMvcBuilders.webAppContextSetup(ctx).apply(springSecurity()).build();
        when(lock.tryRun(any(), any(Duration.class), any(Runnable.class))).thenAnswer(i -> {
            ((Runnable) i.getArgument(2)).run();
            return true;
        });
        jdbc.execute("DELETE FROM data_export_receipt"); // testler arasi makbuz sizintisi olmasin (H2'de tetikleyici yok)
        jdbc.execute("DELETE FROM data_purge_log");
        jdbc.execute("DROP TABLE IF EXISTS profanity_hit_log");
        jdbc.execute("CREATE TABLE profanity_hit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "field VARCHAR(40) NOT NULL, entity VARCHAR(24) NOT NULL, user_id BIGINT, action VARCHAR(8) NOT NULL, "
                + "\"AT\" TIMESTAMP WITH TIME ZONE NOT NULL)");
    }

    private User admin(AdminProfile profile) {
        User u = new User();
        u.setEmail("ret." + UUID.randomUUID().toString().substring(0, 8) + "@bingol.edu.tr");
        u.setPasswordHash("x");
        u.setDisplayName("ret");
        u.setEmailVerified(true);
        u.setRole(Role.ADMIN);
        u.setStatus(UserStatus.ACTIVE);
        u.setAdminProfile(profile);
        return users.save(u);
    }

    private MockHttpServletResponse as(User u, MockHttpServletRequestBuilder b) throws Exception {
        var token = new UsernamePasswordAuthenticationToken(u.getId(), null, List.of(new SimpleGrantedAuthority("ROLE_ADMIN")));
        return mvc.perform(b.with(authentication(token))).andReturn().getResponse();
    }

    private static JsonNode json(MockHttpServletResponse r) throws Exception {
        return OM.readTree(r.getContentAsString(StandardCharsets.UTF_8));
    }

    private void insertHits(int n, String date) {
        for (int i = 0; i < n; i++) {
            jdbc.update("INSERT INTO profanity_hit_log (field, entity, user_id, action, \"AT\") VALUES ('f','e',1,'BLOCK',?)",
                    Timestamp.valueOf(date + " 10:00:00"));
        }
    }

    private static String body(String table, String from, String to, String extra) {
        return "{\"table\":\"" + table + "\",\"from\":\"" + from + "\",\"to\":\"" + to + "\",\"reason\":\"yedekleme ve temizlik\""
                + extra + "}";
    }

    private String okTo() {
        return LocalDate.now().minusDays(40).toString(); // profanity_hit_log asgari 30 gun
    }

    @Test
    void viewerCanReadButNotExportOrPurge() throws Exception {
        User viewer = admin(AdminProfile.VIEWER);
        assertThat(as(viewer, get("/api/admin/data-retention/tables")).getStatus()).isEqualTo(200);
        assertThat(as(viewer, get("/api/admin/system/storage")).getStatus()).isEqualTo(200);
        assertThat(as(viewer, get("/api/admin/data-retention/purges")).getStatus()).isEqualTo(200);
        MockHttpServletResponse e = as(viewer, post("/api/admin/data-retention/exports").contentType("application/json")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), "")));
        assertThat(e.getStatus()).isEqualTo(403);
        assertThat(json(e).get("code").asText()).isEqualTo("ADMIN_PERMISSION_DENIED");
        MockHttpServletResponse p = as(viewer, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345").content(body("profanity_hit_log", "2025-01-01", okTo(), "")));
        assertThat(p.getStatus()).isEqualTo(403);
        // SUPPORT/MODERATOR bile okuyamaz (yalnız FULL + VIEWER)
        assertThat(as(admin(AdminProfile.MODERATOR), get("/api/admin/data-retention/tables")).getStatus()).isEqualTo(403);
    }

    @Test
    void tablesListContainsMinimumRetentionAndNoUserDataTables() throws Exception {
        MockHttpServletResponse r = as(admin(AdminProfile.FULL), get("/api/admin/data-retention/tables"));
        assertThat(r.getStatus()).isEqualTo(200);
        JsonNode arr = json(r);
        List<String> names = new java.util.ArrayList<>();
        arr.forEach(n -> names.add(n.get("name").asText()));
        assertThat(names).contains("admin_audit", "analytics_event", "mail_outbox").doesNotContain("message", "app_user");
        arr.forEach(n -> assertThat(n.get("minRetentionDays").asInt()).isGreaterThanOrEqualTo(7));
    }

    @Test
    void purgeWithoutReceiptIsRejected() throws Exception {
        insertHits(5, "2025-06-01");
        User full = admin(AdminProfile.FULL);
        MockHttpServletResponse r = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), ",\"confirmTable\":\"profanity_hit_log\"")));
        assertThat(r.getStatus()).isEqualTo(409);
        assertThat(json(r).get("code").asText()).isEqualTo("RETENTION_EXPORT_REQUIRED");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM profanity_hit_log", Long.class)).isEqualTo(5L);
    }

    @Test
    void purgeRequiresIdempotencyKeyConfirmationAndOldEnoughRange() throws Exception {
        User full = admin(AdminProfile.FULL);
        String ok = body("profanity_hit_log", "2025-01-01", okTo(), ",\"confirmTable\":\"profanity_hit_log\"");
        MockHttpServletResponse noKey = as(full, post("/api/admin/data-retention/purges").contentType("application/json").content(ok));
        assertThat(json(noKey).get("code").asText()).isEqualTo("RETENTION_IDEMPOTENCY_REQUIRED");

        MockHttpServletResponse badConfirm = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), ",\"confirmTable\":\"baska_tablo\"")));
        assertThat(json(badConfirm).get("code").asText()).isEqualTo("RETENTION_CONFIRM_MISMATCH");

        String tooRecent = LocalDate.now().minusDays(5).toString();
        MockHttpServletResponse recent = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345")
                .content(body("profanity_hit_log", "2025-01-01", tooRecent, ",\"confirmTable\":\"profanity_hit_log\"")));
        assertThat(recent.getStatus()).isEqualTo(422);
        assertThat(json(recent).get("code").asText()).isEqualTo("RETENTION_RANGE_TOO_RECENT");

        MockHttpServletResponse unknown = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345")
                .content(body("app_user", "2025-01-01", okTo(), ",\"confirmTable\":\"app_user\"")));
        assertThat(unknown.getStatus()).isEqualTo(404);
    }

    @Test
    void messageAccessAuditCannotBePurgedFromPanel() throws Exception {
        MockHttpServletResponse r = as(admin(AdminProfile.FULL), post("/api/admin/data-retention/purges")
                .contentType("application/json").header("Idempotency-Key", "abcdefgh12345")
                .content(body("message_access_audit", "2020-01-01", LocalDate.now().minusDays(400).toString(),
                        ",\"confirmTable\":\"message_access_audit\"")));
        assertThat(r.getStatus()).isEqualTo(409);
        assertThat(json(r).get("code").asText()).isEqualTo("RETENTION_TABLE_NOT_DELETABLE");
    }

    @Test
    void exportThenPurgeWithReceiptDeletesRowsAndForcedPurgeNeedsLongReason() throws Exception {
        insertHits(30, "2025-06-01");
        insertHits(3, LocalDate.now().minusDays(2).toString()); // asgari sureden yeni: dokunulmaz
        User full = admin(AdminProfile.FULL);

        MockHttpServletResponse ex = as(full, post("/api/admin/data-retention/exports").contentType("application/json")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), "")));
        assertThat(ex.getStatus()).isEqualTo(200);
        String receiptId = ex.getHeader("X-Export-Receipt-Id");
        assertThat(receiptId).isNotBlank();
        byte[] gz = ex.getContentAsByteArray();
        String csv = new String(new GZIPInputStream(new ByteArrayInputStream(gz)).readAllBytes(), StandardCharsets.UTF_8);
        assertThat(csv.split("\r\n")).hasSize(31);

        JsonNode receipt = json(as(full, get("/api/admin/data-retention/exports/" + receiptId)));
        assertThat(receipt.get("status").asText()).isEqualTo("COMPLETED");
        assertThat(receipt.get("rowCount").asLong()).isEqualTo(30);
        assertThat(receipt.get("sha256").asText()).hasSize(64);

        JsonNode preview = json(as(full, get("/api/admin/data-retention/tables/profanity_hit_log/purge-preview")
                .param("from", "2025-01-01").param("to", okTo())));
        assertThat(preview.get("rowsInRange").asLong()).isEqualTo(30);
        assertThat(preview.get("canPurge").asBoolean()).isTrue();
        assertThat(preview.get("receipt").get("id").asLong()).isEqualTo(Long.parseLong(receiptId));

        // makbuzlu silme: 202
        MockHttpServletResponse del = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), ",\"confirmTable\":\"profanity_hit_log\"")));
        assertThat(del.getStatus()).isEqualTo(202);
        long purgeId = json(del).get("id").asLong();
        String st = "RUNNING";
        for (int i = 0; i < 100 && "RUNNING".equals(st); i++) {
            Thread.sleep(100);
            st = json(as(full, get("/api/admin/data-retention/purges/" + purgeId))).get("status").asText();
        }
        assertThat(st).isEqualTo("COMPLETED");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM profanity_hit_log", Long.class)).isEqualTo(3L);

        // zorla silme (makbuzsuz): gerekce >= 20 karakter
        insertHits(4, "2025-06-02");
        MockHttpServletResponse shortReason = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh99999")
                .content("{\"table\":\"profanity_hit_log\",\"from\":\"2025-01-01\",\"to\":\"" + okTo() + "\","
                        + "\"confirmTable\":\"profanity_hit_log\",\"forceWithoutExport\":true,\"reason\":\"kisa gerekce\"}"));
        assertThat(shortReason.getStatus()).isEqualTo(400);
        assertThat(json(shortReason).get("code").asText()).isEqualTo("REASON_REQUIRED");
    }

    @Test
    void staleReceiptIsRejectedWhenNewRowsAppearedInRange() throws Exception {
        insertHits(10, "2025-06-01");
        User full = admin(AdminProfile.FULL);
        as(full, post("/api/admin/data-retention/exports").contentType("application/json")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), "")));
        insertHits(5, "2025-06-03"); // makbuzdan sonra gelen gec kayit
        MockHttpServletResponse r = as(full, post("/api/admin/data-retention/purges").contentType("application/json")
                .header("Idempotency-Key", "abcdefgh12345")
                .content(body("profanity_hit_log", "2025-01-01", okTo(), ",\"confirmTable\":\"profanity_hit_log\"")));
        assertThat(r.getStatus()).isEqualTo(409);
        assertThat(json(r).get("code").asText()).isEqualTo("RETENTION_RECEIPT_STALE");
        assertThat(jdbc.queryForObject("SELECT count(*) FROM profanity_hit_log", Long.class)).isEqualTo(15L);
    }
}
