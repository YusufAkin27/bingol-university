/**
 * GERCEK PostgreSQL ile uctan uca dogrulama: V1220 migration + UsageRollup SQL'i + rapor sorgulari. H2'de calismayan
 * sorgular (jsonb, FILTER, ON COMMIT DROP, starts_with) burada sinanir. Yalniz USAGE_PG_URL tanimliysa calisir
 * (ornek: jdbc:postgresql://usage-pg:5432/postgres, kullanici postgres/USAGE_PG_PASSWORD); aksi halde atlanir.
 * Ayrinti: docs/USAGE_STATS.md "Dogrulama".
 */
class UsageRollupPostgresTest {

    private static final String URL = System.getenv("USAGE_PG_URL");
    private static final Instant NOW = Instant.parse("2026-11-02T09:00:00Z"); // Istanbul 12:00
    private static final LocalDate DAY = LocalDate.parse("2026-11-01");

    private static JdbcTemplate plain;
    private static NamedParameterJdbcTemplate jdbc;
    private static UsageRollup rollup;

    @BeforeAll
    static void setUp() throws Exception {
        assumeTrue(URL != null && !URL.isBlank(), "USAGE_PG_URL yok: PostgreSQL testi atlandi");
        DriverManagerDataSource ds = new DriverManagerDataSource(URL, System.getenv().getOrDefault("USAGE_PG_USER", "postgres"),
                System.getenv().getOrDefault("USAGE_PG_PASSWORD", "postgres"));
        plain = new JdbcTemplate(ds);
        jdbc = new NamedParameterJdbcTemplate(plain);
        plain.execute("DROP SCHEMA public CASCADE");
        plain.execute("CREATE SCHEMA public");
        plain.execute("CREATE TABLE app_user (id BIGINT PRIMARY KEY, faculty VARCHAR(120), department VARCHAR(120))");
        plain.execute("CREATE TABLE activity_daily (user_id BIGINT NOT NULL, day DATE NOT NULL, opens INTEGER NOT NULL DEFAULT 1, "
                + "PRIMARY KEY (user_id, day))");
        plain.execute("CREATE TABLE analytics_event (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, "
                + "name VARCHAR(40) NOT NULL, screen VARCHAR(60), props JSONB, created_at TIMESTAMPTZ NOT NULL DEFAULT now())");
        Path mig = Path.of("src/main/resources/db/migration/V1220__usage_stats.sql");
        plain.execute(Files.readString(mig, StandardCharsets.UTF_8));

        // 12 kullanici Muhendislik, 3 kullanici Egitim (k=10 altinda), 1 kullanici fakultesiz
        for (int u = 1; u <= 16; u++) {
            String faculty = u <= 12 ? "Muhendislik" : u <= 15 ? "Egitim" : null;
            plain.update("INSERT INTO app_user (id, faculty, department) VALUES (?, ?, ?)", u, faculty,
                    u <= 12 ? "Bilgisayar" : null);
            plain.update("INSERT INTO activity_daily (user_id, day, opens) VALUES (?, DATE '2026-11-01', 1)", u);
        }
        // Her kullanici: app_open (10:00 Istanbul = 07:00Z), home -> news_list (4 sn) -> news_detail (8 sn), eylem, app_background 120 sn
        for (int u = 1; u <= 16; u++) {
            String v = u <= 8 ? "2.0.6+20006" : "2.0.5";
            String p = u % 4 == 0 ? "ios" : "android";
            ev(u, "app_open", null, null, "2026-11-01T07:00:00Z", p, v);
            ev(u, "screen_view", "home", null, "2026-11-01T07:00:01Z", p, v);
            ev(u, "screen_view", "news_list", "{\"from\":\"home\",\"ms\":4000}", "2026-11-01T07:00:05Z", p, v);
            ev(u, "screen_view", "news_detail", "{\"from\":\"news_list\",\"ms\":8000}", "2026-11-01T07:00:13Z", p, v);
            ev(u, "news_open", null, "{\"id\":5}", "2026-11-01T07:00:13Z", p, v);
            ev(u, "app_background", null, "{\"dur\":120}", "2026-11-01T07:02:00Z", p, v);
            ev(u, "app_error", "home", "{\"type\":\"x\"}", "2026-11-01T07:03:00Z", p, v);
        }
        // gecersiz/ele gecirilmemesi gerekenler: legacy rota adi, 30 dk ustu sure, sayisal olmayan ms
        ev(1, "screen_view", "/news", null, "2026-11-01T07:10:00Z", "android", "2.0.6");
        ev(1, "screen_view", "settings", "{\"from\":\"home\",\"ms\":99999999}", "2026-11-01T07:11:00Z", "android", "2.0.6");
        ev(1, "screen_view", "profile", "{\"from\":\"settings\",\"ms\":\"abc\"}", "2026-11-01T07:12:00Z", "android", "2.0.6");
        // baska gun (24 saat sonra): 1 Kasim kapsamina girmemeli
        ev(2, "screen_view", "home", null, "2026-11-02T06:00:00Z", "android", "2.0.6");
        // 21:30Z = Istanbul 00:30 (2 Kasim): 1 Kasim'a girmemeli
        ev(3, "screen_view", "home", null, "2026-11-01T21:30:00Z", "android", "2.0.6");

        rollup = new UsageRollup(jdbc, Clock.fixed(NOW, ZoneOffset.UTC), null, 10);
        rollup.rollUp(DAY, true, true);
    }

    private static void ev(int uid, String name, String screen, String props, String at, String platform, String version) {
        plain.update("INSERT INTO analytics_event (user_id, name, screen, props, created_at, platform, app_version) "
                + "VALUES (?, ?, ?, CAST(? AS jsonb), CAST(? AS timestamptz), ?, ?)", uid, name, screen, props, at, platform, version);
    }

    private static UsageReportService service() {
        return new UsageReportService(new UsageReportRepository(jdbc), Clock.fixed(NOW, ZoneOffset.UTC), 10);
    }

    @Test
    void screenAggregates() {
        TopScreens r = service().topScreens("2026-11-01", "2026-11-01");
        ScreenItem home = r.items().stream().filter(i -> i.screen().equals("home")).findFirst().orElseThrow();
        // home: 16 kullanici x 1 (+ 1 kullanici 00:30 Istanbul'da 2 Kasim'a ait, hesaba girmez) = 16
        assertEquals(16, home.views());
        assertEquals(16, home.userDays());
        // home'dan cikan ekranlar: news_list (16, 4000ms) ve settings (1, 99999999 > 30 dk: sure yok) => avg 4 sn
        assertEquals(4.0, home.avgSeconds());
        // cikis: 16 goruntuleme, 17 gecis (16 + settings) => 0
        assertEquals(0.0, home.exitPercent());
        ScreenItem detail = r.items().stream().filter(i -> i.screen().equals("news_detail")).findFirst().orElseThrow();
        assertEquals(100.0, detail.exitPercent()); // sonrasinda ekran yok
        assertTrue(r.items().stream().noneMatch(i -> i.screen().startsWith("/")), "legacy rota adi sayilmamali");
        ScreenItem list = r.items().stream().filter(i -> i.screen().equals("news_list")).findFirst().orElseThrow();
        assertEquals(8.0, list.avgSeconds());
        assertNotNull(list.medianSeconds());
        assertEquals(1, home.trend().size());
    }

    @Test
    void actionsAndAdoption() {
        TopActions r = service().topActions("2026-11-01", "2026-11-01");
        assertEquals(1, r.items().size(), "yalniz news_open eylem; yasam dongusu ve app_error eylem degil");
        assertEquals("news_open", r.items().get(0).action());
        assertEquals(16, r.items().get(0).count());
        assertEquals(100.0, r.items().get(0).adoptionPercent());
    }

    @Test
    void flowEdges() {
        Flow f = service().flow("2026-11-01", "2026-11-01");
        assertTrue(f.edges().stream().anyMatch(e -> e.from().equals("home") && e.to().equals("news_list") && e.count() == 16));
        assertTrue(f.edges().stream().anyMatch(e -> e.from().equals("news_list") && e.to().equals("news_detail") && e.count() == 16));
        assertTrue(f.edges().stream().noneMatch(e -> e.from().equals(e.to())));
    }

    @Test
    void hourlyUsesIstanbulClock() {
        Hourly h = service().hourly("2026-11-01", "2026-11-01");
        assertEquals(168, h.cells().size());
        // 07:00Z = Istanbul 10:00, 1 Kasim 2026 = Pazar (ISO 7)
        assertEquals(16, h.cells().stream().filter(c -> c.dow() == 7 && c.hour() == 10).findFirst().orElseThrow().sessions());
        assertEquals(16, h.totalSessions());
        assertEquals(7, h.peak().dow());
        assertEquals(10, h.peak().hour());
    }

    @Test
    void summaryAndSessionDuration() {
        Summary s = service().summary("2026-11-01", "2026-11-01");
        assertEquals(16, s.totalSessions());
        assertEquals(16, s.avgDau());
        assertEquals(120.0, s.avgSessionSeconds());
        assertEquals("home", s.topScreen());
        assertEquals("news_open", s.topAction());
    }

    @Test
    void segmentsApplyKAnonymityAndKeepPlatforms() {
        Segments seg = service().segments("2026-11-01", "2026-11-01");
        assertEquals(10, seg.kAnonymity());
        assertEquals(2, seg.platforms().size());
        // surum: 2.0.6 (8 kullanici + 1 legacy olay ayni kullanici) ve 2.0.5 (8): ikisi de < 10 kullanici => other (16) >= 10 yazilir
        assertTrue(seg.versions().stream().allMatch(v -> v.key().equals("other")), seg.versions().toString());
        // fakulte: Muhendislik 12 (>=10) gorunur; Egitim 3 + fakultesiz 1 = other 4 (<10) HIC YAZILMAZ
        assertEquals(1, seg.faculties().size());
        assertEquals("Muhendislik", seg.faculties().get(0).key());
        assertTrue(seg.faculties().stream().noneMatch(f -> f.key().equals("Egitim") || f.key().equals("other")));
        assertEquals(1, seg.departments().size());
    }

    @Test
    void featuresSnapshotHasMauAndFeatureUsers() {
        Features f = service().features("2026-11-02", "2026-11-02");
        assertEquals("2026-11-01", f.asOf());
        assertEquals(16, f.mau());
        assertEquals(16, f.reportingUsers());
        assertEquals(16, f.items().stream().filter(i -> i.feature().equals("news")).findFirst().orElseThrow().users());
        assertEquals(0, f.items().stream().filter(i -> i.feature().equals("map")).findFirst().orElseThrow().users());
    }

    @Test
    void rollUpIsIdempotent() {
        long before = plain.queryForObject("SELECT count(*) FROM analytics_screen_daily", Long.class);
        rollup.rollUp(DAY, true, true);
        assertEquals(before, plain.queryForObject("SELECT count(*) FROM analytics_screen_daily", Long.class));
        assertEquals(1L, plain.queryForObject("SELECT count(*) FROM analytics_usage_day WHERE complete", Long.class));
        assertEquals(1L, plain.queryForObject("SELECT count(*) FROM analytics_feature_snapshot WHERE feature = 'all'", Long.class));
    }

    @Test
    void outputTablesHaveNoUserColumn() {
        Long n = plain.queryForObject("SELECT count(*) FROM information_schema.columns WHERE table_name IN ("
                + "'analytics_usage_day','analytics_screen_daily','analytics_screen_dur_daily','analytics_action_daily',"
                + "'analytics_flow_daily','analytics_hour_daily','analytics_segment_daily','analytics_feature_snapshot') "
                + "AND column_name IN ('user_id','email','device_id')", Long.class);
        assertEquals(0L, n);
        assertNull(null);
        assertFalse(false);
    }
}
