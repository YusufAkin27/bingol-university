import org.springframework.dao.QueryTimeoutException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * T-071 (A2-08): gece bakimi parcalari. Agir tablolar daha kucuk parcalarla silinir, PostgreSQL'de her parca kendi
 * kisa isleminde {@code SET LOCAL statement_timeout} ile calisir, basarisiz parca sayilir (eskiden sessizce yutulurdu).
 */
class ChunkedDeleterTest {

    private static final String SQL = "DELETE FROM t WHERE id IN (SELECT id FROM t LIMIT :lim)";

    private NamedParameterJdbcTemplate h2() {
        DriverManagerDataSource ds = new DriverManagerDataSource("jdbc:h2:mem:cd" + System.nanoTime() + ";DB_CLOSE_DELAY=-1",
                "sa", "");
        JdbcTemplate plain = new JdbcTemplate(ds);
        plain.execute("CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT)");
        for (int i = 0; i < 450; i++) {
            plain.update("INSERT INTO t (v) VALUES (?)", i);
        }
        return new NamedParameterJdbcTemplate(plain);
    }

    @Test
    void heavyDeletesInSmallerChunksThanNormal() {
        NamedParameterJdbcTemplate jdbc = spy(h2());
        // normal parca 500, agir parca 200 (alt sinir 100'un ustu)
        ChunkedDeleter d = new ChunkedDeleter(jdbc, new SimpleMeterRegistry(), 500, 0, 50, 200, 0);

        int n = d.deleteHeavy("t", SQL, Map.of());

        assertEquals(450, n);
        assertEquals(200, d.heavyChunkSize());
        assertEquals(500, d.chunkSize());
        verify(jdbc, times(3)).update(eq(SQL), anyMap()); // 200 + 200 + 50
        assertEquals(0, jdbc.getJdbcTemplate().queryForObject("SELECT count(*) FROM t", Integer.class));
        assertEquals(0, d.failedChunks());
    }

    @Test
    void heavyChunkNeverExceedsNormalChunk() {
        ChunkedDeleter d = new ChunkedDeleter(h2(), new SimpleMeterRegistry(), 300, 0, 50, 2000, 0);
        assertEquals(300, d.heavyChunkSize());
    }

    @Test
    void failedChunkIsCountedAndMetered() {
        NamedParameterJdbcTemplate jdbc = spy(h2());
        doThrow(new QueryTimeoutException("57014 statement timeout")).when(jdbc).update(anyString(), anyMap());
        SimpleMeterRegistry meters = new SimpleMeterRegistry();
        ChunkedDeleter d = new ChunkedDeleter(jdbc, meters, 500, 0, 50, 200, 0);

        assertEquals(0, d.deleteHeavy("notification_read", SQL, Map.of()), "hata cagirana sizmaz");
        assertEquals(1, d.failedChunks());
        assertEquals(1.0, meters.counter("bu_dbmaint_chunk_failed_total", "table", "notification_read").count());

        ChunkedDeleter.Result r = d.deleteAll("retention_x", SQL, Map.of(), null, null);
        assertTrue(r.error() != null);
        assertEquals(2, d.failedChunks());
    }

    @Test
    void postgresChunkRunsInOwnTransactionWithLocalStatementTimeout() throws SQLException {
        DataSource ds = mock(DataSource.class);
        Connection con = mock(Connection.class);
        DatabaseMetaData meta = mock(DatabaseMetaData.class);
        Statement st = mock(Statement.class);
        PreparedStatement ps = mock(PreparedStatement.class);
        when(ds.getConnection()).thenReturn(con);
        when(con.getMetaData()).thenReturn(meta);
        when(meta.getDatabaseProductName()).thenReturn("PostgreSQL");
        when(con.getAutoCommit()).thenReturn(true);
        when(con.createStatement()).thenReturn(st);
        when(con.prepareStatement(anyString())).thenReturn(ps);
        when(ps.executeUpdate()).thenReturn(7);
        ChunkedDeleter d = new ChunkedDeleter(new NamedParameterJdbcTemplate(new JdbcTemplate(ds)),
                new SimpleMeterRegistry(), 500, 0, 50, 200, 60_000);

        assertEquals(7, d.deleteHeavy("notification_read", SQL, Map.of()));

        InOrder o = inOrder(con, st, ps);
        o.verify(con).setAutoCommit(false);
        o.verify(st).execute("SET LOCAL statement_timeout = 60000");
        o.verify(ps).executeUpdate();
        o.verify(con).commit();
        o.verify(con).setAutoCommit(true);
        verify(con, never()).rollback();
    }

    @Test
    void postgresChunkRollsBackAndRestoresAutoCommitOnFailure() throws SQLException {
        DataSource ds = mock(DataSource.class);
        Connection con = mock(Connection.class);
        DatabaseMetaData meta = mock(DatabaseMetaData.class);
        Statement st = mock(Statement.class);
        PreparedStatement ps = mock(PreparedStatement.class);
        when(ds.getConnection()).thenReturn(con);
        when(con.getMetaData()).thenReturn(meta);
        when(meta.getDatabaseProductName()).thenReturn("PostgreSQL");
        when(con.getAutoCommit()).thenReturn(true);
        when(con.createStatement()).thenReturn(st);
        when(con.prepareStatement(anyString())).thenReturn(ps);
        when(ps.executeUpdate()).thenThrow(new SQLException("canceling statement due to statement timeout", "57014"));
        ChunkedDeleter d = new ChunkedDeleter(new NamedParameterJdbcTemplate(new JdbcTemplate(ds)),
                new SimpleMeterRegistry(), 500, 0, 50, 200, 60_000);

        assertEquals(0, d.deleteHeavy("notification_read", SQL, Map.of()));

        assertEquals(1, d.failedChunks());
        verify(con).rollback();
        verify(con, never()).commit();
        verify(con).setAutoCommit(true);
    }

    @Test
    void nonPostgresKeepsPlainAutoCommitPath() throws SQLException {
        DataSource ds = mock(DataSource.class);
        Connection con = mock(Connection.class);
        DatabaseMetaData meta = mock(DatabaseMetaData.class);
        PreparedStatement ps = mock(PreparedStatement.class);
        when(ds.getConnection()).thenReturn(con);
        when(con.getMetaData()).thenReturn(meta);
        when(meta.getDatabaseProductName()).thenReturn("H2");
        when(con.prepareStatement(anyString())).thenReturn(ps);
        when(ps.executeUpdate()).thenReturn(3);
        ChunkedDeleter d = new ChunkedDeleter(new NamedParameterJdbcTemplate(new JdbcTemplate(ds)),
                new SimpleMeterRegistry(), 500, 0, 50, 200, 60_000);

        assertEquals(3, d.delete("t", SQL, Map.of()));

        verify(con, never()).setAutoCommit(false);
        verify(con, never()).createStatement();
    }
}
