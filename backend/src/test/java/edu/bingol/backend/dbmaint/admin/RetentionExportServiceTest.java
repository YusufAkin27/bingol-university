package edu.bingol.backend.dbmaint.admin;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import edu.bingol.backend.common.ApiException;
import edu.bingol.backend.dbmaint.admin.RetentionTables.Spec;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.time.LocalDate;
import java.util.HexFormat;
import java.util.List;
import java.util.zip.GZIPInputStream;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.invocation.InvocationOnMock;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/** Akisli gzip CSV disa aktarma (H2, PostgreSQL modu): keyset sayfalama, SHA-256, CSV enjeksiyonu, maskeleme, yuva. */
class RetentionExportServiceTest {

    private JdbcTemplate plain;
    private NamedParameterJdbcTemplate jdbc;
    private DataExportReceiptRepository repo;
    private RetentionExportService svc;
    private final Spec audit = RetentionTables.find("admin_audit").orElseThrow();

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:retexp" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        plain = new JdbcTemplate(ds);
        jdbc = new NamedParameterJdbcTemplate(plain);
        plain.execute("CREATE TABLE admin_audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT, "
                + "admin_email VARCHAR(254), method VARCHAR(8) NOT NULL, path VARCHAR(300) NOT NULL, status INT NOT NULL, "
                + "target_type VARCHAR(32), target_id VARCHAR(64), reason VARCHAR(300), summary VARCHAR(500), "
                + "request_id VARCHAR(64), ip VARCHAR(64), created_at TIMESTAMP WITH TIME ZONE NOT NULL)");
        repo = mock(DataExportReceiptRepository.class);
        when(repo.save(any(DataExportReceipt.class))).thenAnswer((InvocationOnMock i) -> {
            DataExportReceipt r = i.getArgument(0);
            if (r.getId() == null) {
                r.setId(7L);
            }
            return r;
        });
        // sayfa boyutu alt siniri 100: 250 satir 3 sayfa
        svc = new RetentionExportService(jdbc, repo, 100, 5_000_000, 2);
    }

    private void insert(int n, String daysAgoDate, String email, String summary) {
        for (int i = 0; i < n; i++) {
            plain.update("INSERT INTO admin_audit (admin_id, admin_email, method, path, status, summary, ip, created_at) "
                            + "VALUES (1, ?, 'POST', '/api/admin/x', 200, ?, '10.0.0.1', ?)", email, summary,
                    java.sql.Timestamp.valueOf(daysAgoDate + " 10:00:00"));
        }
    }

    private RetentionService.Range range(String from, String to) {
        return new RetentionService.Range(LocalDate.parse(from), LocalDate.parse(to));
    }

    private static byte[] gunzip(byte[] gz) throws IOException {
        try (GZIPInputStream in = new GZIPInputStream(new ByteArrayInputStream(gz))) {
            return in.readAllBytes();
        }
    }

    @Test
    void streamsAllPagesWithCorrectRowCountAndSha256OfDownloadedBytes() throws IOException {
        insert(250, "2026-01-10", "ali@bingol.edu.tr", "ozet");
        insert(5, "2026-05-01", "disinda@bingol.edu.tr", "aralik disi");
        RetentionExportService.Started st = svc.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a@b.c", "yedekleme",
                "req-1");
        ByteArrayOutputStream out = new ByteArrayOutputStream();

        DataExportReceipt done = svc.stream(st, out);

        assertThat(done.getStatus()).isEqualTo(DataExportReceipt.Status.COMPLETED);
        assertThat(done.getRowCount()).isEqualTo(250);
        assertThat(done.getByteCount()).isEqualTo(out.size());
        String sha = HexFormat.of().formatHex(sha256(out.toByteArray()));
        assertThat(done.getSha256()).isEqualTo(sha);
        String csv = new String(gunzip(out.toByteArray()), StandardCharsets.UTF_8);
        String[] lines = csv.split("\r\n");
        assertThat(lines).hasSize(251); // baslik + 250
        assertThat(lines[0]).startsWith("id,admin_id,admin_email,method,path,status");
        assertThat(csv).doesNotContain("disinda@bingol.edu.tr");
        assertThat(csv.charAt(0)).as("BOM yok").isEqualTo('i');
    }

    @Test
    void escapesCsvInjectionInCells() throws IOException {
        insert(1, "2026-01-10", "ali@bingol.edu.tr", "=HYPERLINK(\"http://x\")");
        RetentionExportService.Started st = svc.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a", "neden1", null);
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        svc.stream(st, out);
        String csv = new String(gunzip(out.toByteArray()), StandardCharsets.UTF_8);
        assertThat(csv).contains("\"'=HYPERLINK(\"\"http://x\"\")\"");
    }

    @Test
    void cellsMaskPersonalColumnsWhenNoPiiPermission() {
        List<Object> row = List.of(1L, 9L, "ali@bingol.edu.tr", "POST", "/p", 200, "T", "1", "r", "s", "rid", "10.1.2.3",
                java.sql.Timestamp.valueOf("2026-01-10 10:00:00"));
        List<Object> masked = RetentionExportService.cells(audit, row, false);
        assertThat(masked.get(2)).isEqualTo("a***@bingol.edu.tr");
        assertThat(masked.get(11)).isEqualTo("***");
        List<Object> full = RetentionExportService.cells(audit, row, true);
        assertThat(full.get(2)).isEqualTo("ali@bingol.edu.tr");
        assertThat(full.get(11)).isEqualTo("10.1.2.3");
        assertThat(full.get(12).toString()).endsWith("Z");
    }

    @Test
    void partialWhenRowCapReached() throws IOException {
        RetentionExportService small = new RetentionExportService(jdbc, repo, 100, 1000, 2);
        insert(1200, "2026-01-10", "ali@bingol.edu.tr", "x");
        RetentionExportService.Started st = small.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a", "neden1", null);
        DataExportReceipt done = small.stream(st, new ByteArrayOutputStream());
        assertThat(done.getStatus()).isEqualTo(DataExportReceipt.Status.PARTIAL);
        assertThat(done.getRowCount()).isGreaterThanOrEqualTo(1000);
    }

    @Test
    void clientAbortMarksReceiptFailedAndFreesSlot() {
        insert(250, "2026-01-10", "ali@bingol.edu.tr", "x");
        RetentionExportService one = new RetentionExportService(jdbc, repo, 100, 5_000_000, 1);
        RetentionExportService.Started st = one.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a", "neden1", null);
        OutputStream broken = new OutputStream() {
            @Override
            public void write(int b) throws IOException {
                throw new IOException("client gone");
            }
        };
        assertThatThrownBy(() -> one.stream(st, broken)).isInstanceOf(IOException.class);
        assertThat(st.receipt().getStatus()).isEqualTo(DataExportReceipt.Status.FAILED);
        // yuva birakildi: yenisi alinabilir
        RetentionExportService.Started again = one.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a", "neden1", null);
        one.abort(again);
    }

    @Test
    void concurrencyLimitReturns429() {
        RetentionExportService one = new RetentionExportService(jdbc, repo, 100, 5_000_000, 1);
        RetentionExportService.Started first = one.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a", "neden1", null);
        assertThatThrownBy(() -> one.begin(audit, range("2026-01-01", "2026-02-01"), 1L, "a", "neden1", null))
                .isInstanceOfSatisfying(ApiException.class, e -> assertThat(e.code()).isEqualTo("RETENTION_EXPORT_BUSY"));
        one.abort(first);
    }

    private static byte[] sha256(byte[] b) {
        try {
            return MessageDigest.getInstance("SHA-256").digest(b);
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }
}
