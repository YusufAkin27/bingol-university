    /** T-063 (A11-09c): hesabi artik olmayan (silinmis dahil) adreslere giden eski SENT satirlari silinir. */
    @Test
    void sentMailToAddressesWithoutAnAccountIsRemoved() {
        plain.update("INSERT INTO app_user (email, status) VALUES ('var@bingol.edu.tr', 'ACTIVE')");
        plain.update("INSERT INTO app_user (email, status) VALUES ('deleted-9@deleted.invalid', 'DELETED')");
        mail("SENT", "ANNOUNCEMENT", "silinen@bingol.edu.tr", "{}", 48); // hesabi yok -> silinir
        mail("SENT", "ANNOUNCEMENT", "Var@Bingol.edu.tr", "{}", 48); // hesabi var (buyuk harf) -> kalir
        mail("SENT", "ANNOUNCEMENT", "silinen@bingol.edu.tr", "{}", 2); // taze -> kalir (son 24 saat istatistigi)
        mail("DEAD", "ANNOUNCEMENT", "silinen@bingol.edu.tr", "{}", 48); // DEAD operator incelemesi icin kalir
        mail("SENT", "ACCOUNT_DELETED", "silinen@bingol.edu.tr", "{}", 48); // hesap silindi onayi kalir

        assertEquals(1, job.runAll().get("mail_orphan_address"));
        assertEquals(4, plain.queryForObject("SELECT count(*) FROM mail_outbox", Integer.class));
    }

