    /** T-063 (A8-25): gonderilen kod postalarinin kodu 1 saat sonra kuyruktan silinir; satir ve diger sablonlar kalir. */
    @Test
    void sentCodeMailsLoseTheirCodeButRowRemains() {
        mail("SENT", "VERIFICATION_CODE", "a@bingol.edu.tr", "{\"code\":\"123456\",\"minutes\":\"10\"}", 3);
        mail("DEAD", "PASSWORD_RESET_CODE", "a@bingol.edu.tr", "{\"code\":\"654321\"}", 3);
        mail("SENT", "VERIFICATION_CODE", "b@bingol.edu.tr", "{\"code\":\"111111\"}", 0); // henuz taze: kalir
        mail("PENDING", "VERIFICATION_CODE", "c@bingol.edu.tr", "{\"code\":\"222222\"}", 5); // gonderilmedi: kalir
        mail("SENT", "ANNOUNCEMENT", "d@bingol.edu.tr", "{\"heading\":\"x\"}", 5); // kodsuz sablon: kalir

        assertEquals(2, job.runAll().get("mail_code_scrub"));

        assertEquals(2, plain.queryForObject("SELECT count(*) FROM mail_outbox WHERE vars_json = '{}'", Integer.class));
        assertEquals(0, plain.queryForObject("SELECT count(*) FROM mail_outbox WHERE vars_json LIKE '%123456%' OR vars_json LIKE '%654321%'", Integer.class));
        assertEquals(1, plain.queryForObject("SELECT count(*) FROM mail_outbox WHERE vars_json LIKE '%111111%'", Integer.class));
        assertEquals(1, plain.queryForObject("SELECT count(*) FROM mail_outbox WHERE vars_json LIKE '%222222%'", Integer.class));
        assertEquals(5, plain.queryForObject("SELECT count(*) FROM mail_outbox", Integer.class));
    }

