package edu.bingol.backend.dbmaint.admin;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import edu.bingol.backend.common.ApiException;
import edu.bingol.backend.config.SchedulerLock;
import edu.bingol.backend.dbmaint.ChunkedDeleter;
import edu.bingol.backend.dbmaint.admin.RetentionDtos.PurgeView;
import edu.bingol.backend.dbmaint.admin.RetentionTables.Spec;
import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.util.Map;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/** Onayli temizlik (H2): parcali silme, aralik sinirlari, durum kaydi, kilit yoksa FAILED, es zamanli temizlik reddi. */
class RetentionPurgeServiceTest {

    private JdbcTemplate plain;
    private DataPurgeLogRepository logs;
    private SchedulerLock lock;
    private RetentionPurgeService svc;
    private final Spec hits = RetentionTables.find("profanity_hit_log").orElseThrow();

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:retpurge" + System.nanoTime() + ";MODE=PostgreSQL;NON_KEYWORDS=AT;DB_CLOSE_DELAY=-1", "sa", "");
        plain = new JdbcTemplate(ds);
        NamedParameterJdbcTemplate jdbc = new NamedParameterJdbcTemplate(plain);
        plain.execute("CREATE TABLE profanity_hit_log (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "field VARCHAR(40) NOT NULL, entity VARCHAR(24) NOT NULL, user_id BIGINT, action VARCHAR(8) NOT NULL, "
                + "at TIMESTAMP WITH TIME ZONE NOT NULL)");
        plain.execute("CREATE TABLE data_purge_log (id BIGINT PRIMARY KEY, table_name VARCHAR(48), range_from DATE, "
                + "range_to DATE, receipt_id BIGINT, forced BOOLEAN DEFAULT FALSE, status VARCHAR(12) DEFAULT 'RUNNING', "
                + "est_rows BIGINT DEFAULT 0, deleted_rows BIGINT DEFAULT 0, oldest_at TIMESTAMP WITH TIME ZONE, "
                + "newest_at TIMESTAMP WITH TIME ZONE, reason VARCHAR(300), admin_id BIGINT, admin_email VARCHAR(254), "
                + "request_id VARCHAR(64), error VARCHAR(300), started_at TIMESTAMP WITH TIME ZONE DEFAULT now(), "
                + "updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(), finished_at TIMESTAMP WITH TIME ZONE)");
        logs = mock(DataPurgeLogRepository.class);
        when(logs.save(any(DataPurgeLog.class))).thenAnswer(i -> {
            DataPurgeLog r = i.getArgument(0);
            r.setId(1L);
            plain.update("INSERT INTO data_purge_log (id, table_name, range_from, range_to, reason) VALUES (1, ?, ?, ?, ?)",
                    r.getTableName(), java.sql.Date.valueOf(r.getRangeFrom()), java.sql.Date.valueOf(r.getRangeTo()),
                    r.getReason());
            return r;
        });
        lock = mock(SchedulerLock.class);
        when(lock.tryRun(any(), any(Duration.class), any(Runnable.class))).thenAnswer(i -> {
            ((Runnable) i.getArgument(2)).run();
            return true;
        });
        // parca 100: 250 satir 3 parcada silinmeli (alt sinir)
        ChunkedDeleter deleter = new ChunkedDeleter(jdbc, new SimpleMeterRegistry(), 100, 0, 50);
        svc = new RetentionPurgeService(jdbc, logs, deleter, lock, 6);
    }

    /** run() dogrudan cagrilan testlerde kayit 1'i elle olusturur (start() yolu bunu repo mock'uyla yapar). */
    private void seedLog() {
        plain.update("INSERT INTO data_purge_log (id, table_name, range_from, range_to, reason) VALUES (1, 'profanity_hit_log', "
                + "DATE '2026-01-01', DATE '2026-02-01', 'test gerekcesi')");
    }

    private void ins(String date, int n) {
        for (int i = 0; i < n; i++) {
            plain.update("INSERT INTO profanity_hit_log (field, entity, user_id, action, at) VALUES ('f','e',1,'BLOCK',?)",
                    java.sql.Timestamp.valueOf(date + " 10:00:00"));
        }
    }

    private RetentionService.Range range() {
        return new RetentionService.Range(LocalDate.parse("2026-01-01"), LocalDate.parse("2026-02-01"));
    }

    private PurgeView start() {
        return svc.start(hits, range(), null, true, 250, "test gerekcesi yeterince uzun", 5L, "a@b.c", "req");
    }

    @Test
    void deletesOnlyRangeRowsInChunksAndRecordsCompletion() {
        ins("2026-01-10", 250);
        ins("2026-03-01", 40); // aralik disi
        ins("2025-12-31", 7);  // aralik disi (oncesi)
        seedLog();
        svc.run(1L, hits, range());

        assertThat(plain.queryForObject("SELECT count(*) FROM profanity_hit_log", Long.class)).isEqualTo(47L);
        Map<String, Object> row = plain.queryForMap("SELECT status, deleted_rows, error FROM data_purge_log WHERE id = 1");
        assertThat(row.get("STATUS")).isEqualTo("COMPLETED");
        assertThat(((Number) row.get("DELETED_ROWS")).longValue()).isEqualTo(250L);
        assertThat(row.get("ERROR")).isNull();
    }

    @Test
    void failsWhenSchedulerLockCannotBeTaken() {
        ins("2026-01-10", 10);
        when(lock.tryRun(any(), any(Duration.class), any(Runnable.class))).thenReturn(false);
        seedLog();
        svc.run(1L, hits, range());
        assertThat(plain.queryForObject("SELECT count(*) FROM profanity_hit_log", Long.class)).isEqualTo(10L);
        assertThat(plain.queryForObject("SELECT status FROM data_purge_log WHERE id = 1", String.class)).isEqualTo("FAILED");
        assertThat(plain.queryForObject("SELECT error FROM data_purge_log WHERE id = 1", String.class)).isEqualTo("LOCK_UNAVAILABLE");
    }

    @Test
    void sqlErrorMarksFailedWithoutThrowing() {
        ins("2026-01-10", 10);
        plain.execute("DROP TABLE profanity_hit_log");
        plain.execute("CREATE TABLE profanity_hit_log (id BIGINT PRIMARY KEY)"); // kolonlar yok -> SQL hatasi
        start();
        svc.run(1L, hits, range());
        assertThat(plain.queryForObject("SELECT status FROM data_purge_log WHERE id = 1", String.class)).isEqualTo("FAILED");
    }

    @Test
    void refusesToStartWhileAnotherPurgeIsLive() {
        when(logs.existsLive(any(Instant.class))).thenReturn(true);
        assertThatThrownBy(this::start).isInstanceOfSatisfying(ApiException.class,
                e -> assertThat(e.code()).isEqualTo("RETENTION_PURGE_RUNNING"));
    }

    @Test
    void startReturnsRunningRecordAndWorkCompletesInBackground() throws Exception {
        ins("2026-01-10", 120);
        PurgeView v = start();
        assertThat(v.status()).isEqualTo("RUNNING");
        assertThat(v.forced()).isTrue();
        String st = "RUNNING";
        for (int i = 0; i < 100 && "RUNNING".equals(st); i++) {
            Thread.sleep(100);
            st = plain.queryForObject("SELECT status FROM data_purge_log WHERE id = 1", String.class);
        }
        assertThat(st).isEqualTo("COMPLETED");
        assertThat(plain.queryForObject("SELECT count(*) FROM profanity_hit_log", Long.class)).isZero();
    }

    @Test
    void staleRunningRecordsAreMarkedInterrupted() {
        when(logs.markStale(any(Instant.class), any(Instant.class))).thenReturn(2);
        assertThat(svc.markStale()).isEqualTo(2);
        when(logs.markStale(any(Instant.class), any(Instant.class))).thenThrow(new IllegalStateException("db"));
        assertThat(svc.markStale()).isZero();
    }
}
