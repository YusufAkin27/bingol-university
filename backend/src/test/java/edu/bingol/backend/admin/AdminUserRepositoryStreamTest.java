package edu.bingol.backend.admin;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import edu.bingol.backend.analytics.ActivityRepository;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * FIX-P09 (A08#9): kullanici CSV akisi 1000'lik sayfalarla okunur (tum sonuc heap'e alinmaz); sayfalar arasi tekrar ya
 * da atlama yok, limit korunur, siralama istenen yonde.
 */
class AdminUserRepositoryStreamTest {

    private JdbcTemplate jdbc;
    private AdminUserRepository repo;

    @BeforeEach
    void setUp() {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:ausr" + UUID.randomUUID().toString().replace("-", "")
                + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE app_user (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR(254), "
                + "display_name VARCHAR(100), faculty VARCHAR(100), department VARCHAR(100), class_year SMALLINT, "
                + "language VARCHAR(5), role VARCHAR(10) DEFAULT 'USER', status VARCHAR(16) DEFAULT 'ACTIVE', "
                + "email_verified BOOLEAN DEFAULT TRUE, created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP, "
                + "last_seen_at TIMESTAMP WITH TIME ZONE, avatar_url VARCHAR(300), two_factor_enabled BOOLEAN DEFAULT FALSE)");
        for (int i = 0; i < 2300; i++) {
            jdbc.update("INSERT INTO app_user (email, display_name, language) VALUES (?, ?, 'tr')",
                    "u" + i + "@bingol.edu.tr", "Kisi " + i);
        }
        repo = new AdminUserRepository(new NamedParameterJdbcTemplate(jdbc), Mockito.mock(ActivityRepository.class));
    }

    private static UserFilter all() {
        return new UserFilter(null, null, null, null, null, null, null, null, null, null, null, null, null);
    }

    @Test
    void streamsAllRowsAcrossPagesWithoutDuplicatesOrGaps() {
        List<Long> ids = new ArrayList<>();
        repo.stream(all(), UserFilter.orderBy("createdAt,asc"), 50_000, r -> ids.add(r.id()));
        assertEquals(2300, ids.size());
        assertEquals(2300, ids.stream().distinct().count());
        for (int i = 1; i < ids.size(); i++) {
            assertTrue(ids.get(i - 1) < ids.get(i));
        }
    }

    @Test
    void limitIsHonoredAcrossPageBoundary() {
        List<Long> ids = new ArrayList<>();
        repo.stream(all(), UserFilter.orderBy(null), 1500, r -> ids.add(r.id()));
        assertEquals(1500, ids.size());
        assertEquals(1500, ids.stream().distinct().count());
        assertTrue(ids.get(0) > ids.get(1)); // varsayilan: en yeni once
    }
}
