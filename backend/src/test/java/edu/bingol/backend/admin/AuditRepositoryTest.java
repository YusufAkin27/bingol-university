/** Denetim kaydi v2 (H2): alanlar, suzgecler, CSV kacisi, sohbet erisim kaydi listesi. */
class AuditRepositoryTest {

    private JdbcTemplate jdbc;
    private AuditRepository repo;
    private AuditController controller;

    @BeforeEach
    void setUp() {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:audit" + UUID.randomUUID().toString().replace("-", "")
                + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE app_user (id BIGINT PRIMARY KEY, email VARCHAR(254))");
        jdbc.execute("CREATE TABLE admin_audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT, "
                + "admin_email VARCHAR(254), method VARCHAR(8) NOT NULL, path VARCHAR(300) NOT NULL, status INTEGER NOT NULL, "
                + "ip VARCHAR(64), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, target_type VARCHAR(32), "
                + "target_id VARCHAR(64), reason VARCHAR(300), summary VARCHAR(500), request_id VARCHAR(64))");
        jdbc.execute("CREATE TABLE message_access_audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "admin_id BIGINT NOT NULL, conversation_id BIGINT NOT NULL, message_count INT NOT NULL, "
                + "from_message_id BIGINT, to_message_id BIGINT, reason VARCHAR(500) NOT NULL, ip VARCHAR(64), "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, target_user_id BIGINT, kind VARCHAR(24))");
        jdbc.update("INSERT INTO app_user VALUES (5, 'root@bingol.edu.tr'), (6, 'ops@bingol.edu.tr')");
        var named = new NamedParameterJdbcTemplate(jdbc);
        repo = new AuditRepository(named);
        controller = new AuditController(repo, new MessageAccessAuditReader(named));
    }

    private void add(Long admin, String method, String path, int status, String type, String id, String reason,
                     String summary, String at) {
        repo.insert(admin, null, method, path, status, "10.0.0.1",
                new AuditRepository.Details(type, id, reason, summary, "req-" + path.hashCode()));
        if (at != null) {
            jdbc.update("UPDATE admin_audit SET created_at = ? WHERE id = (SELECT MAX(id) FROM admin_audit)",
                    Timestamp.from(Instant.parse(at)));
        }
    }

    private void seed() {
        add(5L, "PATCH", "/api/admin/users/3/role", 204, "USER", "3", "yetki duzeltme", "rol -> USER", "2026-10-01T10:00:00Z");
        add(5L, "DELETE", "/api/admin/users/4", 204, "USER", "4", "talep uzerine", null, "2026-10-10T10:00:00Z");
        add(6L, "PUT", "/api/admin/settings/maintenance_mode", 403, "SETTING", "maintenance_mode", null, null,
                "2026-10-20T10:00:00Z");
        add(6L, "POST", "/api/admin/faq", 201, "FAQ", null, null, null, "2026-10-25T10:00:00Z");
    }

    private AuditRepository.Filter f(Long admin, String method, String q, String from, String to, String tt, String tid,
                                     String status) {
        return new AuditRepository.Filter(admin, method, q, AuditController.parseFrom(from), AuditController.parseTo(to),
                tt, tid, status);
    }

    @Test
    void insertStoresAllV2FieldsAndEmailFromUser() {
        add(5L, "PATCH", "/api/admin/users/3/role", 204, "USER", "3", "yetki duzeltme", "rol -> USER", null);

        AuditRow r = repo.page(f(null, null, null, null, null, null, null, null), 0, 10).get(0);

        assertEquals("root@bingol.edu.tr", r.adminEmail());
        assertEquals("USER", r.targetType());
        assertEquals("3", r.targetId());
        assertEquals("yetki duzeltme", r.reason());
        assertEquals("rol -> USER", r.summary());
        assertTrue(r.requestId().startsWith("req-"));
    }

    @Test
    void v1InsertLeavesNewColumnsNull() {
        repo.insert(null, "basic-admin", "POST", "/api/admin/sync", 200, "1.2.3.4");

        AuditRow r = repo.page(new AuditRepository.Filter(null, null, null), 0, 10).get(0);

        assertEquals("basic-admin", r.adminEmail());
        assertNull(r.targetType());
        assertNull(r.reason());
    }

    @Test
    void filtersByTargetAdminMethodStatusAndText() {
        seed();
        assertEquals(2, repo.count(f(null, null, null, null, null, "user", null, null)));
        assertEquals(1, repo.count(f(null, null, null, null, null, "USER", "4", null)));
        assertEquals(2, repo.count(f(5L, null, null, null, null, null, null, null)));
        assertEquals(1, repo.count(f(null, "delete", null, null, null, null, null, null)));
        assertEquals(1, repo.count(f(null, null, null, null, null, null, null, "403")));
        assertEquals(3, repo.count(f(null, null, null, null, null, null, null, "2xx")));
        assertEquals(1, repo.count(f(null, null, null, null, null, null, null, "4xx")));
        assertEquals(0, repo.count(f(null, null, null, null, null, null, null, "bogus")));
        assertEquals(1, repo.count(f(null, null, "talep", null, null, null, null, null))); // sebep icinde arar
        assertEquals(1, repo.count(f(null, null, "maintenance", null, null, null, null, null))); // hedef kimligi
        assertEquals(2, repo.count(f(null, null, "ops@bingol", null, null, null, null, null)));
    }

    @Test
    void filtersByDateRangeWithInclusiveToDay() {
        seed();
        // 10 Ekim gunu dahil: 1 ve 10 Ekim kayitlari
        assertEquals(2, repo.count(f(null, null, null, "2026-10-01", "2026-10-10", null, null, null)));
        assertEquals(1, repo.count(f(null, null, null, "2026-10-02", "2026-10-10", null, null, null)));
        assertEquals(2, repo.count(f(null, null, null, "2026-10-15T00:00:00Z", null, null, null, null)));
        assertThrows(ApiException.class, () -> AuditController.parseFrom("not-a-date"));
    }

    @Test
    void paginationNewestFirst() {
        seed();
        List<AuditRow> p0 = repo.page(f(null, null, null, null, null, null, null, null), 0, 3);
        List<AuditRow> p1 = repo.page(f(null, null, null, null, null, null, null, null), 1, 3);
        assertEquals(3, p0.size());
        assertEquals(1, p1.size());
        assertTrue(p0.get(0).id() > p0.get(1).id());
    }

    @Test
    void csvEscapesFormulasAndStaysUtf8() throws Exception {
        add(5L, "POST", "/api/admin/faq", 201, "FAQ", null, "=HYPERLINK(\"http://x\")", "+cmd|calc, \"q\"", null);
        add(5L, "POST", "/api/admin/faq", 201, "FAQ", null, "@SUM(A1)", "yeni\nsatir", null);
        MockHttpServletResponse res = new MockHttpServletResponse();

        controller.exportCsv(null, null, null, null, null, null, null, null, res);

        String csv = res.getContentAsString(StandardCharsets.UTF_8);
        assertTrue(csv.startsWith(Csv.BOM + "id,at,adminId,adminEmail,method,path,status,targetType,targetId,reason,"
                + "summary,requestId,ip\r\n"));
        assertTrue(csv.contains("'=HYPERLINK"), csv);
        assertTrue(csv.contains("'+cmd|calc"), csv);
        assertTrue(csv.contains("'@SUM(A1)"), csv);
        assertTrue(csv.contains("\"yeni\nsatir\""), csv);
        assertTrue(res.getContentType().startsWith("text/csv"));
        assertEquals("no-store", res.getHeader("Cache-Control"));
        // formul onekli hicbir hucre kacissiz kalmaz
        for (String line : csv.split("\r\n")) {
            assertTrue(!line.contains(",=") && !line.contains(",+") && !line.contains(",@"), line);
        }
    }

    @Test
    void csvIsCappedAndSelfAuditSummaryIsSet() throws Exception {
        for (int i = 0; i < 5; i++) {
            add(5L, "POST", "/api/admin/faq", 201, "FAQ", null, null, null, null);
        }
        var ctx = new org.springframework.mock.web.MockHttpServletRequest();
        org.springframework.web.context.request.RequestContextHolder.setRequestAttributes(
                new org.springframework.web.context.request.ServletRequestAttributes(ctx));
        try {
            MockHttpServletResponse res = new MockHttpServletResponse();
            controller.exportCsv(null, null, null, null, null, null, null, null, res);

            AuditContext.Data d = AuditContext.peek(ctx);
            assertEquals("AUDIT", d.targetType());
            assertEquals("csv satir=5", d.summary());
        } finally {
            org.springframework.web.context.request.RequestContextHolder.resetRequestAttributes();
        }
        assertEquals(50_000, AuditController.CSV_MAX_ROWS);
    }

    @Test
    void messageAccessListFiltersAndNeverReturnsContent() {
        jdbc.update("INSERT INTO message_access_audit (admin_id, conversation_id, message_count, reason, ip, created_at, "
                + "target_user_id, kind) VALUES (5, 10, 3, 'sikayet incelemesi 77', '1.1.1.1', ?, 1, 'VIEW_MESSAGES')",
                Timestamp.from(Instant.parse("2026-10-05T10:00:00Z")));
        jdbc.update("INSERT INTO message_access_audit (admin_id, conversation_id, message_count, reason, ip, created_at, "
                + "target_user_id, kind) VALUES (6, 11, 1, 'yonetici sohbet goruntuleme', '1.1.1.2', ?, 2, 'FEED')",
                Timestamp.from(Instant.parse("2026-10-06T10:00:00Z")));

        var all = controller.messageAccess(null, null, null, null, null, null, null, 0, 20);
        assertEquals(2, all.totalItems());
        assertEquals("FEED", all.items().get(0).kind()); // en yeni once
        assertEquals("ops@bingol.edu.tr", all.items().get(0).adminEmail());

        assertEquals(1, controller.messageAccess(5L, null, null, null, null, null, null, 0, 20).totalItems());
        assertEquals(1, controller.messageAccess(null, 2L, null, null, null, null, null, 0, 20).totalItems());
        assertEquals(1, controller.messageAccess(null, null, 10L, null, null, null, null, 0, 20).totalItems());
        assertEquals(1, controller.messageAccess(null, null, null, "feed", null, null, null, 0, 20).totalItems());
        assertEquals(1, controller.messageAccess(null, null, null, null, "incelemesi", null, null, 0, 20).totalItems());
        assertEquals(1, controller.messageAccess(null, null, null, null, null, "2026-10-05", "2026-10-05", 0, 20).totalItems());
        assertEquals("sikayet incelemesi 77", controller.messageAccess(5L, null, null, null, null, null, null, 0, 20)
                .items().get(0).reason());
    }

    @Test
    void csvCellsMatchHeaderWidth() {
        var r = new AuditRow(1L, null, null, "GET", "/p", 200, "t", null, null, null, null, null, null);
        assertEquals(AuditController.CSV_HEADER.size(), AuditController.csvCells(r).size());
        List<String> sink = new ArrayList<>();
        repo.stream(new AuditRepository.Filter(null, null, null), 10, x -> sink.add(x.path()));
        assertTrue(sink.isEmpty());
    }
}
