/** Sikayet baglami: mesaj +-10, silinmis, USER ortak sohbet, icerik ozeti, ek, denetim. */
class AdminReportContextServiceTest {

    private static final long ADMIN = 900L;
    private static final long ALICE = 1L; // sikayet eden
    private static final long BOB = 2L;   // sikayet edilen
    private static final long DM = 10L;

    private final CryptoTestSupport t = new CryptoTestSupport();
    private final EnvelopeMessageCipher cipher =
            t.cipher(t.keyService(CryptoTestSupport.provider("k1:" + CryptoTestSupport.b64(1), "")));
    private final ReportRepository repo = mock(ReportRepository.class);
    private final Map<Long, Report> db = new ConcurrentHashMap<>();
    private AdminReportContextService svc;
    private int seq;

    @BeforeEach
    void setUp() {
        var j = t.jdbc;
        j.execute("CREATE TABLE app_user (id BIGINT PRIMARY KEY, display_name VARCHAR(100), avatar_url VARCHAR(300), "
                + "email VARCHAR(100))");
        j.execute("CREATE TABLE conversation (id BIGINT PRIMARY KEY, type VARCHAR(10), title VARCHAR(100), "
                + "last_message_id BIGINT, last_message_at TIMESTAMP)");
        j.execute("CREATE TABLE conversation_member (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "conversation_id BIGINT, user_id BIGINT, role VARCHAR(10) DEFAULT 'MEMBER', joined_at TIMESTAMP, "
                + "left_at TIMESTAMP, hidden_at TIMESTAMP, cleared_up_to_message_id BIGINT DEFAULT 0, "
                + "archived_at TIMESTAMP, muted_until TIMESTAMP, last_read_message_id BIGINT DEFAULT 0, "
                + "last_delivered_message_id BIGINT DEFAULT 0)");
        j.execute("CREATE TABLE message (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id BIGINT, "
                + "sender_id BIGINT, client_id VARCHAR(64), created_at TIMESTAMP, body_ciphertext BYTEA, body_nonce BYTEA, "
                + "key_version INT, reply_to_message_id BIGINT, edited_at TIMESTAMP, deleted_at TIMESTAMP, "
                + "deleted_by BIGINT, hidden_at TIMESTAMP, suppressed BOOLEAN DEFAULT FALSE)");
        j.execute("CREATE TABLE message_reaction (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "message_id BIGINT, user_id BIGINT, emoji VARCHAR(16))");
        j.execute("CREATE TABLE message_revision (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "message_id BIGINT, body_ciphertext BYTEA, body_nonce BYTEA, key_version INT, revised_at TIMESTAMP)");
        j.execute("CREATE TABLE message_attachment (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "conversation_id BIGINT, uploader_id BIGINT, message_id BIGINT, kind VARCHAR(16), content_type VARCHAR(40), "
                + "width INT, height INT, duration_ms INT, bytes BIGINT, view_once BOOLEAN DEFAULT FALSE, "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, purged_at TIMESTAMP, hidden_at TIMESTAMP)");
        j.execute("CREATE TABLE message_attachment_view (attachment_id BIGINT, user_id BIGINT, viewed_at TIMESTAMP)");
        j.execute("CREATE TABLE user_block (blocker_id BIGINT, blocked_id BIGINT)");
        j.execute("CREATE TABLE report (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reporter_id BIGINT, "
                + "target_type VARCHAR(16), target_id BIGINT, reason VARCHAR(32), status VARCHAR(16), "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        j.execute("CREATE TABLE moderation_strike (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "user_id BIGINT, revoked_at TIMESTAMP)");
        j.execute("CREATE TABLE community_post (id BIGINT PRIMARY KEY, community_id BIGINT, author_id BIGINT, "
                + "content VARCHAR(2000), image_url VARCHAR(300), deleted BOOLEAN, created_at TIMESTAMP)");
        j.update("INSERT INTO app_user VALUES (1, 'Alice', NULL, 'a@bingol.edu.tr'), (2, 'Bob', NULL, 'b@bingol.edu.tr'), "
                + "(3, 'Carol', NULL, 'c@bingol.edu.tr'), (900, 'Admin', NULL, 'x@bingol.edu.tr')");
        j.update("INSERT INTO conversation VALUES (10, 'DIRECT', NULL, NULL, NULL)");
        Timestamp early = Timestamp.from(Instant.parse("2026-01-01T00:00:00Z"));
        for (long u : new long[] {ALICE, BOB}) {
            j.update("INSERT INTO conversation_member (conversation_id, user_id, joined_at) VALUES (10, ?, ?)", u, early);
        }
        when(repo.findById(anyLong())).thenAnswer(inv -> Optional.ofNullable(db.get(inv.<Long>getArgument(0))));
        var crypto = new AdminDecryptService(CryptoTestSupport.props("", "", true, 200), cipher,
                new MessageAccessAuditRepository(j));
        svc = new AdminReportContextService(j, repo, crypto, new AdminChatViewerService(j, crypto));
    }

    private long msg(long sender, String text) {
        String client = "c" + (++seq);
        Sealed s = cipher.encryptText(DM, MessageCodec.context(sender, client), text);
        t.jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, created_at, body_ciphertext, "
                + "body_nonce, key_version) VALUES (10, ?, ?, ?, ?, ?, ?)", sender, client,
                Timestamp.from(Instant.parse("2026-02-01T00:00:00Z").plusSeconds(seq * 60L)), s.ciphertext(), s.nonce(),
                s.keyVersion());
        return t.jdbc.queryForObject("SELECT MAX(id) FROM message", Long.class);
    }

    private long report(ReportTargetType type, long target, long reporter) {
        Report r = new Report();
        r.setId((long) (db.size() + 1));
        r.setReporterId(reporter);
        r.setTargetType(type);
        r.setTargetId(target);
        r.setReason(ReportReason.HARASSMENT);
        r.setNote("kufur etti");
        db.put(r.getId(), r);
        t.jdbc.update("INSERT INTO report (reporter_id, target_type, target_id, reason, status) "
                + "VALUES (?, ?, ?, 'HARASSMENT', 'OPEN')", reporter, type.name(), target);
        return r.getId();
    }

    @Test
    void messageContextHasWindowReportedFlagAndDeletedBodyAndAudit() {
        long reported = 0;
        for (int i = 1; i <= 30; i++) {
            long id = msg(i % 2 == 0 ? BOB : ALICE, "m" + i);
            if (i == 16) {
                reported = id;
            }
        }
        t.jdbc.update("UPDATE message SET deleted_at = CURRENT_TIMESTAMP, deleted_by = ? WHERE id = ?", BOB, reported);
        // kullanici "sohbeti sil" demis ve ayrilmis olsa da yonetici gorur
        t.jdbc.update("UPDATE conversation_member SET cleared_up_to_message_id = 999, left_at = CURRENT_TIMESTAMP, "
                + "hidden_at = CURRENT_TIMESTAMP WHERE user_id = ?", ALICE);
        long rid = report(ReportTargetType.MESSAGE, reported, ALICE);
        report(ReportTargetType.MESSAGE, reported, 3L);

        var d = svc.detail(ADMIN, rid, "10.0.0.1");

        assertEquals("Alice", d.reporter().displayName());
        assertEquals("b@bingol.edu.tr", d.reportedUser().email());
        var c = d.context();
        assertEquals("MESSAGE", c.type());
        assertEquals(21, c.messages().size()); // 10 once + kendisi + 10 sonra
        var rep = c.messages().stream().filter(m -> m.reported()).toList();
        assertEquals(1, rep.size());
        assertEquals(reported, rep.get(0).message().id());
        assertEquals("m16", rep.get(0).message().text()); // silinmis ama cozulu
        assertTrue(rep.get(0).message().deleted());
        assertEquals(DM, c.conversation().id());
        assertEquals("/admin/users/2/messages?c=10&m=" + reported, d.viewerPath());
        assertEquals(1, d.relatedReports().sameTargetCount());
        assertEquals(1, d.relatedReports().last().size());
        assertEquals(1, t.jdbc.queryForObject("SELECT COUNT(*) FROM message_access_audit WHERE kind = 'REPORT_CONTEXT'",
                Integer.class));
        assertNotNull(c.userStats());
    }

    @Test
    void userContextShowsLast20OfSharedDirectChatAndStrikeCounts() {
        for (int i = 1; i <= 25; i++) {
            msg(i % 2 == 0 ? BOB : ALICE, "u" + i);
        }
        t.jdbc.update("INSERT INTO moderation_strike (user_id, revoked_at) VALUES (2, NULL), (2, CURRENT_TIMESTAMP)");
        report(ReportTargetType.USER, BOB, 3L);
        long rid = report(ReportTargetType.USER, BOB, ALICE);

        var d = svc.detail(ADMIN, rid, "ip");

        assertEquals("USER", d.context().type());
        assertEquals(20, d.context().messages().size());
        assertEquals("u25", d.context().messages().get(19).message().text());
        assertTrue(d.context().messages().stream().noneMatch(m -> m.reported()));
        assertEquals(2, d.context().userStats().reportsAgainstUser());
        assertEquals(1, d.context().userStats().activeStrikes());
        assertEquals(2, d.context().userStats().totalStrikes());
        assertEquals("/admin/users/2/messages?c=10", d.viewerPath());
    }

    @Test
    void postContextShowsContentSummaryWithoutAudit() {
        t.jdbc.update("INSERT INTO community_post VALUES (5, 7, 2, 'spam icerik', NULL, FALSE, CURRENT_TIMESTAMP)");
        long rid = report(ReportTargetType.POST, 5, ALICE);

        var d = svc.detail(ADMIN, rid, "ip");

        assertEquals("spam icerik", d.context().content().text());
        assertEquals(7L, d.context().content().communityId());
        assertEquals(2L, d.reportedUser().id());
        assertEquals("/admin/users/2/messages", d.viewerPath());
        assertEquals(0, t.jdbc.queryForObject("SELECT COUNT(*) FROM message_access_audit", Integer.class));
    }

    @Test
    void imageReportShowsAttachmentAndUnknownReportIs404() {
        long m = msg(BOB, "foto");
        t.jdbc.update("INSERT INTO message_attachment (conversation_id, uploader_id, message_id, kind, content_type, width, "
                + "height, bytes, view_once) VALUES (10, 2, ?, 'IMAGE', 'image/webp', 8, 6, 100, TRUE)", m);
        long att = t.jdbc.queryForObject("SELECT MAX(id) FROM message_attachment", Long.class);
        long rid = report(ReportTargetType.MESSAGE_IMAGE, att, ALICE);

        var d = svc.detail(ADMIN, rid, "ip");

        assertEquals(att, d.context().reportedAttachmentId());
        var a = d.context().messages().get(0).message().attachments().get(0);
        assertTrue(a.viewOnce());
        assertNotNull(a.previewUrl());
        assertFalse(d.context().messages().isEmpty());
        assertEquals("REPORT_NOT_FOUND", assertThrows(ApiException.class, () -> svc.detail(ADMIN, 999, "ip")).code());
    }
}
