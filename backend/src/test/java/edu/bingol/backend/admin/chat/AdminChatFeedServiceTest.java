    @Test
    void feedReturnsAllConversationsNewestFirstWithDeletedAndSuppressed() {
        long a = msg(DM, ALICE, "bir");
        long b = msg(GROUP, CAROL, "iki");
        long c = msg(OTHER, BOB, "uc");
        t.jdbc.update("UPDATE message SET deleted_at = CURRENT_TIMESTAMP, deleted_by = ? WHERE id = ?", BOB, a);
        t.jdbc.update("UPDATE message SET suppressed = TRUE WHERE id = ?", b);

        FeedPage p = svc.messages(ADMIN, null, 30, null, null, null, null, null, null, null, null, "ip");

        assertEquals(3, p.items().size());
        assertEquals(c, p.items().get(0).message().id()); // en yeni once
        assertEquals("uc", p.items().get(0).message().text());
        assertEquals("Bob · Carol", p.items().get(0).conversation().title()); // birebir basligi uyelerden
        var sup = p.items().get(1).message();
        assertTrue(sup.suppressed());
        assertEquals("Grup", p.items().get(1).conversation().title());
        var del = p.items().get(2).message();
        assertEquals("bir", del.text()); // silinmis de cozulu
        assertTrue(del.deleted());
        assertEquals("EVERYONE_BY_OTHER", del.deleteKind());
        assertNull(p.nextCursor());
    }

