    @Test
    void feedWritesAuditPerConversationAndNoContentIfAuditFails() {
        msg(DM, ALICE, "a");
        msg(GROUP, CAROL, "b");
        msg(GROUP, CAROL, "c");

        svc.messages(ADMIN, null, 30, null, null, null, null, null, null, null, null, "10.0.0.9");

        assertEquals(2, audits("FEED"));
        var row = t.jdbc.queryForMap("SELECT * FROM message_access_audit WHERE conversation_id = " + GROUP);
        assertEquals(2, ((Number) row.get("MESSAGE_COUNT")).intValue());
        assertEquals(ADMIN, ((Number) row.get("ADMIN_ID")).longValue());
        assertEquals("10.0.0.9", row.get("IP"));

        t.jdbc.execute("DROP TABLE message_access_audit");
        assertEquals("CRYPTO_UNAVAILABLE", assertThrows(ApiException.class,
                () -> svc.messages(ADMIN, null, 30, null, null, null, null, null, null, null, null, "ip")).code());
    }

