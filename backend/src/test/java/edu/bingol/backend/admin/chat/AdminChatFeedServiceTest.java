        t.jdbc.update("UPDATE message SET deleted_at = CURRENT_TIMESTAMP WHERE id = ?", m3);

        assertEquals(2, svc.media(ADMIN, null, 30, "image", null, null, null, null, null, null, "desc", "ip").items().size());
        assertEquals(1, svc.media(ADMIN, null, 30, "VIDEO", null, null, null, null, null, null, "desc", "ip").items().size());
        assertEquals(1, svc.media(ADMIN, null, 30, "ALL", true, null, null, null, null, null, "desc", "ip").items().size());
        assertEquals(2, svc.media(ADMIN, null, 30, null, false, null, null, null, null, null, "desc", "ip").items().size());
        assertEquals(1, svc.media(ADMIN, null, 30, null, null, true, null, null, null, null, "desc", "ip").items().size());
        assertEquals(2, svc.media(ADMIN, null, 30, null, null, null, BOB, null, null, null, "desc", "ip").items().size());
        assertEquals(1, svc.media(ADMIN, null, 30, null, null, null, null, GROUP, null, null, "desc", "ip").items().size());
