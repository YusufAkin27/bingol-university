    private long msg(long conv, long sender, String text) {
        String client = "c" + (++seq);
        Instant at = Instant.parse("2026-02-01T00:00:00Z").plusSeconds(seq * 60L);
        Sealed s = cipher.encryptText(conv, MessageCodec.context(sender, client), text);
        t.jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, created_at, body_ciphertext, "
                + "body_nonce, key_version) VALUES (?, ?, ?, ?, ?, ?, ?)", conv, sender, client, Timestamp.from(at),
                s.ciphertext(), s.nonce(), s.keyVersion());
        return t.jdbc.queryForObject("SELECT MAX(id) FROM message", Long.class);
    }

    private long att(long messageId, long conv, long uploader, String kind, boolean viewOnce) {
        t.jdbc.update("INSERT INTO message_attachment (conversation_id, uploader_id, message_id, kind, content_type, "
                + "width, height, bytes, view_once) VALUES (?, ?, ?, ?, 'image/webp', 8, 6, 100, ?)", conv, uploader,
                messageId, kind, viewOnce);
        return t.jdbc.queryForObject("SELECT MAX(id) FROM message_attachment", Long.class);
    }

    private int audits(String kind) {
        return t.jdbc.queryForObject("SELECT COUNT(*) FROM message_access_audit WHERE kind = ?", Integer.class, kind);
    }

