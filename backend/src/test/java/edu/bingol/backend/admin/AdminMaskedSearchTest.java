package edu.bingol.backend.admin;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import edu.bingol.backend.admin.AdminDtos.AuditRow;
import edu.bingol.backend.admin.rbac.AdminPermissionContext;
import edu.bingol.backend.admin.rbac.AdminProfile;
import edu.bingol.backend.common.ApiException;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.mock.web.MockHttpServletRequest;
import org.springframework.web.context.request.RequestContextHolder;
import org.springframework.web.context.request.ServletRequestAttributes;

/**
 * T-018/T-019: `users.pii` olmayan profilde (VIEWER) denetim satirlarinin e-posta/IP maskelemesi ve `q=` aramasinin
 * e-posta uzerinden yurumemesi (maskeli adresi harf harf yeniden kurma yolu). Istek baglami elle kurulur.
 */
class AdminMaskedSearchTest {

    private AuditRepository repo;

    @BeforeEach
    void setUp() {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:amask" + UUID.randomUUID().toString().replace("-", "")
                + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE app_user (id BIGINT PRIMARY KEY, email VARCHAR(254))");
        jdbc.execute("CREATE TABLE admin_audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, admin_id BIGINT, "
                + "admin_email VARCHAR(254), method VARCHAR(8) NOT NULL, path VARCHAR(300) NOT NULL, status INTEGER NOT NULL, "
                + "ip VARCHAR(64), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, target_type VARCHAR(32), "
                + "target_id VARCHAR(64), reason VARCHAR(300), summary VARCHAR(500), request_id VARCHAR(64))");
        jdbc.update("INSERT INTO app_user VALUES (5, 'root.yonetici@bingol.edu.tr')");
        repo = new AuditRepository(new NamedParameterJdbcTemplate(jdbc));
        repo.insert(5L, null, "GET", "/api/admin/users", 200, "10.20.30.40");
    }

    @AfterEach
    void clear() {
        RequestContextHolder.resetRequestAttributes();
    }

    private static void as(AdminProfile p) {
        MockHttpServletRequest req = new MockHttpServletRequest();
        req.setAttribute(AdminPermissionContext.class.getName(), new AdminPermissionContext(p, false));
        RequestContextHolder.setRequestAttributes(new ServletRequestAttributes(req));
    }

    @Test
    void viewerSeesMaskedAdminEmailAndIpInAuditRows() {
        as(AdminProfile.VIEWER);
        List<AuditRow> rows = repo.page(new AuditRepository.Filter(null, null, null), 0, 10);
        assertEquals(1, rows.size());
        assertEquals("r***@bingol.edu.tr", rows.get(0).adminEmail());
        assertEquals("***", rows.get(0).ip());
    }

    @Test
    void fullSeesAuditRowsAsStored() {
        as(AdminProfile.FULL);
        AuditRow r = repo.page(new AuditRepository.Filter(null, null, null), 0, 10).get(0);
        assertEquals("root.yonetici@bingol.edu.tr", r.adminEmail());
        assertEquals("10.20.30.40", r.ip());
    }

    @Test
    void auditSearchByAdminEmailFindsNothingForViewerButWorksForFull() {
        String q = "root.yonetici";
        as(AdminProfile.VIEWER);
        assertEquals(0, repo.count(new AuditRepository.Filter(null, null, q)));
        as(AdminProfile.FULL);
        assertEquals(1, repo.count(new AuditRepository.Filter(null, null, q)));
    }

    @Test
    void userSearchSkipsEmailColumnForMaskedProfilesAndRequiresMinLength() {
        as(AdminProfile.VIEWER);
        UserFilter byMail = new UserFilter("ayse@bingol.edu.tr", null, null, null, null, null, null, null);
        String sql = byMail.where().sql();
        assertFalse(sql.contains("email"), sql);
        assertTrue(sql.contains("display_name"));
        assertThrows(ApiException.class,
                () -> new UserFilter("ay", null, null, null, null, null, null, null).where());

        as(AdminProfile.SUPPORT);
        assertFalse(byMail.where().sql().contains("email"));

        as(AdminProfile.FULL);
        assertTrue(byMail.where().sql().contains("email"));
        as(AdminProfile.MODERATOR);
        assertTrue(byMail.where().sql().contains("email"));
    }
}
