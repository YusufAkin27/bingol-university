    @Test
    void hideRejectsAlreadyHiddenModeratedDeletedAndPurged() {
        long a = msg(DIRECT, ALICE, "a");
        msgSvc.hide(ADMIN, a, REASON);
        assertEquals("MESSAGE_ALREADY_HIDDEN", code(() -> msgSvc.hide(ADMIN, a, REASON)));

        long moderated = msg(DIRECT, ALICE, "m"); // rapor karariyla gizlenmis
        t.jdbc.update("UPDATE message SET hidden_at = CURRENT_TIMESTAMP WHERE id = ?", moderated);
        assertEquals("MESSAGE_ALREADY_HIDDEN", code(() -> msgSvc.hide(ADMIN, moderated, REASON)));
        // moderasyon gizlemesini yonetici buradan geri aciamaz
        assertEquals("MESSAGE_NOT_ADMIN_HIDDEN", code(() -> msgSvc.unhide(ADMIN, moderated, REASON)));
        assertNotNull(col("hidden_at", moderated));

        long deleted = msg(DIRECT, ALICE, "d"); // herkes icin silinmis
        t.jdbc.update("UPDATE message SET deleted_at = CURRENT_TIMESTAMP, deleted_by = ? WHERE id = ?", ALICE, deleted);
        assertEquals("MESSAGE_ALREADY_HIDDEN", code(() -> msgSvc.hide(ADMIN, deleted, REASON)));

        long p = msg(DIRECT, ALICE, "p");
        msgSvc.purge(ADMIN, p, LONG_REASON);
        assertEquals("MESSAGE_ALREADY_PURGED", code(() -> msgSvc.hide(ADMIN, p, REASON)));
        assertEquals("MESSAGE_ALREADY_PURGED", code(() -> msgSvc.unhide(ADMIN, p, REASON)));
    }

