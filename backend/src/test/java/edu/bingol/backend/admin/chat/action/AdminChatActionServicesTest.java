    private long msg(long conv, long sender, String text) {
        String client = "c" + (++seq);
        Sealed s = cipher.encryptText(conv, MessageCodec.context(sender, client), text);
        Instant at = Instant.parse("2026-02-01T00:00:00Z").plusSeconds(seq * 60L);
        t.jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, created_at, body_ciphertext, "
                + "body_nonce, key_version) VALUES (?, ?, ?, ?, ?, ?, ?)", conv, sender, client, Timestamp.from(at),
                s.ciphertext(), s.nonce(), s.keyVersion());
        return t.jdbc.queryForObject("SELECT MAX(id) FROM message", Long.class);
    }

    private static String code(Runnable r) {
        return assertThrows(ApiException.class, r::run).code();
    }

    private Instant col(String column, long id) {
        Timestamp ts = t.jdbc.queryForObject("SELECT " + column + " FROM message WHERE id = ?", Timestamp.class, id);
        return ts == null ? null : ts.toInstant();
    }

    /** Entity gorunumu (kullanici API'si) icin satir -> Message. */
    private Message entity(long id) {
        return t.jdbc.queryForObject("SELECT id, conversation_id, sender_id, client_id, created_at, hidden_at, "
                + "admin_hidden_at, purged_at, deleted_at FROM message WHERE id = ?", (rs, i) -> {
            Message m = new Message();
            m.setId(rs.getLong("id"));
            m.setConversationId(rs.getLong("conversation_id"));
            m.setSenderId(rs.getLong("sender_id"));
            m.setClientId(rs.getString("client_id"));
            m.setCreatedAt(rs.getTimestamp("created_at").toInstant());
            m.setHiddenAt(rs.getTimestamp("hidden_at") == null ? null : rs.getTimestamp("hidden_at").toInstant());
            m.setAdminHiddenAt(rs.getTimestamp("admin_hidden_at") == null ? null : rs.getTimestamp("admin_hidden_at").toInstant());
            m.setPurgedAt(rs.getTimestamp("purged_at") == null ? null : rs.getTimestamp("purged_at").toInstant());
            m.setDeletedAt(rs.getTimestamp("deleted_at") == null ? null : rs.getTimestamp("deleted_at").toInstant());
            return m;
        }, id);
    }

