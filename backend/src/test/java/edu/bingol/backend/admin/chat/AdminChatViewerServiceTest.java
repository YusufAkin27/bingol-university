    @Test
    void deletedMessageIsDecryptedForAdminButNoBodyForUserApi() {
        long id = msg(CONV, ALICE, "gizli silinen metin");
        t.jdbc.update("UPDATE message SET deleted_at = ?, deleted_by = ? WHERE id = ?",
                Timestamp.from(Instant.parse("2026-03-01T00:00:00Z")), BOB, id);

        MessagePage p = svc.messages(ADMIN, ALICE, CONV, null, 50, "10.0.0.1");

        MessageItem it = p.items().get(0);
        assertEquals("gizli silinen metin", it.text());
        assertTrue(it.deleted());
        assertEquals(BOB, it.deletedBy());
        assertEquals("Bob", it.deletedByName());
        assertTrue(it.mine());
        assertEquals("Alice", it.senderName());

        // Kullanici API'si: ayni satir icin gorunum sabit metin doner, govde sizmaz
        Message m = new Message();
        m.setId(id);
        m.setConversationId(CONV);
        m.setSenderId(ALICE);
        m.setClientId("x");
        m.setBodyCiphertext(new byte[] {1, 2});
        m.setBodyNonce(new byte[] {3});
        m.setKeyVersion(1);
        m.setBody("gizli silinen metin"); // bellekte olsa bile
        m.setDeletedAt(Instant.now());
        MessageView v = MessageView.of(m);
        assertEquals(MessagingDtos.DELETED_TEXT, v.text());
        assertTrue(v.deleted());
        assertFalse(v.toString().contains("gizli silinen metin"));
    }

    @Test
    void hiddenAndEditedMessageShowRevisionHistory() {
        long id = msg(CONV, ALICE, "ilk surum");
        // duzenleme: eski surum revision'a, yeni surum mesaja
        String client = t.jdbc.queryForObject("SELECT client_id FROM message WHERE id = ?", String.class, id);
        Sealed old = cipher.encryptText(CONV, MessageCodec.context(ALICE, client), "ilk surum");
        t.jdbc.update("INSERT INTO message_revision (message_id, body_ciphertext, body_nonce, key_version, revised_at) "
                + "VALUES (?, ?, ?, ?, ?)", id, old.ciphertext(), old.nonce(), old.keyVersion(),
                Timestamp.from(Instant.parse("2026-02-01T00:01:00Z")));
        Sealed nw = cipher.encryptText(CONV, MessageCodec.context(ALICE, client), "ikinci surum");
        t.jdbc.update("UPDATE message SET body_ciphertext = ?, body_nonce = ?, key_version = ?, edited_at = ?, hidden_at = ? "
                + "WHERE id = ?", nw.ciphertext(), nw.nonce(), nw.keyVersion(),
                Timestamp.from(Instant.parse("2026-02-01T00:05:00Z")), Timestamp.from(Instant.now()), id);

        MessageItem it = svc.messages(ADMIN, ALICE, CONV, null, 50, "ip").items().get(0);

        assertEquals("ikinci surum", it.text());
        assertTrue(it.edited());
        assertTrue(it.hidden()); // moderasyonla gizlenmis olsa da yonetici cozer
        assertEquals(1, it.revisions().size());
        assertEquals("ilk surum", it.revisions().get(0).text());
    }

