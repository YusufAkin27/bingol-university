    @Test
    void adminSeesGroupMessagesOutsideMembershipWindowAndAfterLeaving() {
        Instant joined = Instant.parse("2026-02-10T00:00:00Z");
        t.jdbc.update("UPDATE conversation_member SET joined_at = ?, left_at = ?, hidden_at = CURRENT_TIMESTAMP, "
                + "archived_at = CURRENT_TIMESTAMP WHERE conversation_id = ? AND user_id = ?",
                Timestamp.from(joined), Timestamp.from(joined.plus(2, ChronoUnit.DAYS)), GROUP, ALICE);
        long before = msg(GROUP, CAROL, "katilmadan once", joined.minus(1, ChronoUnit.DAYS));
        msg(GROUP, CAROL, "uyeyken", joined.plus(1, ChronoUnit.DAYS));
        long after = msg(GROUP, CAROL, "ayrildiktan sonra", joined.plus(5, ChronoUnit.DAYS));
        // kullanici "sohbeti sil" demis olsa bile yonetici tum gecmisi gorur
        t.jdbc.update("UPDATE conversation_member SET cleared_up_to_message_id = ? WHERE conversation_id = ? AND user_id = ?",
                after, GROUP, ALICE);

        List<MessageItem> items = svc.messages(ADMIN, ALICE, GROUP, null, 50, "ip").items();

        assertEquals(3, items.size());
        assertEquals(before, items.get(0).id());
        var list = svc.conversations(ADMIN, ALICE, null, 20, "ip").items();
        var g = list.stream().filter(c -> c.id() == GROUP).findFirst().orElseThrow();
        assertTrue(g.left());
        assertTrue(g.state().hiddenByUser() && g.state().cleared() && g.state().archived());
        assertEquals(3, g.totalMessages());
    }

