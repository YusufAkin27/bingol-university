    private AdminChatViewerService service(boolean enabled) {
        var crypto = new AdminDecryptService(CryptoTestSupport.props("", "", enabled, 200), cipher,
                new MessageAccessAuditRepository(t.jdbc));
        return new AdminChatViewerService(t.jdbc, crypto);
    }

    /** Sifreli mesaj ekler; kimlik doner. at: zaman (artan olmali). */
    private long msg(long conv, long sender, String text) {
        return msg(conv, sender, text, Instant.parse("2026-02-01T00:00:00Z").plusSeconds(++seq * 60L));
    }

    private long msg(long conv, long sender, String text, Instant at) {
        String client = "c" + (++seq);
        Sealed s = cipher.encryptText(conv, MessageCodec.context(sender, client), text);
        t.jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, created_at, body_ciphertext, "
                + "body_nonce, key_version) VALUES (?, ?, ?, ?, ?, ?, ?)", conv, sender, client, Timestamp.from(at),
                s.ciphertext(), s.nonce(), s.keyVersion());
        long id = t.jdbc.queryForObject("SELECT MAX(id) FROM message", Long.class);
        t.jdbc.update("UPDATE conversation SET last_message_id = ?, last_message_at = ? WHERE id = ?", id,
                Timestamp.from(at), conv);
        return id;
    }

    private static String code(Runnable r) {
        return assertThrows(ApiException.class, r::run).code();
    }

    private int audits() {
        return t.jdbc.queryForObject("SELECT COUNT(*) FROM message_access_audit", Integer.class);
    }

