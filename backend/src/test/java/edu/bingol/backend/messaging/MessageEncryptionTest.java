/** Mesaj sifreleme entegrasyonu: codec, gecis isi, yonetici okuyucu, KVKK disa aktarimi (H2 + gercek sifreleme). */
class MessageEncryptionTest {

    private final CryptoTestSupport t = new CryptoTestSupport();
    private final JdbcTemplate jdbc = t.jdbc;
    private final MessageCipher cipher = t.cipher(t.keyService(CryptoTestSupport.provider(
            "k1:" + CryptoTestSupport.b64(7), "")));
    private final MessageCodec codec = new MessageCodec(cipher, jdbc);

    @BeforeEach
    void table() {
        jdbc.execute("CREATE TABLE message (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "conversation_id BIGINT NOT NULL, sender_id BIGINT NOT NULL, client_id VARCHAR(64) NOT NULL, "
                + "body VARCHAR(2000), body_ciphertext BYTEA, body_nonce BYTEA, key_version INT, "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, hidden_at TIMESTAMP)");
    }

    private static Message draft(long conv, long sender, String client) {
        Message m = new Message();
        m.setConversationId(conv);
        m.setSenderId(sender);
        m.setClientId(client);
        return m;
    }

    private long insertSealed(Message m, String text) {
        codec.seal(m, text);
        jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body_ciphertext, body_nonce, key_version) "
                        + "VALUES (?,?,?,?,?,?)", m.getConversationId(), m.getSenderId(), m.getClientId(),
                m.getBodyCiphertext(), m.getBodyNonce(), m.getKeyVersion());
        return jdbc.queryForObject("SELECT MAX(id) FROM message", Long.class);
    }

    @Test
    void sealProducesCiphertextAndOpenRestoresPlaintext() {
        Message m = draft(1, 5, "c-1");
        codec.seal(m, "Merhaba dünya 😀");
        assertNotNull(m.getBodyCiphertext());
        assertEquals(12, m.getBodyNonce().length);
        assertFalse(new String(m.getBodyCiphertext(), StandardCharsets.ISO_8859_1).contains("Merhaba"));

        Message loaded = draft(1, 5, "c-1"); // veritabanindan yeni yuklenmis gibi: duz metin yok
        loaded.setBodyCiphertext(m.getBodyCiphertext());
        loaded.setBodyNonce(m.getBodyNonce());
        loaded.setKeyVersion(m.getKeyVersion());
        assertEquals("Merhaba dünya 😀", codec.open(loaded).getBody());
    }

    @Test
    void ciphertextMovedToAnotherMessageIsUnreadableNotAnException() {
        Message a = draft(1, 5, "c-1");
        codec.seal(a, "a'nin mesaji");
        // Ayni konusma/gonderen, baska clientId'ye tasindi
        Message b = draft(1, 5, "c-2");
        b.setBodyCiphertext(a.getBodyCiphertext());
        b.setBodyNonce(a.getBodyNonce());
        b.setKeyVersion(a.getKeyVersion());
        assertNull(codec.open(b).getBody());
        assertTrue(MessageView.of(b).removed());
        assertEquals(edu.bingol.backend.messaging.dto.MessagingDtos.UNREADABLE_TEXT, MessageView.of(b).text());
        // Baska gonderen
        Message c = draft(1, 6, "c-1");
        c.setBodyCiphertext(a.getBodyCiphertext());
        c.setBodyNonce(a.getBodyNonce());
        c.setKeyVersion(a.getKeyVersion());
        assertNull(codec.open(c).getBody());
    }

    @Test
    void hiddenMessagesAreNotDecrypted() {
        Message m = draft(1, 5, "c-1");
        codec.seal(m, "gizlenecek");
        m.setBody(null);
        m.setHiddenAt(Instant.now());
        assertNull(codec.open(m).getBody());
        assertEquals("Bu mesaj kaldırıldı", MessageView.of(m).text());
    }

    @Test
    void sealFailureBecomesServiceUnavailable() {
        MessageCodec broken = new MessageCodec(cipherWithoutKeys(), jdbc);
        ApiException e = assertThrows(ApiException.class, () -> broken.seal(draft(1, 5, "c"), "x"));
        assertEquals("CRYPTO_UNAVAILABLE", e.code());
    }

    private MessageCipher cipherWithoutKeys() {
        return new MessageCipher() {
            @Override
            public edu.bingol.backend.crypto.Sealed encrypt(long c, byte[] ctx, byte[] p) {
                throw new edu.bingol.backend.crypto.CryptoException(
                        edu.bingol.backend.crypto.CryptoException.Reason.KEY_UNAVAILABLE, "yok");
            }

            @Override
            public byte[] decrypt(long c, byte[] ctx, edu.bingol.backend.crypto.Sealed s) {
                throw new UnsupportedOperationException();
            }
        };
    }

    @Test
    void legacyPlaintextRowsAreStillReadableDuringTransition() {
        jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body) VALUES (1, 5, 'old', 'eski duz metin')");
        Message m = draft(1, 5, "old");
        m.setId(jdbc.queryForObject("SELECT id FROM message WHERE client_id = 'old'", Long.class));
        assertEquals("eski duz metin", codec.open(m).getBody());
    }

    @Test
    void migratorEncryptsAllPlaintextRowsIdempotentlyAndNullsPlaintext() {
        for (int i = 0; i < 450; i++) {
            jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body) VALUES (?, ?, ?, ?)",
                    1 + (i % 3), 5, "c" + i, "metin " + i);
        }
        DataSource ds = jdbc.getDataSource();
        MessageEncryptionMigrator mig = new MessageEncryptionMigrator(jdbc, cipher, codec,
                new DataSourceTransactionManager(ds), true, true);
        assertEquals(450, mig.remaining());

        assertEquals(450, mig.migrateAll());
        assertEquals(0, mig.remaining());
        assertEquals(0, mig.migrateAll()); // ikinci kosu: is yok
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM message WHERE body IS NOT NULL", Integer.class));
        assertEquals(450, jdbc.queryForObject(
                "SELECT COUNT(*) FROM message WHERE body_ciphertext IS NOT NULL AND OCTET_LENGTH(body_nonce) = 12", Integer.class));

        // Satir tam olarak ayni baglamla cozulur
        Message m = draft(1, 5, "c0");
        var row = jdbc.queryForMap("SELECT body_ciphertext, body_nonce, key_version FROM message WHERE client_id = 'c0'");
        m.setBodyCiphertext((byte[]) row.get("BODY_CIPHERTEXT"));
        m.setBodyNonce((byte[]) row.get("BODY_NONCE"));
        m.setKeyVersion(((Number) row.get("KEY_VERSION")).intValue());
        assertEquals("metin 0", codec.open(m).getBody());
    }

    @Test
    void migratorKeepsPlaintextWhenConfiguredAndDisabledDoesNothing() {
        jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body) VALUES (1, 5, 'k', 'sakla')");
        MessageEncryptionMigrator keep = new MessageEncryptionMigrator(jdbc, cipher, codec,
                new DataSourceTransactionManager(jdbc.getDataSource()), true, false);
        keep.migrateAll();
        assertEquals("sakla", jdbc.queryForObject("SELECT body FROM message WHERE client_id = 'k'", String.class));
        assertEquals(0, keep.remaining()); // sifrelendi, ikinci kez islenmez

        jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body) VALUES (1, 5, 'd', 'bekler')");
        MessageEncryptionMigrator off = new MessageEncryptionMigrator(jdbc, cipher, codec,
                new DataSourceTransactionManager(jdbc.getDataSource()), false, true);
        off.scheduled(); // kapali: dokunmaz
        assertEquals(1, off.remaining());
    }

    @Test
    void migratorStopsAndKeepsRowsPlainWhenKeysAreUnavailable() {
        jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body) VALUES (1, 5, 'x', 'duz kalir')");
        MessageEncryptionMigrator mig = new MessageEncryptionMigrator(jdbc, cipherWithoutKeys(), codec,
                new DataSourceTransactionManager(jdbc.getDataSource()), true, true);
        mig.scheduled(); // istisna disari sizmaz
        assertEquals("duz kalir", jdbc.queryForObject("SELECT body FROM message WHERE client_id = 'x'", String.class));
        assertEquals(1, mig.remaining());
    }

    @Test
    void storeReaderFeedsAdminDecryptAndWritesAuditRow() {
        long id1 = insertSealed(draft(9, 5, "a"), "birinci");
        long id2 = insertSealed(draft(9, 6, "b"), "ikinci");
        jdbc.update("INSERT INTO message (conversation_id, sender_id, client_id, body) VALUES (9, 5, 'plain', 'duz')");
        MessageStoreReader reader = new MessageStoreReader(jdbc);
        AdminDecryptService svc = new AdminDecryptService(
                new edu.bingol.backend.crypto.CryptoProperties("", "", "", false, true, 300, 1024, 30, 200), Optional.of(reader), cipher,
                new MessageAccessAuditRepository(jdbc));

        var res = svc.decrypt(1, new AdminDecryptService.Request(9L, id1, id2 + 10, "sikayet 42 incelemesi"), "1.2.3.4");

        assertEquals(2, res.count()); // duz satir (sifresiz) okuyucudan gelmez
        assertEquals("birinci", res.messages().get(0).text());
        assertEquals("ikinci", res.messages().get(1).text());
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM message_access_audit WHERE conversation_id = 9", Integer.class));
        assertArrayEquals(MessageCodec.context(5L, "a"), reader.read(9, id1, id1, 5).get(0).contextBytes());
    }

    @Test
    void exporterReturnsDecryptedOwnMessages() {
        insertSealed(draft(3, 5, "e1"), "disa aktarilan");
        insertSealed(draft(3, 6, "e2"), "baskasinin");
        // Depo sahtesi: yalnizca sentBy kullanilir
        MessageRepository repo = org.mockito.Mockito.mock(MessageRepository.class);
        Message mine = draft(3, 5, "e1");
        var row = jdbc.queryForMap("SELECT id, body_ciphertext, body_nonce, key_version FROM message WHERE client_id = 'e1'");
        mine.setId(((Number) row.get("ID")).longValue());
        mine.setBodyCiphertext((byte[]) row.get("BODY_CIPHERTEXT"));
        mine.setBodyNonce((byte[]) row.get("BODY_NONCE"));
        mine.setKeyVersion(((Number) row.get("KEY_VERSION")).intValue());
        org.mockito.Mockito.when(repo.sentBy(org.mockito.ArgumentMatchers.eq(5L), org.mockito.ArgumentMatchers.any()))
                .thenReturn(java.util.List.of(mine));

        Object out = new MessageExporters().messageExporter(repo, codec).export(5L);

        assertTrue(out.toString().contains("disa aktarilan"));
        assertFalse(out.toString().contains("baskasinin"));
    }
}
