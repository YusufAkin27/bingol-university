package edu.bingol.backend.observability;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.List;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/**
 * Olu mail yeniden denemesi: degiskenleri silinmis (DEAD olurken temizlenir) ve suresi dolmus kod postalari
 * kuyruga alinmaz, acikca "skipped" olarak raporlanir. Kendi izole H2 veritabani (Spring baglami yok).
 */
class DeadLetterServiceTest {

    private JdbcTemplate jdbc;
    private DeadLetterService service;

    @BeforeEach
    void setUp() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:dlq" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE mail_outbox (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, template VARCHAR(40) NOT NULL, "
                + "to_address VARCHAR(254) DEFAULT 'a@bingol.edu.tr' NOT NULL, vars_json VARCHAR(4000) DEFAULT '{}' NOT NULL, "
                + "status VARCHAR(12) NOT NULL, attempts INT DEFAULT 5 NOT NULL, next_attempt_at TIMESTAMP, "
                + "last_error VARCHAR(500), created_at TIMESTAMP NOT NULL)");
        service = new DeadLetterService(new NamedParameterJdbcTemplate(ds));
    }

    private long insert(String template, String vars, String status, Instant created) {
        jdbc.update("INSERT INTO mail_outbox (template, vars_json, status, last_error, created_at) VALUES (?,?,?,?,?)",
                template, vars, status, "boom", java.sql.Timestamp.from(created));
        return jdbc.queryForObject("SELECT MAX(id) FROM mail_outbox", Long.class);
    }

    private String status(long id) {
        return jdbc.queryForObject("SELECT status FROM mail_outbox WHERE id = ?", String.class, id);
    }

    @Test
    void requeuesOnlyMailsWhoseContentCanBeRebuilt() {
        Instant now = Instant.now();
        long cleared = insert("ANNOUNCEMENT", "{}", "DEAD", now.minus(1, ChronoUnit.HOURS));
        long withVars = insert("ANNOUNCEMENT", "{\"title\":\"x\"}", "DEAD", now.minus(1, ChronoUnit.HOURS));
        long deleted = insert("ACCOUNT_DELETED", "{}", "DEAD", now.minus(1, ChronoUnit.HOURS));
        long staleCode = insert("VERIFICATION_CODE", "{\"code\":\"123456\"}", "DEAD", now.minus(1, ChronoUnit.HOURS));
        long freshCode = insert("PASSWORD_RESET_CODE", "{\"code\":\"123456\"}", "DEAD", now.minus(2, ChronoUnit.MINUTES));
        long live = insert("ANNOUNCEMENT", "{\"title\":\"x\"}", "SENT", now);

        DeadLetterService.MailRetryResult r = service.retryMail(List.of());

        assertThat(r.requeued()).isEqualTo(3);
        assertThat(r.skipped()).isEqualTo(2);
        assertThat(status(withVars)).isEqualTo("PENDING");
        assertThat(status(deleted)).isEqualTo("PENDING");
        assertThat(status(freshCode)).isEqualTo("PENDING");
        assertThat(status(cleared)).isEqualTo("DEAD");
        assertThat(status(staleCode)).isEqualTo("DEAD");
        assertThat(status(live)).isEqualTo("SENT");
        assertThat(jdbc.queryForObject("SELECT attempts FROM mail_outbox WHERE id = ?", Integer.class, withVars)).isZero();
    }

    @Test
    void explicitIdsOnlyTouchChosenRowsAndReportSkipped() {
        Instant old = Instant.now().minus(1, ChronoUnit.HOURS);
        long ok = insert("ANNOUNCEMENT", "{\"a\":\"b\"}", "DEAD", old);
        long cleared = insert("ANNOUNCEMENT", "{}", "DEAD", old);
        long other = insert("ANNOUNCEMENT", "{\"a\":\"b\"}", "DEAD", old);

        DeadLetterService.MailRetryResult r = service.retryMail(List.of(ok, cleared));

        assertThat(r).isEqualTo(new DeadLetterService.MailRetryResult(1, 1));
        assertThat(status(ok)).isEqualTo("PENDING");
        assertThat(status(cleared)).isEqualTo("DEAD");
        assertThat(status(other)).isEqualTo("DEAD");
    }
}
