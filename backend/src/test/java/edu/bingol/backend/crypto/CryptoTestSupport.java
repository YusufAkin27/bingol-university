package edu.bingol.backend.crypto;

import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import java.util.Base64;
import java.util.UUID;
import java.util.function.LongSupplier;
import org.springframework.core.env.StandardEnvironment;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/** Testlerde ortak kurulum: H2 uzerinde gercek JDBC deposu + gercek servisler. */
public final class CryptoTestSupport {

    public final JdbcTemplate jdbc;
    public final CryptoService crypto = new CryptoService();
    final SimpleMeterRegistry registry = new SimpleMeterRegistry();
    final CryptoMetrics metrics = new CryptoMetrics(registry);
    final JdbcConversationKeyStore store;

    public CryptoTestSupport() {
        DriverManagerDataSource ds = new DriverManagerDataSource(
                "jdbc:h2:mem:crypto" + UUID.randomUUID().toString().replace("-", "")
                        + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(ds);
        jdbc.execute("CREATE TABLE conversation_key (conversation_id BIGINT NOT NULL, key_version INT NOT NULL, "
                + "wrapped_key BYTEA NOT NULL, master_key_id VARCHAR(32) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE, "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (conversation_id, key_version))");
        jdbc.execute("CREATE TABLE message_access_audit (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                + "admin_id BIGINT NOT NULL, conversation_id BIGINT NOT NULL, message_count INT NOT NULL, "
                + "from_message_id BIGINT, to_message_id BIGINT, reason VARCHAR(500) NOT NULL, ip VARCHAR(64), "
                + "created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        store = new JdbcConversationKeyStore(jdbc);
    }

    public static String b64(int fill) {
        byte[] k = new byte[32];
        java.util.Arrays.fill(k, (byte) fill);
        return Base64.getEncoder().encodeToString(k);
    }

    static CryptoProperties props(String masterKeys, String active) {
        return new CryptoProperties(masterKeys, "", active, false, true, 300, 1024, 30, 200);
    }

    static CryptoProperties props(String masterKeys, String active, boolean adminEnabled, int maxMsgs) {
        return new CryptoProperties(masterKeys, "", active, false, adminEnabled, 300, 1024, 30, maxMsgs);
    }

    public static KeyProvider provider(String masterKeys, String active) {
        return new ConfiguredKeyProvider(props(masterKeys, active), new StandardEnvironment());
    }

    public ConversationKeyService keyService(KeyProvider kp) {
        return new ConversationKeyService(store, kp, crypto, metrics, props("", ""));
    }

    ConversationKeyService keyService(KeyProvider kp, LongSupplier clock, int ttlSeconds) {
        return new ConversationKeyService(store, kp, crypto, metrics,
                new CryptoProperties("", "", "", false, true, ttlSeconds, 1024, 30, 200), clock);
    }

    public EnvelopeMessageCipher cipher(ConversationKeyService ks) {
        return new EnvelopeMessageCipher(ks, crypto, metrics);
    }
}
