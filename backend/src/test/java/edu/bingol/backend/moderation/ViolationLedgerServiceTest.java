package edu.bingol.backend.moderation;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import edu.bingol.backend.common.ApiException;
import edu.bingol.backend.user.UserStatus;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

/** T-058: silinip ayni e-postayla yeniden kayit strike/yasak gecmisini sifirlayamaz; acik sikayetli hesap silme bekler. */
class ViolationLedgerServiceTest {

    private static final String EMAIL = "ali@bingol.edu.tr";

    private final ViolationLedgerRepository ledger = mock(ViolationLedgerRepository.class);
    private final ModerationStrikeRepository strikes = mock(ModerationStrikeRepository.class);
    private final StrikeService strikeService = mock(StrikeService.class);
    private final AccountDeleteHolds holds = mock(AccountDeleteHolds.class);
    private final AccountDeleteHoldRepository holdRepo = mock(AccountDeleteHoldRepository.class);
    private JdbcTemplate jdbc;
    private ViolationLedgerService service;
    private final List<ViolationLedger> saved = new ArrayList<>();

    @BeforeEach
    void setUp() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:vls;DB_CLOSE_DELAY=-1;MODE=PostgreSQL", "sa", ""));
        for (String ddl : List.of(
                "CREATE TABLE IF NOT EXISTS report (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, status VARCHAR(10), target_type VARCHAR(16), target_id BIGINT)",
                "CREATE TABLE IF NOT EXISTS post (id BIGINT PRIMARY KEY, author_id BIGINT)",
                "CREATE TABLE IF NOT EXISTS community_post (id BIGINT PRIMARY KEY, author_id BIGINT)",
                "CREATE TABLE IF NOT EXISTS user_event (id BIGINT PRIMARY KEY, created_by BIGINT)",
                "CREATE TABLE IF NOT EXISTS community (id BIGINT PRIMARY KEY, owner_id BIGINT)",
                "CREATE TABLE IF NOT EXISTS poll (id BIGINT PRIMARY KEY, created_by BIGINT)",
                "CREATE TABLE IF NOT EXISTS message (id BIGINT PRIMARY KEY, sender_id BIGINT)")) {
            jdbc.execute(ddl);
        }
        for (String t : List.of("report", "post", "community_post", "user_event", "community", "poll", "message")) {
            jdbc.update("DELETE FROM " + t);
        }
        service = new ViolationLedgerService(ledger, strikes, strikeService, holds, holdRepo, jdbc, "test-key", "jwt");
        when(ledger.save(any(ViolationLedger.class))).thenAnswer(i -> {
            ViolationLedger l = i.getArgument(0);
            saved.add(l);
            return l;
        });
    }

    @Test
    void digestIsStableCaseInsensitiveAndNotTheRawEmail() {
        String d = service.digest(EMAIL);
        assertEquals(64, d.length());
        assertEquals(d, service.digest("  ALI@bingol.edu.tr "));
        assertNotEquals(d, service.digest("veli@bingol.edu.tr"));
        assertFalse(d.contains("ali"));
        assertNotEquals(d, new ViolationLedgerService(ledger, strikes, strikeService, holds, holdRepo, jdbc, "baska", "jwt")
                .digest(EMAIL), "anahtar degisince ozet degisir (HMAC)");
    }

    @Test
    void deletionRecordsStrikeCountUnderDigest() {
        when(strikes.countByUserIdAndRevokedAtIsNullAndCreatedAtAfter(eq(7L), any(Instant.class))).thenReturn(2L);
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.empty());

        service.recordOnDeletion(7L, EMAIL, UserStatus.ACTIVE);

        assertEquals(1, saved.size());
        ViolationLedger l = saved.get(0);
        assertEquals(service.digest(EMAIL), l.getEmailDigest());
        assertEquals(2, l.getStrikeCount());
        assertFalse(l.isBanned());
        assertTrue(l.getExpiresAt().isAfter(Instant.now().plus(Duration.ofDays(360))), "12 ay saklama");
        verify(holds).clear(7L);
    }

    @Test
    void deletionOfCleanAccountLeavesNoLedgerRow() {
        when(strikes.countByUserIdAndRevokedAtIsNullAndCreatedAtAfter(eq(7L), any(Instant.class))).thenReturn(0L);
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.empty());

        service.recordOnDeletion(7L, EMAIL, UserStatus.ACTIVE);

        verify(ledger, never()).save(any());
    }

    @Test
    void suspendedAccountDeletionBansTheAddress() {
        when(strikes.countByUserIdAndRevokedAtIsNullAndCreatedAtAfter(eq(7L), any(Instant.class))).thenReturn(0L);
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.empty());

        service.recordOnDeletion(7L, EMAIL, UserStatus.SUSPENDED);

        assertTrue(saved.get(0).isBanned());
    }

    @Test
    void liveUserAccessBanAlsoBansTheAddress() {
        edu.bingol.backend.accessban.AccessBanRepository bans = mock(edu.bingol.backend.accessban.AccessBanRepository.class);
        when(bans.findLiveByValue(eq("USER"), eq("7"), any(Instant.class)))
                .thenReturn(Optional.of(new edu.bingol.backend.accessban.AccessBan()));
        service.setBans(bans);
        when(strikes.countByUserIdAndRevokedAtIsNullAndCreatedAtAfter(eq(7L), any(Instant.class))).thenReturn(0L);
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.empty());

        service.recordOnDeletion(7L, EMAIL, UserStatus.ACTIVE);

        assertTrue(saved.get(0).isBanned());
    }

    @Test
    void alreadyAnonymizedEmailIsSkipped() {
        service.recordOnDeletion(7L, "deleted-7@deleted.invalid", UserStatus.DELETED);
        verify(ledger, never()).save(any());
        verify(ledger, never()).findByEmailDigest(any());
    }

    @Test
    void reRegistrationInheritsStrikesAndConsumesTheRow() {
        ViolationLedger row = new ViolationLedger();
        row.setEmailDigest(service.digest(EMAIL));
        row.setStrikeCount(2);
        row.setExpiresAt(Instant.now().plus(Duration.ofDays(100)));
        when(ledger.findByEmailDigest(service.digest(EMAIL))).thenReturn(Optional.of(row));

        service.inheritOnRegister(42L, EMAIL);

        ArgumentCaptor<ModerationStrike> cap = ArgumentCaptor.forClass(ModerationStrike.class);
        verify(strikes, times(2)).save(cap.capture());
        for (ModerationStrike s : cap.getAllValues()) {
            assertEquals(42L, s.getUserId());
            assertTrue(s.isInherited());
            assertEquals(ReportTargetType.USER, s.getTargetType());
        }
        verify(ledger).delete(row);
        verify(strikeService).recommendIfNeeded(42L);
    }

    @Test
    void expiredLedgerRowIsIgnored() {
        ViolationLedger row = new ViolationLedger();
        row.setStrikeCount(3);
        row.setExpiresAt(Instant.now().minus(Duration.ofDays(1)));
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.of(row));

        service.inheritOnRegister(42L, EMAIL);

        verify(strikes, never()).save(any());
    }

    @Test
    void inheritedStrikeCountIsCapped() {
        ViolationLedger row = new ViolationLedger();
        row.setStrikeCount(500);
        row.setExpiresAt(Instant.now().plus(Duration.ofDays(5)));
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.of(row));

        service.inheritOnRegister(42L, EMAIL);

        verify(strikes, times(ViolationLedgerService.MAX_INHERIT)).save(any());
    }

    @Test
    void bannedAddressCannotRegisterButStrikeOnlyRowCan() {
        ViolationLedger banned = new ViolationLedger();
        banned.setBanned(true);
        banned.setExpiresAt(Instant.now().plus(Duration.ofDays(5)));
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.of(banned));
        ApiException e = assertThrows(ApiException.class, () -> service.requireNotBanned(EMAIL));
        assertEquals("ACCESS_BLOCKED", e.code());
        assertEquals(403, e.status().value());

        ViolationLedger strikeOnly = new ViolationLedger();
        strikeOnly.setStrikeCount(1);
        strikeOnly.setExpiresAt(Instant.now().plus(Duration.ofDays(5)));
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.of(strikeOnly));
        service.requireNotBanned(EMAIL);

        banned.setExpiresAt(Instant.now().minus(Duration.ofDays(1)));
        when(ledger.findByEmailDigest(any())).thenReturn(Optional.of(banned));
        service.requireNotBanned(EMAIL);

        when(ledger.findByEmailDigest(any())).thenReturn(Optional.empty());
        service.requireNotBanned(EMAIL);
    }

    // ---- silme bekletmesi ----

    @Test
    void deletionWithoutOpenReportsIsAllowed() {
        service.requireDeletionAllowed(7L);
        verify(holds).clear(7L);
        verify(holds, never()).ensure(anyLong(), org.mockito.ArgumentMatchers.anyInt());
    }

    @Test
    void openReportAboutUserOrOwnedContentHoldsDeletionSevenDays() {
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('OPEN', 'FEED_POST', 100)");
        jdbc.update("INSERT INTO post (id, author_id) VALUES (100, 7)");
        assertEquals(1, service.openReportsAbout(7L));

        Instant release = Instant.now().plus(Duration.ofDays(7));
        when(holdRepo.findById(7L)).thenReturn(Optional.empty());
        when(holds.ensure(7L, 7)).thenReturn(release);

        ApiException e = assertThrows(ApiException.class, () -> service.requireDeletionAllowed(7L));

        assertEquals("ACCOUNT_DELETE_ON_HOLD", e.code());
        assertEquals(409, e.status().value());
        verify(holds).ensure(7L, 7);
    }

    @Test
    void reportAboutSomeoneElsesContentDoesNotHold() {
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('OPEN', 'FEED_POST', 100)");
        jdbc.update("INSERT INTO post (id, author_id) VALUES (100, 8)");
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('RESOLVED', 'USER', 7)");
        assertEquals(0, service.openReportsAbout(7L));
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('OPEN', 'USER', 7)");
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('OPEN', 'POLL', 5)");
        jdbc.update("INSERT INTO poll (id, created_by) VALUES (5, 7)");
        assertEquals(2, service.openReportsAbout(7L));
    }

    @Test
    void holdExpiryAllowsDeletionEvenIfReportStillOpen() {
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('OPEN', 'USER', 7)");
        AccountDeleteHold h = new AccountDeleteHold();
        h.setUserId(7L);
        h.setReleaseAt(Instant.now().minus(Duration.ofHours(1)));
        when(holdRepo.findById(7L)).thenReturn(Optional.of(h));

        service.requireDeletionAllowed(7L); // bekleme doldu: hata yok

        verify(holds, never()).ensure(anyLong(), org.mockito.ArgumentMatchers.anyInt());
    }

    @Test
    void existingFutureHoldKeepsBlockingWithoutExtending() {
        jdbc.update("INSERT INTO report (status, target_type, target_id) VALUES ('OPEN', 'USER', 7)");
        AccountDeleteHold h = new AccountDeleteHold();
        h.setUserId(7L);
        h.setReleaseAt(Instant.now().plus(Duration.ofDays(3)));
        when(holdRepo.findById(7L)).thenReturn(Optional.of(h));

        ApiException e = assertThrows(ApiException.class, () -> service.requireDeletionAllowed(7L));

        assertEquals("ACCOUNT_DELETE_ON_HOLD", e.code());
        verify(holds, never()).ensure(anyLong(), org.mockito.ArgumentMatchers.anyInt());
    }
}
